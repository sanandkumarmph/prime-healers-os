    private function validateLinkedSaleReferences(Request $request, Customer $customer, array $saleItems, ?Sale $currentSale = null): void
    {
        foreach ($saleItems as $index => $line) {
            if (empty($line['asset_id'])) {
                continue;
            }

            $asset = Asset::query()
                ->where('organization_id', $this->orgId())
                ->findOrFail((int) $line['asset_id']);

            if ((int) $asset->product_id !== (int) $line['product_id']) {
                throw ValidationException::withMessages([
                    "sale_items.$index.asset_id" => ['Selected asset does not belong to the chosen product.'],
                ]);
            }

            if ($asset->asset_stage !== Asset::STAGE_NEW_STOCK) {
                throw ValidationException::withMessages([
                    "sale_items.$index.asset_id" => ['Only new stock assets can be linked to a sale.'],
                ]);
            }

            $isCurrentSaleAsset = $currentSale
                && ((int) $currentSale->asset_id === (int) $asset->id
                    || $currentSale->displaySaleItems()->pluck('asset_id')->contains((int) $asset->id)
                    || $currentSale->displaySaleItems()->pluck('asset_ids')->flatten()->contains((int) $asset->id));

            if ($asset->asset_status !== 'available_for_sale' && !$isCurrentSaleAsset) {
                throw ValidationException::withMessages([
                    "sale_items.$index.asset_id" => ['Selected asset is not available for sale.'],
                ]);
            }

            if ((int) $line['quantity'] !== 1) {
                throw ValidationException::withMessages([
                    "sale_items.$index.quantity" => ['Quantity must be 1 when a serialized asset is linked.'],
                ]);
            }
        }

        if ($request->filled('rental_id')) {
            $rental = Rental::query()
                ->where('organization_id', $this->orgId())
                ->findOrFail($request->integer('rental_id'));

            if ((int) $rental->customer_id !== (int) $customer->id) {
                throw ValidationException::withMessages([
                    'rental_id' => 'Linked rental must belong to the selected customer.',
                ]);
            }
        }
    }

    private function synchronizeLinkedRentalContext(Request $request): void
    {
        if (! $request->filled('rental_id')) {
            return;
        }

        $rental = Rental::query()
            ->where('organization_id', $this->orgId())
            ->find($request->integer('rental_id'));

        if (! $rental || ! $rental->customer_id) {
            return;
        }

        $request->merge([
            'customer_id' => $rental->customer_id,
        ]);
    }

    private function attachLinkedInvoiceIds($sales)
    {
        $saleIds = $sales->pluck('id')->filter()->map(fn ($id) => (int) $id)->values();

        if ($saleIds->isEmpty()) {
            return $sales;
        }

        $invoiceMap = Invoice::query()
            ->whereIn('id', (clone $this->saleInvoiceLookupQuery($saleIds->all()))->select('id'))
            ->with(['items' => function ($itemQuery) use ($saleIds) {
                $itemQuery
                    ->where('source_type', 'sale')
                    ->whereIn('source_id', $saleIds->all());
            }])
            ->orderByDesc('id')
            ->get()
            ->reduce(function ($carry, $invoice) {
                $directSaleId = $this->hasInvoiceSaleColumn()
                    ? (int) ($invoice->sale_id ?? 0)
                    : 0;

                if ($directSaleId > 0 && !isset($carry[$directSaleId])) {
                    $carry[$directSaleId] = (int) $invoice->id;
                }

                foreach ($invoice->items as $item) {
                    $saleId = (int) ($item->source_id ?? 0);

                    if ($saleId > 0 && !isset($carry[$saleId])) {
                        $carry[$saleId] = (int) $invoice->id;
                    }
                }

                return $carry;
            }, []);

        $sales->each(function ($sale) use ($invoiceMap) {
            $sale->setAttribute('linked_invoice_id', $invoiceMap[(int) $sale->id] ?? null);
        });

        return $sales;
    }

    private function salesReceivablesSnapshot($salesQuery): array
    {
