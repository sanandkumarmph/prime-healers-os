    public function store(Request $request)
    {
        $this->authorize('create', Sale::class);

        $this->synchronizeLinkedRentalContext($request);
        $request->validate($this->saleValidationRules());

        $customer = Customer::where('organization_id', $this->orgId())->findOrFail($request->customer_id);
        $product = Product::where('organization_id', $this->orgId())->findOrFail($request->product_id);
        $this->validateLinkedSaleReferences($request, $product, $customer);
        $commercials = $this->calculateSaleCommercials(
            (float) $request->quantity,
            (float) $request->unit_price,
            (float) ($request->discount_amount ?? 0),
            (float) ($request->shipping_charges ?? 0),
            (float) ($request->tax_percentage ?? 0),
            (string) ($request->tax_calculation_mode ?? 'exclusive')
        );

        $salePayload = [
            'customer_id' => $customer->id,
            'product_id' => $product->id,
            'asset_id' => $request->filled('asset_id') ? $request->integer('asset_id') : null,
            'rental_id' => $request->filled('rental_id') ? $request->integer('rental_id') : null,
            'quantity' => $request->quantity,
            'unit_price' => $request->unit_price,
            'discount_amount' => $request->discount_amount ?? 0,
            'shipping_charges' => $request->shipping_charges ?? 0,
            'tax_percentage' => $request->tax_percentage ?? 0,
            'tax_calculation_mode' => $request->tax_calculation_mode ?? 'exclusive',
            'sale_date' => $request->sale_date,
            'sale_amount' => $commercials['sale_amount'],
            'payment_status' => $request->payment_status,
            'notes' => $request->notes,
            'organization_id' => $this->orgId(),
        ];

        if ($this->hasCreatedByColumn()) {
            $salePayload['created_by'] = auth()->id();
        }

        if ($this->hasCreatedByUserColumn()) {
            $salePayload['created_by_user_id'] = auth()->id();
        }

        [$sale, $invoice] = DB::transaction(function () use ($salePayload) {
            $sale = Sale::create($salePayload);
            $this->applySaleStock($sale);
            $invoice = $this->createSaleInvoice($sale);

            return [$sale, $invoice];
        });

        ActivityLogger::log('sale.created', $sale, [
            'invoice_id' => $invoice->id,
            'invoice_number' => $invoice->invoice_number,
            'sale_amount' => $sale->sale_amount,
            'payment_status' => $sale->payment_status,
            'tax_calculation_mode' => $sale->tax_calculation_mode ?? null,
        ], 'Sale created and invoice generated.');

        return redirect()
            ->route('sales.index')
            ->with('success', 'Sale created successfully. Invoice ' . $invoice->invoice_number . ' was created automatically.');
    }

    public function importSaleFromPayload(array $attributes): array
    {
        $customer = Customer::where('organization_id', $this->orgId())->findOrFail((int) $attributes['customer_id']);
        $product = Product::where('organization_id', $this->orgId())->findOrFail((int) $attributes['product_id']);
        $match = $this->describeImportedSaleMatch(
            $this->importMatchSignatureService()->sale(
                $attributes,
                $customer->id,
                $product->id,
                max((int) ($attributes['quantity'] ?? 0), 1),
                $this->hasWarehouseColumn() && !empty($attributes['warehouse_id'])
                    ? (int) $attributes['warehouse_id']
                    : null
            )
        );

        if (($match['action'] ?? null) === 'review') {
            throw ValidationException::withMessages([
                'import' => [$match['message'] ?? 'This sales import row requires manual review.'],
            ]);
        }

        $commercials = $this->calculateSaleCommercials(
            (float) $attributes['quantity'],
            (float) $attributes['unit_price'],
            (float) ($attributes['discount_amount'] ?? 0),
            (float) ($attributes['shipping_charges'] ?? 0),
            (float) ($attributes['tax_percentage'] ?? 0),
            (string) ($attributes['tax_calculation_mode'] ?? 'exclusive')
        );

        $salePayload = [
            'customer_id' => $customer->id,
            'product_id' => $product->id,
            'asset_id' => $attributes['asset_id'] ?? null,
            'rental_id' => $attributes['rental_id'] ?? null,
            'quantity' => $attributes['quantity'],
            'unit_price' => $attributes['unit_price'],
            'discount_amount' => $attributes['discount_amount'] ?? 0,
            'shipping_charges' => $attributes['shipping_charges'] ?? 0,
            'tax_percentage' => $attributes['tax_percentage'] ?? 0,
            'tax_calculation_mode' => $attributes['tax_calculation_mode'] ?? 'exclusive',
            'sale_date' => $attributes['sale_date'],
            'sale_amount' => $commercials['sale_amount'],
            'payment_status' => in_array(($attributes['payment_status'] ?? 'pending'), ['paid', 'partial'], true)
                ? 'pending'
                : ($attributes['payment_status'] ?? 'pending'),
            'notes' => $attributes['notes'] ?? null,
            'organization_id' => $this->orgId(),
        ];

        if ($this->hasWarehouseColumn() && !empty($attributes['warehouse_id'])) {
            $salePayload['warehouse_id'] = (int) $attributes['warehouse_id'];
        }

        if ($this->hasCreatedByColumn()) {
            $salePayload['created_by'] = auth()->id();
        }

        if ($this->hasCreatedByUserColumn()) {
            $salePayload['created_by_user_id'] = auth()->id();
        }

        if ($existingSale = ($match['sale'] ?? null)) {
            [$sale, $invoice, $delivery] = $this->updateImportedSaleFromPayload($existingSale, $salePayload, $attributes);
            $action = 'updated';
        } else {
            [$sale, $invoice, $delivery] = $this->createImportedSaleFromPayload($salePayload, $attributes);
            $action = 'created';
        }

        try {
            ActivityLogger::log('sale.imported', $sale, [
                'invoice_id' => $invoice?->id,
                'invoice_number' => $invoice?->invoice_number,
                'delivery_id' => $delivery?->id,
                'sale_amount' => $sale->sale_amount,
                'payment_status' => $sale->payment_status,
                'import_action' => $action,
            ], 'Sale imported via sales import preview.');
        } catch (\Throwable) {
            // Keep import success independent from optional activity logging.
        }

        return [
            'sale' => $sale,
            'invoice' => $invoice,
            'delivery' => $delivery,
            'action' => $action,
        ];
    }

    public function describeImportedSaleMatch(array $attributes): array
    {
        $customerId = (int) ($attributes['customer_id'] ?? 0);
        $productId = (int) ($attributes['product_id'] ?? 0);
        $quantity = max((int) ($attributes['quantity'] ?? 0), 1);
        $saleDate = $attributes['sale_date'] ?? null;
        $warehouseId = !empty($attributes['warehouse_id']) ? (int) $attributes['warehouse_id'] : null;

        if ($customerId <= 0 || $productId <= 0 || blank($saleDate)) {
            return ['action' => 'create', 'sale' => null, 'message' => null];
        }

        $candidates = Sale::query()
            ->where('organization_id', $this->orgId())
            ->where('customer_id', $customerId)
            ->where('product_id', $productId)
            ->whereDate('sale_date', $saleDate)
            ->where('quantity', $quantity)
            ->when($this->hasWarehouseColumn() && $warehouseId, fn ($query) => $query->where('warehouse_id', $warehouseId))
            ->with(['invoice.payments'])
            ->get();

        if ($candidates->isEmpty()) {
            return ['action' => 'create', 'sale' => null, 'message' => null];
        }

        if ($candidates->count() > 1) {
            return [
                'action' => 'review',
                'sale' => null,
                'message' => 'Multiple sales match this import row. Add a unique external reference or review manually.',
            ];
        }

        $sale = $candidates->first();
        $invoice = $sale?->invoice ?? $this->saleInvoice($sale);
        $paymentReview = $invoice ? $this->importedSalePaymentReviewMessage($sale, $invoice, $attributes) : null;

        if ($paymentReview) {
            return [
                'action' => 'review',
                'sale' => $sale,
                'message' => $paymentReview,
            ];
        }

        return ['action' => 'update', 'sale' => $sale, 'message' => null];
    }

