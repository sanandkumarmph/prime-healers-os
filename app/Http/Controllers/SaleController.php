    private function paymentsRentalIdIsNullable(): bool
    {
        static $isNullable = null;

        if ($isNullable !== null) {
            return $isNullable;
        }

        if (DB::connection()->getDriverName() === 'sqlite') {
            $columns = DB::select("PRAGMA table_info('payments')");

            foreach ($columns as $column) {
                if (($column->name ?? null) === 'rental_id') {
                    return $isNullable = ((int) ($column->notnull ?? 1)) === 0;
                }
            }

            return $isNullable = true;
        }

        $column = DB::table('information_schema.columns')
            ->select('is_nullable')
            ->where('table_schema', DB::raw('schema()'))
            ->where('table_name', 'payments')
            ->where('column_name', 'rental_id')
            ->first();

        return $isNullable = strtoupper((string) ($column->is_nullable ?? 'NO')) === 'YES';
    }

    private function applySalesScope($query)
    {
        $user = auth()->user();

        if (!$user || !$user->hasScope('self_created', 'sales')) {
            return $query;
        }

        if ($this->hasCreatedByUserColumn()) {
            return $query->where('created_by_user_id', $user->id);
        }

        if ($this->hasCreatedByColumn()) {
            return $query->where('created_by', $user->id);
        }

        return $query;
    }

    private function scopedSale(Sale $sale): Sale
    {
        abort_if($sale->organization_id !== $this->orgId(), 403);

        $user = auth()->user();

        if ($user && $user->hasScope('self_created', 'sales')) {
            $owned = true;

            if ($this->hasCreatedByUserColumn()) {
                $owned = (int) $sale->created_by_user_id === (int) $user->id;
            } elseif ($this->hasCreatedByColumn()) {
                $owned = (int) $sale->created_by === (int) $user->id;
            }

            abort_if(!$owned, 403);
        }

        return $sale;
    }

    private function applyDateRangeFilter($query, string $fromDate, string $toDate)
    {
        if ($fromDate !== '') {
            $query->whereDate('sale_date', '>=', $fromDate);
        }

        if ($toDate !== '') {
            $query->whereDate('sale_date', '<=', $toDate);
        }

        return $query;
    }

    private function applySorting($query, string $sortBy)
    {
        return match ($sortBy) {
            'oldest' => $query->orderBy('sale_date')->orderBy('id'),
            'priority' => $query->orderByRaw("CASE WHEN payment_status IN ('pending', 'partial') THEN 0 ELSE 1 END")
                ->orderByDesc('sale_amount')
                ->orderByDesc('sale_date'),
            'amount_desc' => $query->orderByDesc('sale_amount')->orderByDesc('sale_date'),
            'amount_asc' => $query->orderBy('sale_amount')->orderByDesc('sale_date'),
            'customer_asc' => $query->leftJoin('customers', 'sales.customer_id', '=', 'customers.id')
                ->select('sales.*')
                ->orderBy('customers.name')
                ->orderByDesc('sales.sale_date'),
            'customer_desc' => $query->leftJoin('customers', 'sales.customer_id', '=', 'customers.id')
                ->select('sales.*')
                ->orderByDesc('customers.name')
                ->orderByDesc('sales.sale_date'),
            default => $query->orderByDesc('sale_date')->orderByDesc('id'),
        };
    }

