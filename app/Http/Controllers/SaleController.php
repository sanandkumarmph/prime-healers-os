    private function productTaxPercentage(Product $product): float
    {
        return match ($product->gst_tax_type) {
            Product::GST_TAX_TYPE_CGST_SGST => round((float) ($product->cgst_rate ?? 0) + (float) ($product->sgst_rate ?? 0), 2),
            Product::GST_TAX_TYPE_IGST => round((float) ($product->igst_rate ?? 0), 2),
            default => 0.0,
        };
    }

    private function calculateSaleCommercials(
        float $quantity,
        float $unitPrice,
        float $discountAmount,
        float $shippingCharges,
        float $taxPercentage,
        string $taxCalculationMode
    ): array {
        $quantity = max($quantity, 1);
        $unitPrice = max($unitPrice, 0);
        $discountAmount = max($discountAmount, 0);
        $shippingCharges = max($shippingCharges, 0);
        $taxPercentage = max($taxPercentage, 0);
        $taxCalculationMode = $taxCalculationMode === 'inclusive' ? 'inclusive' : 'exclusive';

        $subtotal = round($quantity * $unitPrice, 2);
        $taxableBase = max($subtotal - $discountAmount, 0);

        if ($taxCalculationMode === 'inclusive' && $taxPercentage > 0) {
            $taxableAmount = round($taxableBase / (1 + ($taxPercentage / 100)), 2);
            $totalTaxAmount = round($taxableBase - $taxableAmount, 2);
        } else {
            $taxableAmount = $taxableBase;
            $totalTaxAmount = round(($taxableAmount * $taxPercentage) / 100, 2);
        }

        $saleAmount = round($taxableBase + ($taxCalculationMode === 'exclusive' ? $totalTaxAmount : 0) + $shippingCharges, 2);

        return [
            'subtotal' => $subtotal,
            'discount_amount' => $discountAmount,
            'shipping_charges' => $shippingCharges,
            'taxable_amount' => $taxableAmount,
            'total_tax_amount' => $totalTaxAmount,
            'sale_amount' => $saleAmount,
        ];
    }

    private function normalizedSaleItems(Request $request, ?Sale $sale = null): array
    {
        $requestedItems = collect($request->input('sale_items', []))
            ->map(fn ($row) => is_array($row) ? $row : [])
            ->values();

        $rows = $requestedItems
            ->filter(function (array $row): bool {
                return collect([
                    $row['product_id'] ?? null,
                    $row['asset_id'] ?? null,
                    $row['warehouse_id'] ?? null,
                    $row['quantity'] ?? null,
                    $row['unit_price'] ?? null,
                    $row['discount_amount'] ?? null,
                    $row['shipping_charges'] ?? null,
                    $row['tax_percentage'] ?? null,
                    $row['notes'] ?? null,
                ])->contains(fn ($value) => filled($value) && $value !== '0' && $value !== 0 && $value !== '0.00');
            })
            ->values();

        if ($rows->isEmpty() && $request->filled('product_id')) {
            $rows = collect([[
                'product_id' => $request->input('product_id'),
                'asset_id' => $request->input('asset_id'),
                'warehouse_id' => $request->input('warehouse_id'),
                'quantity' => $request->input('quantity'),
                'unit_price' => $request->input('unit_price'),
                'discount_amount' => $request->input('discount_amount'),
                'shipping_charges' => $request->input('shipping_charges'),
                'tax_percentage' => $request->input('tax_percentage'),
                'tax_calculation_mode' => $request->input('tax_calculation_mode'),
                'notes' => $request->input('notes'),
            ]]);
        }

        if ($rows->isEmpty()) {
            throw ValidationException::withMessages([
                'sale_items' => ['Add at least one product line before saving the sale.'],
            ]);
        }

        $productIds = $rows->pluck('product_id')
            ->filter(fn ($id) => filled($id))
            ->map(fn ($id) => (int) $id)
            ->unique()
            ->values();

        $products = Product::query()
            ->where('organization_id', $this->orgId())
            ->whereIn('id', $productIds)
            ->get()
            ->keyBy('id');

        return $rows->map(function (array $row, int $index) use ($products) {
            $productId = (int) ($row['product_id'] ?? 0);
            $product = $products->get($productId);

            if (!$product) {
                throw ValidationException::withMessages([
                    "sale_items.$index.product_id" => ['Select a valid product for this line.'],
                ]);
            }

            if (!$product->canSell()) {
                throw ValidationException::withMessages([
                    "sale_items.$index.product_id" => [$product->name . ' is not available for sale.'],
                ]);
            }

            $quantity = max((int) ($row['quantity'] ?? 0), 0);
            $unitPrice = round((float) ($row['unit_price'] ?? 0), 2);
            $discountAmount = round((float) ($row['discount_amount'] ?? 0), 2);
            $shippingCharges = round((float) ($row['shipping_charges'] ?? 0), 2);
            $taxCalculationMode = (($row['tax_calculation_mode'] ?? '') === 'inclusive')
                ? 'inclusive'
                : (($product->gst_calculation_mode ?? 'exclusive') === 'inclusive' ? 'inclusive' : 'exclusive');
            $taxPercentage = filled($row['tax_percentage'] ?? null)
                ? round((float) ($row['tax_percentage'] ?? 0), 2)
                : $this->productTaxPercentage($product);

            if ($quantity < 1) {
                throw ValidationException::withMessages([
                    "sale_items.$index.quantity" => ['Quantity must be greater than 0.'],
                ]);
            }

            foreach ([
                'unit_price' => $unitPrice,
                'discount_amount' => $discountAmount,
                'shipping_charges' => $shippingCharges,
                'tax_percentage' => $taxPercentage,
            ] as $field => $value) {
                if ($value < 0) {
                    throw ValidationException::withMessages([
                        "sale_items.$index.$field" => [ucfirst(str_replace('_', ' ', $field)) . ' cannot be negative.'],
                    ]);
                }
            }

            $commercials = $this->calculateSaleCommercials(
                (float) $quantity,
                $unitPrice,
                $discountAmount,
                $shippingCharges,
                $taxPercentage,
                $taxCalculationMode
            );

            return [
                'product_id' => $product->id,
                'asset_id' => filled($row['asset_id'] ?? null) ? (int) $row['asset_id'] : null,
                'warehouse_id' => filled($row['warehouse_id'] ?? null) ? (int) $row['warehouse_id'] : null,
                'quantity' => $quantity,
                'unit_price' => $unitPrice,
                'discount_amount' => $discountAmount,
                'shipping_charges' => $shippingCharges,
                'tax_percentage' => $taxPercentage,
                'tax_calculation_mode' => $taxCalculationMode,
                'notes' => filled($row['notes'] ?? null) ? trim((string) $row['notes']) : null,
                'commercials' => $commercials,
                'product' => $product,
            ];
        })->all();
    }

    private function aggregateSaleCommercials(array $saleItems): array
    {
        return [
            'subtotal' => round((float) collect($saleItems)->sum(fn (array $line) => (float) ($line['commercials']['subtotal'] ?? 0)), 2),
            'discount_amount' => round((float) collect($saleItems)->sum(fn (array $line) => (float) ($line['discount_amount'] ?? 0)), 2),
            'shipping_charges' => round((float) collect($saleItems)->sum(fn (array $line) => (float) ($line['shipping_charges'] ?? 0)), 2),
            'taxable_amount' => round((float) collect($saleItems)->sum(fn (array $line) => (float) ($line['commercials']['taxable_amount'] ?? 0)), 2),
            'total_tax_amount' => round((float) collect($saleItems)->sum(fn (array $line) => (float) ($line['commercials']['total_tax_amount'] ?? 0)), 2),
            'sale_amount' => round((float) collect($saleItems)->sum(fn (array $line) => (float) ($line['commercials']['sale_amount'] ?? 0)), 2),
            'quantity' => (int) collect($saleItems)->sum(fn (array $line) => (int) ($line['quantity'] ?? 0)),
        ];
    }

