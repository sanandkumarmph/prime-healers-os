    private function resolveSaleInventory(Product $product, int $quantity, ?int $warehouseId = null, bool $restore = false): ?SaleInventory
    {
        $inventoryQuery = SaleInventory::query()
            ->where('organization_id', $this->orgId())
            ->where('product_id', $product->id);

        if ($warehouseId) {
            return (clone $inventoryQuery)
                ->where('warehouse_id', $warehouseId)
                ->lockForUpdate()
                ->first();
        }

        $inventories = (clone $inventoryQuery)
            ->orderBy('id')
            ->lockForUpdate()
            ->get();

        if ($inventories->isEmpty()) {
            return null;
        }

        if ($restore) {
            return $inventories->first();
        }

        return $inventories->first(fn ($inventory) => $inventory->availableToSell() >= $quantity);
    }

