            'has_delivery_assignment_type_column' => Schema::hasColumn('deliveries', 'assignment_type'),
            'import_field_was_provided' => fn (array $row, string $field) => $this->importFieldWasProvided($row, $field),
            'managed_imported_payment_query' => fn (Invoice $invoice, int $saleId) => $this->managedImportedSalePaymentQuery($invoice, $saleId),
            'imported_payment_note' => fn (int $saleId) => $this->importedSalePaymentNote($saleId),
            'create_invoice_payment' => fn (Sale $saleRecord, Invoice $invoice, array $payload) => $this->createInvoicePaymentForSale($saleRecord, $invoice, $payload),
            'sync_sale_payment_status_from_invoice' => fn (Sale $saleRecord, Invoice $invoice) => $this->syncSalePaymentStatusFromInvoice($saleRecord, $invoice),
            'has_warehouse_column' => $this->hasWarehouseColumn(),
            'sale_invoice' => fn (Sale $saleRecord) => $this->saleInvoice($saleRecord),
            'create_sale_invoice' => fn (Sale $saleRecord) => $this->createSaleInvoice($saleRecord),
            'sync_sale_invoice_from_sale' => fn (Sale $saleRecord, Invoice $invoice) => $this->syncSaleInvoiceFromSale($saleRecord, $invoice),
        ]);
    }

    private function shouldCreateImportedSaleInvoice(array $attributes): bool
    {
        return $this->saleImportExecutor()->shouldCreateImportedSaleInvoice($attributes);
    }

    private function applyImportedSalePaymentState(Sale $sale, Invoice $invoice, array $attributes): void
    {
        $this->saleImportExecutor()->applyImportedSalePaymentState($sale, $invoice, $attributes, [
            'import_field_was_provided' => fn (array $row, string $field) => $this->importFieldWasProvided($row, $field),
            'managed_imported_payment_query' => fn (Invoice $linkedInvoice, int $saleId) => $this->managedImportedSalePaymentQuery($linkedInvoice, $saleId),
            'imported_payment_note' => fn (int $saleId) => $this->importedSalePaymentNote($saleId),
            'create_invoice_payment' => fn (Sale $saleRecord, Invoice $linkedInvoice, array $payload) => $this->createInvoicePaymentForSale($saleRecord, $linkedInvoice, $payload),
            'sync_sale_payment_status_from_invoice' => fn (Sale $saleRecord, Invoice $linkedInvoice) => $this->syncSalePaymentStatusFromInvoice($saleRecord, $linkedInvoice),
        ]);
    }

    private function applyImportedSaleDeliveryState(Sale $sale, array $attributes, bool $isUpdate = false): ?Delivery
    {
        return $this->saleImportExecutor()->applyImportedSaleDeliveryState(
            $sale,
            $attributes,
            $isUpdate,
            $this->orgId(),
            $this->hasDeliverySaleColumn(),
            Schema::hasColumn('deliveries', 'assignment_type')
        );
    }

    private function managedImportedSalePaymentQuery(Invoice $invoice, int $saleId)
    {
        return Payment::query()
            ->where('organization_id', $this->orgId())
            ->where('invoice_id', $invoice->id)
            ->where('notes', $this->importedSalePaymentNote($saleId));
    }

    private function importedSalePaymentNote(int $saleId): string
    {
        return 'Imported payment sync for sale #'.$saleId.'.';
    }

    private function importedSalePaymentReviewMessage(Sale $sale, Invoice $invoice, array $attributes): ?string
    {
        $statusProvided = $this->importFieldWasProvided($attributes, 'payment_status');
        $paidAmountProvided = $this->importFieldWasProvided($attributes, 'paid_amount');

        if (!$statusProvided && !$paidAmountProvided) {
            return null;
        }

        $paymentStatus = strtolower(trim((string) ($attributes['payment_status'] ?? 'pending')));
        $requestedPaidAmount = match ($paymentStatus) {
            'paid' => round((float) ($attributes['sale_amount'] ?? $sale->sale_amount), 2),
            'partial' => round((float) ($attributes['paid_amount'] ?? 0), 2),
            default => 0.0,
        };

        $managedPayment = $this->managedImportedSalePaymentQuery($invoice, $sale->id)->first();
        $historicalPaymentsTotal = (float) $invoice->payments()
            ->when($managedPayment, fn ($query) => $query->whereKeyNot($managedPayment->id))
            ->sum('amount');

        if ($requestedPaidAmount + 0.01 < $historicalPaymentsTotal) {
            return 'Existing recorded payments exceed the imported payment state for this sale. Review this row manually.';
        }

        return null;
    }

    private function importFieldWasProvided(array $attributes, string $field): bool
    {
        return (bool) ($attributes[$field.'_provided'] ?? false);
    }

    public function edit(Sale $sale)
    {
        $sale = $this->scopedSale($sale);
        $this->authorize('update', $sale);

        if ($this->isAutoGeneratedRentalSale($sale)) {
            return $this->managedRentalSaleRedirect($sale);
        }

        $customers = Customer::where('organization_id', $this->orgId())->orderBy('name')->get();
        $products = Product::where('organization_id', $this->orgId())->orderBy('name')->get();
        $assets = Asset::query()
            ->with(['product', 'warehouse'])
            ->where('organization_id', $this->orgId())
            ->where('asset_stage', Asset::STAGE_NEW_STOCK)
            ->where(function ($query) use ($sale) {
                $query->where('asset_status', 'available_for_sale');

                if ($sale->asset_id) {
                    $query->orWhere('id', $sale->asset_id);
                }
            })
            ->orderBy('serial_number')
            ->get();
        $rentals = Rental::query()
            ->with(['customer', 'product'])
            ->where('organization_id', $this->orgId())
            ->latest('id')
            ->get();

        return view('sales.edit', compact('sale', 'customers', 'products', 'assets', 'rentals'));
    }

    public function update(Request $request, Sale $sale)
    {
        $sale = $this->scopedSale($sale);
        $this->authorize('update', $sale);

        if ($this->isAutoGeneratedRentalSale($sale)) {
            return $this->managedRentalSaleRedirect($sale);
        }

        $this->synchronizeLinkedRentalContext($request);
        $request->validate($this->saleValidationRules($sale));

        $customer = Customer::where('organization_id', $this->orgId())->findOrFail($request->customer_id);
        $product = Product::where('organization_id', $this->orgId())->findOrFail($request->product_id);
        $this->validateLinkedSaleReferences($request, $product, $customer, $sale);
        $commercials = $this->calculateSaleCommercials(
            (float) $request->quantity,
            (float) $request->unit_price,
            (float) ($request->discount_amount ?? 0),
            (float) ($request->shipping_charges ?? 0),
            (float) ($request->tax_percentage ?? 0),
            (string) ($request->tax_calculation_mode ?? 'exclusive')
        );

        $linkedInvoice = $this->saleInvoice($sale->loadMissing(['customer', 'product']));
        if ($linkedInvoice) {
            app(AmountReductionGuardService::class)->assertTotalNotBelowReceivedPayments(
                $linkedInvoice,
                (float) ($commercials['sale_amount'] ?? 0),
                'This sale update'
            );
        }

        DB::transaction(function () use ($sale, $customer, $product, $request, $commercials) {
            $originalSale = Sale::query()
                ->with(['product', 'asset'])
                ->where('organization_id', $this->orgId())
                ->findOrFail($sale->id);

            if ($this->saleUsesAppliedStock($originalSale)) {
                $this->restoreSaleStock($originalSale);
            }

            $sale->update([
                'customer_id' => $customer->id,
                'product_id' => $product->id,
                'asset_id' => $request->filled('asset_id') ? $request->integer('asset_id') : null,
                'rental_id' => $request->filled('rental_id') ? $request->integer('rental_id') : null,
                'quantity' => $request->quantity,
                'unit_price' => $request->unit_price,
                'discount_amount' => $request->discount_amount ?? 0,
                'shipping_charges' => $request->shipping_charges ?? 0,
                'tax_percentage' => $request->tax_percentage ?? 0,
                'tax_calculation_mode' => $request->tax_calculation_mode ?? 'exclusive',
                'sale_date' => $request->sale_date,
                'sale_amount' => $commercials['sale_amount'],
                'payment_status' => $request->payment_status,
                'notes' => $request->notes,
            ]);

            if ($sale->payment_status !== 'void') {
                $this->applySaleStock($sale->fresh(['product', 'asset']));
            } elseif ($this->hasStockAppliedColumn()) {
                $sale->forceFill(['stock_applied' => false])->saveQuietly();
            }

            if ($invoice = $this->saleInvoice($sale->refresh())) {
                $this->syncSaleInvoiceFromSale($sale, $invoice);
                $this->syncExistingSaleInvoicePayment($sale, $invoice);
            }
        });

        ActivityLogger::log('sale.updated', $sale->refresh(), [
            'sale_amount' => $sale->sale_amount,
            'payment_status' => $sale->payment_status,
            'tax_calculation_mode' => $sale->tax_calculation_mode ?? null,
        ], 'Sale updated.');

        return redirect()->route('sales.index')->with('success', 'Sale updated successfully.');
    }

