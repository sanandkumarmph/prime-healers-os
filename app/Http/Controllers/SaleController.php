            ActivityLogger::log('sale.marked_paid', $sale, [
                'invoice_id' => $invoice->id,
                'payment_id' => $payment->id,
                'payment_amount' => $payment->amount,
            ], 'Sale marked as paid from the sale page.');
        });

        return redirect()->route('sales.show', $sale)->with('success', 'Sale marked as paid.');
    }

    public function recordPayment(Request $request, Sale $sale)
    {
        $sale = $this->scopedSale($sale);
        $validated = $this->validateQuickPayment($request);
        $invoice = $this->createSaleInvoice($sale);

        DB::transaction(function () use ($sale, $invoice, $validated) {
            $payment = $this->createInvoicePaymentForSale($sale, $invoice, $validated);
            $this->syncSalePaymentStatusFromInvoice($sale->refresh(), $invoice->refresh());

            ActivityLogger::log('sale.partial_payment_recorded', $sale, [
                'invoice_id' => $invoice->id,
                'payment_id' => $payment->id,
                'payment_amount' => $payment->amount,
                'payment_method' => $payment->payment_method,
            ], 'Sale payment recorded from the sale page.');
        });

        return redirect()->route('sales.show', $sale)->with('success', 'Sale payment recorded successfully.');
    }

    public function destroy(Sale $sale)
    {
        $sale = $this->scopedSale($sale);
        $this->authorize('delete', $sale);

        if ($this->isAutoGeneratedRentalSale($sale)) {
            return $this->managedRentalSaleRedirect($sale);
        }

        DB::transaction(function () use ($sale) {
            $sale->loadMissing(['product', 'asset']);

            if ($this->saleUsesAppliedStock($sale)) {
                $this->restoreSaleStock($sale);
            }

            $sale->delete();
        });

        return redirect()->route('sales.index')->with('success', 'Sale deleted successfully.');
    }

    public function voidSale(Sale $sale)
    {
        $sale = $this->scopedSale($sale);

        if ($this->isAutoGeneratedRentalSale($sale)) {
            return $this->managedRentalSaleRedirect($sale);
        }

        if ($sale->payment_status === 'void') {
            return redirect()->route('sales.show', $sale)->with('error', 'This sale is already voided.');
        }

        DB::transaction(function () use ($sale) {
            if ($this->saleUsesAppliedStock($sale->loadMissing(['product', 'asset']))) {
                $this->restoreSaleStock($sale);
            }

            $invoice = $this->saleInvoice($sale);

            if ($invoice) {
                $this->autoPaidSalePaymentQuery($sale, $invoice)->delete();
                $invoice->forceFill([
                    'status' => 'cancelled',
                    'payment_status' => 'cancelled',
                    'paid_amount' => (float) $invoice->payments()->sum('amount'),
                    'balance_amount' => 0,
                ])->save();
            }

            $sale->update([
                'payment_status' => 'void',
                'notes' => trim(($sale->notes ? $sale->notes . ' | ' : '') . 'Sale voided.'),
            ]);

            if ($this->hasStockAppliedColumn()) {
                $sale->forceFill(['stock_applied' => false])->saveQuietly();
            }
        });

        ActivityLogger::log('sale.voided', $sale->refresh(), [
            'payment_status' => $sale->payment_status,
        ], 'Sale voided.');

        return redirect()->route('sales.show', $sale)->with('success', 'Sale voided successfully.');
    }
