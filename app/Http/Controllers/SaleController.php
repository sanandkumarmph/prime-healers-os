    private function importedSalePaymentReviewMessage(Sale $sale, Invoice $invoice, array $attributes): ?string
    {
        $statusProvided = $this->importFieldWasProvided($attributes, 'payment_status');
        $paidAmountProvided = $this->importFieldWasProvided($attributes, 'paid_amount');

        if (!$statusProvided && !$paidAmountProvided) {
            return null;
        }

        $paymentStatus = strtolower(trim((string) ($attributes['payment_status'] ?? 'pending')));
        $requestedPaidAmount = match ($paymentStatus) {
            'paid' => round((float) ($attributes['sale_amount'] ?? $sale->sale_amount), 2),
            'partial' => round((float) ($attributes['paid_amount'] ?? 0), 2),
            default => 0.0,
        };

        $managedPayment = $this->managedImportedSalePaymentQuery($invoice, $sale->id)->first();
        $historicalPaymentsTotal = (float) $invoice->payments()
            ->when($managedPayment, fn ($query) => $query->whereKeyNot($managedPayment->id))
            ->sum('amount');

        if ($requestedPaidAmount + 0.01 < $historicalPaymentsTotal) {
            return 'Existing recorded payments exceed the imported payment state for this sale. Review this row manually.';
        }

        return null;
    }

    private function importFieldWasProvided(array $attributes, string $field): bool
    {
        return (bool) ($attributes[$field.'_provided'] ?? false);
    }

    public function edit(Sale $sale)
    {
        $sale = $this->scopedSale($sale);
        $this->authorize('update', $sale);

        if ($this->isAutoGeneratedRentalSale($sale)) {
            return $this->managedRentalSaleRedirect($sale);
        }

        $currentSaleAssetIds = $this->hasSaleItemsTable()
            ? $sale->displaySaleItems()
                ->pluck('asset_ids')
                ->flatten()
                ->merge($sale->displaySaleItems()->pluck('asset_id'))
                ->filter()
                ->map(fn ($assetId) => (int) $assetId)
                ->unique()
                ->values()
                ->all()
            : [];
        $currentSaleProductIds = $this->hasSaleItemsTable()
            ? $sale->displaySaleItems()
                ->pluck('product_id')
                ->filter()
                ->map(fn ($productId) => (int) $productId)
                ->unique()
                ->values()
                ->all()
            : [(int) $sale->product_id];

        $customers = Customer::where('organization_id', $this->orgId())->orderBy('name')->get();
        $products = Product::where('organization_id', $this->orgId())
            ->orderBy('name')
            ->get()
            ->filter(function (Product $product) use ($currentSaleProductIds) {
                return $product->canSell() || in_array((int) $product->id, $currentSaleProductIds, true);
            })
            ->values();
        $assets = Asset::query()
            ->with(['product', 'warehouse'])
            ->where('organization_id', $this->orgId())
            ->where('asset_stage', Asset::STAGE_NEW_STOCK)
            ->where(function ($query) use ($sale, $currentSaleAssetIds) {
                $query->where('asset_status', 'available_for_sale');

                if ($sale->asset_id) {
                    $query->orWhere('id', $sale->asset_id);
                }

                if (!empty($currentSaleAssetIds)) {
                    $query->orWhereIn('id', $currentSaleAssetIds);
                }
            })
            ->orderBy('serial_number')
            ->get();
        $rentals = Rental::query()
            ->with(['customer', 'product'])
            ->where('organization_id', $this->orgId())
            ->latest('id')
            ->get();

        if ($this->hasSaleItemsTable()) {
            $sale->loadMissing(['saleItems.product', 'saleItems.asset.warehouse', 'saleItems.warehouse']);
        }

        return view('sales.edit', compact('sale', 'customers', 'products', 'assets', 'rentals'));
    }

    public function update(Request $request, Sale $sale)
    {
        $sale = $this->scopedSale($sale);
        $this->authorize('update', $sale);

        if ($this->isAutoGeneratedRentalSale($sale)) {
            return $this->managedRentalSaleRedirect($sale);
        }

        $this->synchronizeLinkedRentalContext($request);
        $request->validate($this->saleValidationRules($sale));
        $saleItems = $this->normalizedSaleItems($request, $sale);

        $customer = Customer::where('organization_id', $this->orgId())->findOrFail($request->customer_id);
        $this->validateLinkedSaleReferences($request, $customer, $saleItems, $sale);
        $commercials = $this->aggregateSaleCommercials($saleItems);

        $linkedInvoice = $this->saleInvoice($sale->loadMissing(['customer', 'product']));
        if ($linkedInvoice) {
            app(AmountReductionGuardService::class)->assertTotalNotBelowReceivedPayments(
                $linkedInvoice,
                (float) ($commercials['sale_amount'] ?? 0),
                'This sale update'
            );
        }

        DB::transaction(function () use ($sale, $customer, $request, $commercials, $saleItems) {
            $originalSale = Sale::query()
                ->with(['product', 'asset', 'saleItems.product', 'saleItems.asset'])
                ->where('organization_id', $this->orgId())
                ->findOrFail($sale->id);

            if ($this->saleUsesAppliedStock($originalSale)) {
                $this->restoreSaleStock($originalSale);
            }

            $sale->update($this->saleSummaryPayload($request, $customer, $saleItems, $commercials));
            $this->syncSaleItems($sale, $saleItems);

            if ($sale->payment_status !== 'void') {
                $this->applySaleStock($sale->fresh(['product', 'asset', 'saleItems.product', 'saleItems.asset']));
            } elseif ($this->hasStockAppliedColumn()) {
                $sale->forceFill(['stock_applied' => false])->saveQuietly();
            }

            if ($invoice = $this->saleInvoice($sale->refresh())) {
                $this->syncSaleInvoiceFromSale($sale, $invoice);
                $this->syncExistingSaleInvoicePayment($sale, $invoice);
            }
        });

        ActivityLogger::log('sale.updated', $sale->refresh(), [
            'sale_amount' => $sale->sale_amount,
            'payment_status' => $sale->payment_status,
            'tax_calculation_mode' => $sale->tax_calculation_mode ?? null,
        ], 'Sale updated.');

        return redirect()->route('sales.index')->with('success', 'Sale updated successfully.');
    }

