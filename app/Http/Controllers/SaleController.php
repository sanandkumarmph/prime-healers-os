    private function saleInvoiceItemPayloads(Sale $sale, string $taxType, array $saleItems): array
    {
        return collect($saleItems)->map(function (array $line) use ($sale, $taxType) {
            $taxAmount = (float) ($line['commercials']['total_tax_amount'] ?? 0);
            $lineTotalExShipping = round((float) ($line['commercials']['sale_amount'] ?? 0) - (float) ($line['shipping_charges'] ?? 0), 2);
            $product = $line['product'] ?? null;
            $description = $product?->name ?? 'Sale product';

            $assetNote = !empty($line['asset_id']) ? ' | Asset linked' : '';

            return [
                'product_id' => $line['product_id'],
                'source_type' => 'sale',
                'source_id' => $sale->id,
                'description' => $description . ' | Unit: sale | Qty: ' . (float) $line['quantity'] . $assetNote,
                'hsn_sac_code' => null,
                'quantity' => (float) $line['quantity'],
                'unit' => 'sale',
