    private function calculateSaleCommercials(
        float $quantity,
        float $unitPrice,
        float $discountAmount,
        float $shippingCharges,
        float $taxPercentage,
        string $taxCalculationMode
    ): array {
        $quantity = max($quantity, 1);
        $unitPrice = max($unitPrice, 0);
        $discountAmount = max($discountAmount, 0);
        $shippingCharges = max($shippingCharges, 0);
        $taxPercentage = max($taxPercentage, 0);
        $taxCalculationMode = $taxCalculationMode === 'inclusive' ? 'inclusive' : 'exclusive';

        $subtotal = round($quantity * $unitPrice, 2);
        $taxableBase = max($subtotal - $discountAmount, 0);

        if ($taxCalculationMode === 'inclusive' && $taxPercentage > 0) {
            $taxableAmount = round($taxableBase / (1 + ($taxPercentage / 100)), 2);
            $totalTaxAmount = round($taxableBase - $taxableAmount, 2);
        } else {
            $taxableAmount = $taxableBase;
            $totalTaxAmount = round(($taxableAmount * $taxPercentage) / 100, 2);
        }

        $saleAmount = round($taxableBase + ($taxCalculationMode === 'exclusive' ? $totalTaxAmount : 0) + $shippingCharges, 2);

        return [
            'subtotal' => $subtotal,
            'discount_amount' => $discountAmount,
            'shipping_charges' => $shippingCharges,
            'taxable_amount' => $taxableAmount,
            'total_tax_amount' => $totalTaxAmount,
            'sale_amount' => $saleAmount,
        ];
    }

    private function createSaleInvoice(Sale $sale): Invoice
    {
        $sale->loadMissing(['customer', 'product', 'asset.warehouse', 'rental']);

        if ($existingInvoice = $this->saleInvoice($sale)) {
            $this->syncSaleInvoiceFromSale($sale, $existingInvoice);
            $this->syncExistingSaleInvoicePayment($sale, $existingInvoice);

            return $existingInvoice;
        }

        $organization = Organization::findOrFail($this->orgId());
        $taxType = $this->saleTaxType($sale, $organization);

        $commercials = $this->calculateSaleCommercials(
            (float) $sale->quantity,
            (float) ($sale->unit_price ?: 0),
            (float) ($sale->discount_amount ?: 0),
            (float) ($sale->shipping_charges ?: 0),
            (float) ($sale->tax_percentage ?: 0),
            (string) ($sale->tax_calculation_mode ?: 'exclusive')
        );

        return DB::transaction(function () use ($sale, $organization, $taxType, $commercials) {
            $invoice = app(InvoiceSyncService::class)->createSaleInvoiceFromPayload(
                $this->orgId(),
                $sale,
                $this->hasInvoiceSaleColumn(),
                $this->nextInvoiceNumber(),
                $this->saleInvoicePayload($sale, $organization, $taxType, $commercials),
                $this->saleInvoiceItemPayload($sale, $taxType, $commercials),
                $sale->payment_status === 'paid',
                auth()->id()
            );

            if ($sale->payment_status === 'paid') {
                app(PaymentSyncService::class)->recordPaidSaleInvoice(
                    $this->orgId(),
                    $sale,
                    $invoice,
                    (float) $commercials['sale_amount'],
                    $this->paymentsRentalIdIsNullable()
                );
                $invoice->refresh()->syncFinancialStatus();
            }

            return $invoice;
        });
    }

    private function saleTaxType(Sale $sale, Organization $organization): string
    {
        $customerState = $this->normalizeStateName($sale->customer?->state);
        $organizationState = $this->normalizeStateName($organization->state);

        return ($customerState && $organizationState && $customerState !== $organizationState)
            ? 'igst'
            : 'cgst_sgst';
    }

