            if ($this->hasDeliverySaleColumn()) {
                $relations[] = 'deliveryRecord.assignedStaff';
                $relations[] = 'deliveryRecord.assignedUser';
            }

            $query->with($relations);
        }

        return $this->applySalesScope($query);
    }

