    private function trackedSaleAllocatedAssetsForLine(SaleItem $saleItem)
    {
        $assetIds = collect($saleItem->asset_ids ?? [])
            ->map(fn ($assetId) => (int) $assetId)
            ->filter(fn ($assetId) => $assetId > 0)
            ->values()
            ->all();

        if (empty($assetIds) && $saleItem->asset_id) {
