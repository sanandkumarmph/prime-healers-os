    private function trackedSaleAllocationError(Product $product): ValidationException
    {
        return ValidationException::withMessages([
            'quantity' => ['Tracked sale product requires available sale asset units. Add stock or convert rental asset to sale stock first.'],
        ]);
    }

    private function trackedSaleAllocatedAssets(Sale $sale)
    {
        $sale->loadMissing('saleUnits');

        $assetIds = $sale->saleUnits
            ->pluck('id')
            ->map(fn ($assetId) => (int) $assetId)
            ->filter(fn ($assetId) => $assetId > 0)
            ->values()
            ->all();

        if (empty($assetIds) && $sale->asset_id) {
            $assetIds = [(int) $sale->asset_id];
        }

        if (empty($assetIds)) {
            return collect();
        }

        return Asset::query()
            ->where('organization_id', $this->orgId())
            ->whereIn('id', $assetIds)
            ->lockForUpdate()
            ->get()
            ->sortBy(fn ($asset) => $asset->serial_number ?: (string) $asset->id)
            ->values();
    }

    private function autoAllocateTrackedSaleAssets(Product $product, int $quantity, ?int $warehouseId = null, ?int $explicitAssetId = null)
    {
        if ($quantity <= 0) {
            return collect();
        }

        $baseQuery = Asset::query()
            ->where('organization_id', $this->orgId())
            ->where('product_id', $product->id)
            ->where('asset_stage', Asset::STAGE_NEW_STOCK);

        if ($explicitAssetId) {
            $asset = (clone $baseQuery)
                ->lockForUpdate()
                ->findOrFail($explicitAssetId);

            if ($asset->asset_status !== 'available_for_sale') {
                throw $this->trackedSaleAllocationError($product);
            }

            if ($quantity !== 1) {
                throw ValidationException::withMessages([
                    'quantity' => ['Quantity must be 1 when a serialized asset is selected for a tracked sale product.'],
                ]);
            }

            return collect([$asset]);
        }

        if ($warehouseId) {
            $assets = (clone $baseQuery)
                ->where('warehouse_id', $warehouseId)
                ->where('asset_status', 'available_for_sale')
                ->orderBy('serial_number')
                ->orderBy('id')
                ->lockForUpdate()
                ->limit($quantity)
                ->get();

            if ($assets->count() < $quantity) {
                throw $this->trackedSaleAllocationError($product);
            }

            return $assets->values();
        }

        $assets = (clone $baseQuery)
            ->where('asset_status', 'available_for_sale')
            ->orderByRaw('CASE WHEN warehouse_id IS NULL THEN 1 ELSE 0 END')
            ->orderBy('warehouse_id')
            ->orderBy('serial_number')
            ->orderBy('id')
            ->lockForUpdate()
            ->limit($quantity)
            ->get();

        if ($assets->count() < $quantity) {
            throw $this->trackedSaleAllocationError($product);
        }

        return $assets->values();
    }

    private function syncTrackedSaleUnitAssignments(Sale $sale, $assets): void
    {
        $syncPayload = $assets
            ->mapWithKeys(fn ($asset) => [
                (int) $asset->id => ['organization_id' => $this->orgId()],
            ])
            ->all();

        $sale->saleUnits()->sync($syncPayload);

        $resolvedAssetId = $assets->count() === 1 ? (int) $assets->first()->id : null;

        if ((int) ($sale->asset_id ?? 0) !== (int) ($resolvedAssetId ?? 0)) {
            $sale->forceFill([
                'asset_id' => $resolvedAssetId,
            ])->saveQuietly();
        }
    }

    private function adjustSaleStock(Sale $sale, bool $restore = false): void
    {
        $sale->loadMissing(['product', 'asset']);

        $product = Product::query()
            ->where('organization_id', $this->orgId())
            ->findOrFail($sale->product_id);

        $quantity = max((int) $sale->quantity, 1);
        $warehouseId = $this->hasWarehouseColumn() ? (int) ($sale->warehouse_id ?? 0) : 0;
        $asset = null;

        if ($product->tracksSaleStock()) {
            if ($restore) {
                $allocatedAssets = $this->trackedSaleAllocatedAssets($sale);

                foreach ($allocatedAssets as $allocatedAsset) {
                    if ($allocatedAsset->asset_stage !== Asset::STAGE_NEW_STOCK) {
                        continue;
                    }

                    $allocatedAsset->update(['asset_status' => 'available_for_sale']);
                }

                $this->syncTrackedSaleSummary($product);
                $this->updateSaleStockState(
                    $sale,
                    false,
                    $warehouseId ?: ($allocatedAssets->count() === 1 ? (int) ($allocatedAssets->first()->warehouse_id ?: 0) : null)
                );

                return;
            }

            $allocatedAssets = $this->autoAllocateTrackedSaleAssets(
                $product,
                $quantity,
                $warehouseId ?: null,
                $sale->asset_id ? (int) $sale->asset_id : null
            );

            foreach ($allocatedAssets as $allocatedAsset) {
                $allocatedAsset->update(['asset_status' => 'sold']);
            }

            $this->syncTrackedSaleUnitAssignments($sale, $allocatedAssets);
            $this->syncTrackedSaleSummary($product);

            $resolvedWarehouseId = null;

            if ($allocatedAssets->pluck('warehouse_id')->filter(fn ($warehouse) => filled($warehouse))->unique()->count() === 1) {
                $resolvedWarehouseId = (int) $allocatedAssets->pluck('warehouse_id')->first();
            } elseif ($warehouseId > 0) {
                $resolvedWarehouseId = $warehouseId;
            }

            $this->updateSaleStockState($sale, true, $resolvedWarehouseId);

            return;
        }

        if ($sale->asset_id) {
            $asset = Asset::query()
                ->where('organization_id', $this->orgId())
                ->lockForUpdate()
                ->findOrFail($sale->asset_id);

            if ((int) $asset->product_id !== (int) $product->id) {
                throw ValidationException::withMessages([
                    'asset_id' => 'Selected asset does not belong to the chosen product.',
                ]);
            }

            if ($asset->asset_stage !== Asset::STAGE_NEW_STOCK) {
                throw ValidationException::withMessages([
                    'asset_id' => 'Only new stock assets can be linked to a sale.',
                ]);
            }

            $warehouseId = (int) ($asset->warehouse_id ?: $warehouseId);

            if ($restore) {
                $asset->update(['asset_status' => 'available_for_sale']);
            } else {
                if ($asset->asset_status !== 'available_for_sale') {
                    throw ValidationException::withMessages([
                        'asset_id' => 'Selected asset is no longer available for sale.',
                    ]);
                }

                $asset->update(['asset_status' => 'sold']);
            }
        }

        $inventory = $this->resolveSaleInventory($product, $quantity, $warehouseId ?: null, $restore);

        if ($inventory) {
            if (!$restore && $inventory->availableToSell() < $quantity) {
                throw ValidationException::withMessages([
                    'quantity' => 'Sale quantity exceeds available stock for ' . $product->name . '.',
                ]);
            }

            if ($restore) {
                $inventory->increment('quantity_in_stock', $quantity);
            } else {
                $inventory->decrement('quantity_in_stock', $quantity);
            }

            $product->syncLegacyStockFields();
            $warehouseId = (int) $inventory->warehouse_id;
        } else {
            if ($restore) {
                $product->increment('available_quantity', $quantity);
            } else {
                if ((int) $product->available_quantity < $quantity) {
                    throw ValidationException::withMessages([
                        'quantity' => 'Sale quantity exceeds available stock for ' . $product->name . '.',
                    ]);
                }

                $product->decrement('available_quantity', $quantity);
            }
        }

        $this->updateSaleStockState($sale, !$restore, $warehouseId ?: null);
    }

