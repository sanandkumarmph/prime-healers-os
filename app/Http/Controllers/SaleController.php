    }

    private function validateLinkedSaleReferences(Request $request, Product $product, Customer $customer, ?Sale $currentSale = null): void
    {
        if ($request->filled('asset_id')) {
            $asset = Asset::query()
                ->where('organization_id', $this->orgId())
                ->findOrFail($request->integer('asset_id'));

            if ((int) $asset->product_id !== (int) $product->id) {
                throw ValidationException::withMessages([
                    'asset_id' => 'Selected asset does not belong to the chosen product. Please choose an asset for ' . $product->name . '.',
                ]);
            }

            if ($asset->asset_stage !== Asset::STAGE_NEW_STOCK) {
                throw ValidationException::withMessages([
                    'asset_id' => 'Only new stock assets can be linked to a sale.',
                ]);
            }

            $isCurrentSaleAsset = $currentSale && (int) $currentSale->asset_id === (int) $asset->id;

            if ($asset->asset_status !== 'available_for_sale' && !$isCurrentSaleAsset) {
                throw ValidationException::withMessages([
                    'asset_id' => 'Selected asset is not available for sale.',
                ]);
            }

            if ((int) $request->integer('quantity') !== 1) {
                throw ValidationException::withMessages([
                    'quantity' => 'Quantity must be 1 when a serialized asset is linked.',
                ]);
            }
        }

        if ($request->filled('rental_id')) {
            $rental = Rental::query()
                ->where('organization_id', $this->orgId())
                ->findOrFail($request->integer('rental_id'));

            if ((int) $rental->customer_id !== (int) $customer->id) {
                throw ValidationException::withMessages([
                    'rental_id' => 'Linked rental must belong to the selected customer.',
                ]);
            }
        }
    }

    private function synchronizeLinkedRentalContext(Request $request): void
    {
        if (! $request->filled('rental_id')) {
            return;
        }

        $rental = Rental::query()
            ->where('organization_id', $this->orgId())
            ->find($request->integer('rental_id'));

        if (! $rental || ! $rental->customer_id) {
            return;
        }

        $request->merge([
            'customer_id' => $rental->customer_id,
        ]);
    }

    private function attachLinkedInvoiceIds($sales)
    {
        $saleIds = $sales->pluck('id')->filter()->map(fn ($id) => (int) $id)->values();

        if ($saleIds->isEmpty()) {
            return $sales;
        }

        $invoiceMap = Invoice::query()
            ->whereIn('id', (clone $this->saleInvoiceLookupQuery($saleIds->all()))->select('id'))
            ->with(['items' => function ($itemQuery) use ($saleIds) {
                $itemQuery
                    ->where('source_type', 'sale')
                    ->whereIn('source_id', $saleIds->all());
            }])
            ->orderByDesc('id')
            ->get()
            ->reduce(function ($carry, $invoice) {
                $directSaleId = $this->hasInvoiceSaleColumn()
                    ? (int) ($invoice->sale_id ?? 0)
                    : 0;

                if ($directSaleId > 0 && !isset($carry[$directSaleId])) {
                    $carry[$directSaleId] = (int) $invoice->id;
                }

                foreach ($invoice->items as $item) {
                    $saleId = (int) ($item->source_id ?? 0);

                    if ($saleId > 0 && !isset($carry[$saleId])) {
                        $carry[$saleId] = (int) $invoice->id;
                    }
                }

                return $carry;
            }, []);

        $sales->each(function ($sale) use ($invoiceMap) {
            $sale->setAttribute('linked_invoice_id', $invoiceMap[(int) $sale->id] ?? null);
        });

        return $sales;
    }

    private function salesReceivablesSnapshot($salesQuery): array
    {
        $salesCollection = (clone $salesQuery)->get(['id', 'sale_amount']);
        $saleIds = $salesCollection
            ->pluck('id')
            ->filter()
            ->map(fn ($id) => (int) $id)
            ->unique()
            ->values();

        if ($saleIds->isEmpty()) {
            return [
                'outstandingInvoiceCount' => 0,
                'outstandingInvoiceAmount' => 0.0,
                'unbilledSalesCount' => 0,
                'unbilledSalesAmount' => 0.0,
                'totalPendingSalesAmount' => 0.0,
            ];
        }

        $linkedInvoices = DB::table('invoice_items')
            ->join('invoices', 'invoices.id', '=', 'invoice_items.invoice_id')
            ->where('invoices.organization_id', $this->orgId())
            ->where('invoice_items.source_type', 'sale')
            ->whereIn('invoice_items.source_id', $saleIds->all())
            ->whereNotIn('invoices.payment_status', ['cancelled'])
            ->select([
                'invoice_items.source_id',
                'invoices.id as invoice_id',
                'invoices.payment_status',
                'invoices.balance_amount',
            ])
            ->get();

        if ($this->hasInvoiceSaleColumn()) {
            $linkedInvoices = $linkedInvoices
                ->concat(
                    Invoice::query()
                        ->where('organization_id', $this->orgId())
                        ->whereIn('sale_id', $saleIds->all())
                        ->whereNotIn('payment_status', ['cancelled'])
                        ->get([
                            'sale_id as source_id',
                            'id as invoice_id',
                            'payment_status',
                            'balance_amount',
                        ])
                )
                ->unique(fn ($invoice) => ((int) $invoice->invoice_id).':'.((int) $invoice->source_id));
        }

        $linkedSaleIds = $linkedInvoices
            ->pluck('source_id')
            ->map(fn ($id) => (int) $id)
            ->unique();

        $outstandingInvoices = $linkedInvoices
            ->filter(fn ($invoice) => in_array($invoice->payment_status, ['unpaid', 'partial', 'overdue'], true))
            ->unique('invoice_id');

        $outstandingInvoiceAmount = round((float) $outstandingInvoices->sum(fn ($invoice) => (float) ($invoice->balance_amount ?? 0)), 2);
        $unbilledSales = $salesCollection
            ->filter(fn (Sale $sale) => !$linkedSaleIds->contains((int) $sale->id));
        $unbilledSalesAmount = round((float) $unbilledSales->sum(fn (Sale $sale) => (float) ($sale->sale_amount ?? 0)), 2);

        return [
            'outstandingInvoiceCount' => (int) $outstandingInvoices->count(),
            'outstandingInvoiceAmount' => $outstandingInvoiceAmount,
            'unbilledSalesCount' => (int) $unbilledSales->count(),
            'unbilledSalesAmount' => $unbilledSalesAmount,
            'totalPendingSalesAmount' => round($outstandingInvoiceAmount + $unbilledSalesAmount, 2),
        ];
    }

    public function index(Request $request)
    {
        $this->authorize('viewAny', Sale::class);

        $search = trim((string) $request->get('search', ''));
        $customerId = $request->get('customer_id', '');
        $paymentStatus = (string) $request->get('payment_status', '');
        $fromDate = trim((string) $request->get('from_date', $request->get('date', '')));
        $toDate = trim((string) $request->get('to_date', $request->get('date', '')));
        $sortBy = (string) $request->get('sort_by', 'latest');

        $applyIndexFilters = function ($query) use ($customerId, $paymentStatus, $search, $fromDate, $toDate) {
            $query
                ->when($customerId !== '', fn ($innerQuery) => $innerQuery->where('customer_id', $customerId))
                ->when($paymentStatus !== '', fn ($innerQuery) => $innerQuery->where('payment_status', $paymentStatus))
                ->when($search !== '', function ($innerQuery) use ($search) {
                    $innerQuery->where(function ($nestedQuery) use ($search) {
                        $nestedQuery->whereHas('customer', function ($customerQuery) use ($search) {
                            $customerQuery->where('name', 'like', '%' . $search . '%')
                                ->orWhere('phone', 'like', '%' . $search . '%')
                                ->orWhere('email', 'like', '%' . $search . '%');

                            if (Customer::hasWhatsappNumberColumn()) {
                                $customerQuery->orWhere('whatsapp_number', 'like', '%' . $search . '%');
                            }
                        })->orWhereHas('product', function ($productQuery) use ($search) {
                            $productQuery->where('name', 'like', '%' . $search . '%');
                        })->orWhere('notes', 'like', '%' . $search . '%');
                    });
                });

            $this->applyDateRangeFilter($query, $fromDate, $toDate);

            return $query;
        };

        $salesQuery = $applyIndexFilters($this->baseSalesQuery(true));
        $summaryQuery = $applyIndexFilters($this->baseSalesQuery(false));

        $sales = $this->applySorting(clone $salesQuery, $sortBy)
            ->paginate(20)
            ->withQueryString();

        $this->attachLinkedInvoiceIds($sales->getCollection());

        $totalSales = (clone $summaryQuery)->count();
        $paidSales = (clone $summaryQuery)->where('payment_status', 'paid')->count();
        $pendingSales = (clone $summaryQuery)->whereIn('payment_status', ['pending', 'partial'])->count();
        $totalSalesAmount = (clone $summaryQuery)->sum('sale_amount');
        $totalTransportationAmount = (clone $summaryQuery)->sum('shipping_charges');
        $totalSaleValue = max((float) $totalSalesAmount - (float) $totalTransportationAmount, 0);
        $salesReceivables = $this->salesReceivablesSnapshot($summaryQuery);
        $outstandingInvoiceAmount = (float) ($salesReceivables['outstandingInvoiceAmount'] ?? 0);
        $outstandingInvoiceCount = (int) ($salesReceivables['outstandingInvoiceCount'] ?? 0);
        $unbilledSalesAmount = (float) ($salesReceivables['unbilledSalesAmount'] ?? 0);
        $unbilledSalesCount = (int) ($salesReceivables['unbilledSalesCount'] ?? 0);
        $totalPendingSalesAmount = (float) ($salesReceivables['totalPendingSalesAmount'] ?? 0);

        $customers = Customer::where('organization_id', $this->orgId())
            ->orderBy('name')
            ->get(['id', 'name']);

        return view('sales.index', compact(
            'sales',
            'customers',
            'search',
            'customerId',
            'paymentStatus',
            'fromDate',
            'toDate',
            'sortBy',
            'totalSales',
            'paidSales',
            'pendingSales',
            'totalSalesAmount',
            'totalTransportationAmount',
            'totalSaleValue',
            'outstandingInvoiceAmount',
            'outstandingInvoiceCount',
            'unbilledSalesAmount',
            'unbilledSalesCount',
            'totalPendingSalesAmount'
        ));
    }

