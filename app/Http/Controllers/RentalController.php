            }

            if ($this->hasDeliveryThirdPartyNameColumn()) {
                $deliveryData['third_party_name'] = ($deliveryAssignment['type'] ?? null) === 'third_party'
                    ? $request->input('third_party_name')
                    : null;
            }

            if ($this->hasDeliveryThirdPartyContactColumn()) {
                $deliveryData['third_party_contact'] = ($deliveryAssignment['type'] ?? null) === 'third_party'
