            ->where('organization_id', $this->orgId())
            ->when(Schema::hasColumn('users', 'is_active'), fn ($query) => $query->where('is_active', true))
            ->where(function ($query) use ($allowedRoles, $allowedRoleIds) {
                $query->whereIn('role', $allowedRoles);

                if ($allowedRoleIds->isNotEmpty()) {
                    $query->orWhereIn('role_id', $allowedRoleIds);
                }
            })
            ->orderBy('name')
            ->get();
    }

    private function activeRentalStaffExistsRule(): Exists
    {
        return Rule::exists('staff', 'id')->where(function ($query) {
            $query->where('organization_id', $this->orgId())
                ->where('status', 'active');

            if (Staff::hasAssignmentEnabledColumn()) {
                $query->where('is_assignment_enabled', true);
            }

            if (Staff::hasAssignmentRoleColumn()) {
                $query->whereIn('assignment_role', Staff::deliveryPickupAssignmentRoles());
            } else {
                $query->whereIn('role', Staff::deliveryPickupAssignmentRoles());
            }
        });
    }

    private function assignableUserRule(): Exists
    {
        $allowedRoles = ['delivery', 'pickup'];
        $allowedRoleIds = collect();

        if (Schema::hasColumn('users', 'role_id')) {
            $allowedRoleIds = Role::query()
                ->whereIn('slug', $allowedRoles)
                ->pluck('id');
        }

        return Rule::exists('users', 'id')->where(function ($query) use ($allowedRoles, $allowedRoleIds) {
            $query->where('organization_id', $this->orgId())
                ->when(Schema::hasColumn('users', 'is_active'), fn ($innerQuery) => $innerQuery->where('is_active', true))
                ->where(function ($innerQuery) use ($allowedRoles, $allowedRoleIds) {
                    $innerQuery->whereIn('role', $allowedRoles);

                    if ($allowedRoleIds->isNotEmpty()) {
                        $innerQuery->orWhereIn('role_id', $allowedRoleIds);
                    }
                });
        });
    }

    private function parseAssignmentTarget(mixed $value): array
    {
        $rawValue = trim((string) $value);

        if ($rawValue === '') {
            return ['type' => null, 'id' => null];
        }

        if ($rawValue === 'third_party') {
            return ['type' => 'third_party', 'id' => 0];
        }

        if (str_contains($rawValue, ':')) {
            [$type, $id] = explode(':', $rawValue, 2);
        } else {
            $type = 'staff';
            $id = $rawValue;
        }

        $type = strtolower(trim((string) $type));
        $id = (int) $id;

        if (!in_array($type, ['user', 'staff'], true) || $id <= 0) {
            return ['type' => null, 'id' => null];
        }

        return ['type' => $type, 'id' => $id];
    }

    private function validatedAssignmentTarget(mixed $value, string $field): array
    {
        $target = $this->parseAssignmentTarget($value);

        if ($target['type'] === 'third_party') {
            return [
                'user_id' => null,
                'staff_id' => null,
                'type' => 'third_party',
                'staff_role' => 'third_party',
            ];
        }

        if (!$target['type'] || !$target['id']) {
            if (filled($value)) {
                throw ValidationException::withMessages([
                    $field => ['Please choose a valid delivery assignment.'],
                ]);
            }

            return [
                'user_id' => null,
                'staff_id' => null,
                'type' => null,
                'staff_role' => null,
            ];
        }

        validator(
            [$field => $target['id']],
            [$field => [$target['type'] === 'user' ? $this->assignableUserRule() : $this->activeRentalStaffExistsRule()]]
        )->validate();

        $staffRole = null;
        if ($target['type'] === 'staff') {
            $staffRole = Staff::query()
                ->where('organization_id', $this->orgId())
                ->whereKey($target['id'])
                ->value(Staff::hasAssignmentRoleColumn() ? 'assignment_role' : 'role');

            $staffRole = Staff::normalizedRole($staffRole);
        }

        return [
            'user_id' => $target['type'] === 'user' ? $target['id'] : null,
            'staff_id' => $target['type'] === 'staff' ? $target['id'] : null,
            'type' => $target['type'],
            'staff_role' => $staffRole,
        ];
    }

