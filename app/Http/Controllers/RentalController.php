                $rentalQuery->where('dispatch_warehouse_id', $warehouseId);
            });
        }

        return $this->applySimpleDateRangeFilter($query, 'scheduled_at', $fromDate, $toDate);
    }

    private function monthlyDashboardTrend(Request $request, int $months = 6): array
    {
        $startMonth = Carbon::today()->startOfMonth()->subMonths($months - 1);
        $labels = collect(range(0, $months - 1))
            ->map(fn ($offset) => $startMonth->copy()->addMonths($offset))
            ->values();

        $trend = $labels->mapWithKeys(function (Carbon $month) {
            return [
                $month->format('Y-m') => [
                    'label' => $month->format('M Y'),
                    'rental_total' => 0.0,
                    'sales_total' => 0.0,
                ],
            ];
        });

        $rentalAggregateQuery = $this->filteredRentalAggregateQuery($request)->toBase();

        $monthPeriodExpression = $this->yearMonthExpression('start_date');
        $salesPeriodExpression = $this->yearMonthExpression('sale_date');

        $rentalRows = (clone $rentalAggregateQuery)
            ->whereDate('start_date', '>=', $startMonth->toDateString())
            ->selectRaw("
                {$monthPeriodExpression} as period,
                SUM(COALESCE(rental_amount, 0) + COALESCE(deposit_amount, 0) + COALESCE(transport_amount, 0) + COALESCE(other_amount, 0)) as total
            ")
            ->groupBy('period')
            ->pluck('total', 'period');

        $salesRows = $this->filteredSalesQuery($request, false)
            ->whereDate('sale_date', '>=', $startMonth->toDateString())
            ->selectRaw("{$salesPeriodExpression} as period, SUM(COALESCE(sale_amount, 0)) as total")
            ->groupBy('period')
            ->pluck('total', 'period');

        $trend = $trend->map(function (array $row, string $period) use ($rentalRows, $salesRows) {
            $row['rental_total'] = isset($rentalRows[$period]) ? (float) $rentalRows[$period] : 0.0;
            $row['sales_total'] = isset($salesRows[$period]) ? (float) $salesRows[$period] : 0.0;

            return $row;
        });

        return $trend->values()->all();
    }

