    private function applyVendorFilterToRentalQuery($query, int $vendorUserId)
    {
        if ($vendorUserId <= 0) {
            return $query;
        }

        return $query->where(function ($vendorQuery) use ($vendorUserId) {
            $vendorQuery
                ->whereHas('deliveryRecord', function ($deliveryQuery) use ($vendorUserId) {
                    $deliveryQuery->where('assignment_type', 'vendor')
                        ->where('assigned_user_id', $vendorUserId);
                })
                ->orWhereHas('pickupRecord', function ($pickupQuery) use ($vendorUserId) {
                    $pickupQuery->where('assignment_type', 'vendor')
                        ->where('assigned_user_id', $vendorUserId);
                });
        });
    }

    private function vendorNameFromDeliveryRecord($delivery): ?string
    {
        if (!$delivery || ($delivery->assignment_type ?? null) !== 'vendor') {
            return null;
        }

        if ($delivery->assignedUser && method_exists($delivery->assignedUser, 'isVendor') && $delivery->assignedUser->isVendor()) {
            return $delivery->assignedUser->name;
        }

        return null;
    }

