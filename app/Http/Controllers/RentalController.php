    private function importedRentalPaymentReviewMessage(Rental $rental, Invoice $invoice, array $attributes): ?string
    {
        $statusProvided = $this->importFieldWasProvided($attributes, 'payment_status');
        $paidAmountProvided = $this->importFieldWasProvided($attributes, 'paid_amount');

        if (!$statusProvided && !$paidAmountProvided) {
            return null;
        }

        $paymentStatus = strtolower(trim((string) ($attributes['payment_status'] ?? 'pending')));
        $requestedPaidAmount = match ($paymentStatus) {
            'paid' => round(
                (float) ($attributes['rental_amount'] ?? $rental->rental_amount)
                + (float) ($attributes['deposit_amount'] ?? $rental->deposit_amount)
                + (float) ($attributes['transport_amount'] ?? $rental->transport_amount)
                + (float) ($attributes['other_amount'] ?? $rental->other_amount),
                2
            ),
            'partial' => round((float) ($attributes['paid_amount'] ?? 0), 2),
            default => 0.0,
        };

        $managedPayment = $this->managedImportedRentalPaymentQuery($invoice, $rental->id)->first();
        $historicalPaymentsTotal = (float) $invoice->payments()
            ->when($managedPayment, fn ($query) => $query->whereKeyNot($managedPayment->id))
            ->sum('amount');

        if ($requestedPaidAmount + 0.01 < $historicalPaymentsTotal) {
            return 'Existing recorded payments exceed the imported payment state for this rental. Review this row manually.';
        }

        return null;
    }

