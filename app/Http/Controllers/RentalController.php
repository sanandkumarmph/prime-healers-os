    public function updateRenewal(Request $request, Rental $rental, RentalRenewal $renewal)
    {
        $this->ensureRentalAccess();
        $rental = $this->scopedRental($rental);

        abort_if(!$this->hasRentalRenewalsTable(), 404);
        abort_if((int) $renewal->rental_id !== (int) $rental->id || (int) $renewal->organization_id !== $this->orgId(), 404);

        $validated = $request->validate($this->renewalValidationRulesFor($rental, $renewal));

        $rental->loadMissing(['customer', 'product']);
        $renewal->loadMissing(['invoice', 'payment']);
        $nextRenewal = $this->nextRenewalFor($renewal);

        $oldRentalAmount = (float) ($renewal->rental_amount_added ?? 0);
        $oldDepositAmount = (float) ($renewal->deposit_amount_added ?? 0);
        $oldTransportAmount = (float) ($renewal->transport_amount_added ?? 0);
        $oldOtherAmount = (float) ($renewal->other_amount_added ?? 0);

        $newEndDate = Carbon::parse($validated['new_end_date'])->startOfDay();
        if ($nextRenewal && $nextRenewal->renewed_end_date && !$newEndDate->lt(Carbon::parse($nextRenewal->renewed_end_date)->startOfDay())) {
            return redirect()
                ->route('rentals.show', $rental)
                ->with('error', 'This renewal must end before the next logged renewal ends. Edit the later renewal first if you need to shift the whole chain.');
        }

        $renewalDays = $renewal->previous_end_date
            ? max((int) Carbon::parse($renewal->previous_end_date)->diffInDays($newEndDate), 1)
            : max((int) ($renewal->renewal_days ?? 1), 1);

        $newRentalAmount = (float) ($validated['rental_amount_added'] ?? 0);
        $newDepositAmount = (float) ($validated['deposit_amount_added'] ?? 0);
        $newTransportAmount = (float) ($validated['transport_amount_added'] ?? 0);
        $newOtherAmount = (float) ($validated['other_amount_added'] ?? 0);
        $newPaymentAmount = (float) ($validated['payment_amount'] ?? 0);
        $paymentMethod = Payment::normalizeMethod($validated['payment_method'] ?? null);
        $paymentDate = !empty($validated['payment_date']) ? Carbon::parse($validated['payment_date']) : now();
        $notes = filled($validated['notes'] ?? null) ? trim((string) $validated['notes']) : null;

        DB::transaction(function () use (
            $rental,
            $renewal,
            $newEndDate,
            $renewalDays,
            $newRentalAmount,
            $newDepositAmount,
            $newTransportAmount,
            $newOtherAmount,
            $newPaymentAmount,
            $paymentMethod,
            $paymentDate,
            $notes,
            $oldRentalAmount,
            $oldDepositAmount,
            $oldTransportAmount,
            $oldOtherAmount,
            $nextRenewal
        ) {
            $rental->forceFill([
                'end_date' => $nextRenewal ? $rental->end_date : $newEndDate,
                'status' => 'active',
                'rental_amount' => max((float) ($rental->rental_amount ?? 0) - $oldRentalAmount + $newRentalAmount, 0),
                'deposit_amount' => max((float) ($rental->deposit_amount ?? 0) - $oldDepositAmount + $newDepositAmount, 0),
                'transport_amount' => max((float) ($rental->transport_amount ?? 0) - $oldTransportAmount + $newTransportAmount, 0),
                'other_amount' => max((float) ($rental->other_amount ?? 0) - $oldOtherAmount + $newOtherAmount, 0),
            ])->save();

            $renewal->forceFill([
                'renewed_end_date' => $newEndDate,
                'renewal_days' => $renewalDays,
                'rental_amount_added' => $newRentalAmount,
                'deposit_amount_added' => $newDepositAmount,
                'transport_amount_added' => $newTransportAmount,
                'other_amount_added' => $newOtherAmount,
                'payment_amount' => $newPaymentAmount,
                'payment_method' => $paymentMethod,
                'notes' => $notes,
                'renewed_by_user_id' => auth()->id(),
            ])->save();

            if ($nextRenewal) {
                $nextRenewalEndDate = Carbon::parse($nextRenewal->renewed_end_date)->startOfDay();
                $nextRenewal->forceFill([
                    'previous_end_date' => $newEndDate,
                    'renewal_days' => max((int) $newEndDate->diffInDays($nextRenewalEndDate), 1),
                ])->save();
            }

            $payment = $this->syncRenewalManagedPayment(
                $rental,
                $renewal,
                $newPaymentAmount,
                $paymentMethod,
                $paymentDate,
                $notes
            );

            $renewal->forceFill([
                'payment_id' => $payment?->id,
            ])->save();

            $this->syncRenewalInvoicePaymentState($rental, $renewal->refresh());

            if ($nextRenewal?->invoice_id) {
                $this->syncRenewalInvoicePaymentState($rental, $nextRenewal->refresh());
            }
        });

        ActivityLogger::log('rental.renewal_updated', $rental->refresh(), [
            'renewal_id' => $renewal->id,
            'invoice_id' => $renewal->invoice_id,
            'payment_id' => $renewal->payment_id,
            'new_end_date' => $newEndDate->toDateString(),
            'renewal_days' => $renewalDays,
        ], 'Latest rental renewal updated.');

        return redirect()
            ->route('rentals.show', $rental)
            ->with('success', 'Latest renewal updated successfully.');
    }

