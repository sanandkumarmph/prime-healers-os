        ], 'Rental created and invoice generated.');

        return redirect('/rentals')->with('success', 'Rental added successfully. Invoice ' . $invoice->invoice_number . ' was created automatically.');
    }

    public function importRentalFromPayload(array $attributes): array
    {
        $customer = Customer::query()
            ->where('organization_id', $this->orgId())
            ->findOrFail((int) ($attributes['customer_id'] ?? 0));
        $product = Product::query()
            ->where('organization_id', $this->orgId())
            ->findOrFail((int) ($attributes['product_id'] ?? 0));

        $quantity = max((int) ($attributes['quantity'] ?? 0), 1);
        $dispatchWarehouseId = filled($attributes['dispatch_warehouse_id'] ?? null)
            ? (int) $attributes['dispatch_warehouse_id']
            : null;
        $assetIds = $this->normalizeAssetIds($attributes['asset_ids'] ?? []);
        $notes = trim((string) ($attributes['notes'] ?? ''));

        $match = $this->describeImportedRentalMatch(
            $this->importMatchSignatureService()->rental(
                $attributes,
                $customer->id,
                $product->id,
                $dispatchWarehouseId,
                $assetIds,
                $quantity
            )
        );

        if (($match['action'] ?? null) === 'review') {
            throw ValidationException::withMessages([
                'import' => [$match['message'] ?? 'This rental import row requires manual review.'],
            ]);
        }

        $rentalItems = [[
            'product_id' => $product->id,
            'quantity' => $quantity,
            'asset_ids' => $assetIds,
            'unit_rental_amount' => $quantity > 0
                ? round(((float) ($attributes['rental_amount'] ?? 0)) / $quantity, 2)
                : (float) ($attributes['rental_amount'] ?? 0),
            'gst_rate' => 0.0,
            'gst_mode' => 'exclusive',
            'tax_type' => Product::GST_TAX_TYPE_CGST_SGST,
            'taxable_amount' => (float) ($attributes['rental_amount'] ?? 0),
            'cgst_amount' => 0.0,
            'sgst_amount' => 0.0,
            'igst_amount' => 0.0,
            'line_total' => (float) ($attributes['rental_amount'] ?? 0),
            'notes' => $notes !== '' ? $notes : 'Imported via Rental Import',
            'line_label' => 'imported rental line',
            'form_asset_field' => 'asset_ids',
        ]];

        $existingRental = $match['rental'] ?? null;
        $this->validateCombinedRentalItemStock($rentalItems, $existingRental, $dispatchWarehouseId);

        $selectedAssets = $this->resolveCombinedRentalAssets($rentalItems, $dispatchWarehouseId, $existingRental);

        if ($existingRental) {
            [$rental, $invoice, $delivery, $pickup] = $this->updateImportedRentalFromPayload(
                $existingRental,
                $attributes,
                $customer,
                $product,
                $dispatchWarehouseId,
                $notes,
                $rentalItems,
                $selectedAssets
            );
            $action = 'updated';
        } else {
            [$rental, $invoice, $delivery, $pickup] = $this->createImportedRentalFromPayload(
                $attributes,
                $customer,
                $product,
                $quantity,
                $dispatchWarehouseId,
                $notes,
                $rentalItems,
                $selectedAssets
            );
            $action = 'created';
        }

        try {
            ActivityLogger::log('rental.imported', $rental, [
                'invoice_id' => $invoice?->id,
                'invoice_number' => $invoice?->invoice_number,
                'delivery_id' => $delivery?->id,
                'pickup_id' => $pickup?->id,
