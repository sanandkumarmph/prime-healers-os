    private function availableSaleAssets(?Rental $rental = null)
    {
        $selectedAssetIds = [];

        if ($rental && $this->hasRentalSaleItemsTable()) {
            $rental->loadMissing('saleItems');
            $selectedAssetIds = $rental->saleItems
                ->pluck('asset_id')
                ->filter(fn ($assetId) => filled($assetId))
                ->map(fn ($assetId) => (int) $assetId)
                ->values()
                ->all();
        }

        $assets = Asset::query()
            ->with(['product', 'warehouse'])
            ->where('organization_id', $this->orgId())
            ->where('asset_stage', Asset::STAGE_NEW_STOCK)
            ->where(function ($query) use ($selectedAssetIds) {
                $query->where('asset_status', 'available_for_sale');

                if (!empty($selectedAssetIds)) {
                    $query->orWhereIn('id', $selectedAssetIds);
                }
            })
            ->orderBy('serial_number')
            ->get();

        if ($assets->isEmpty()) {
            return $assets;
        }

        $inventoryByKey = SaleInventory::query()
            ->where('organization_id', $this->orgId())
            ->whereIn('product_id', $assets->pluck('product_id')->filter()->unique()->values())
            ->whereIn('warehouse_id', $assets->pluck('warehouse_id')->filter()->unique()->values())
            ->get()
            ->keyBy(fn ($inventory) => $inventory->product_id . ':' . $inventory->warehouse_id);

        return $assets->filter(function ($asset) use ($inventoryByKey, $selectedAssetIds) {
            if (in_array((int) $asset->id, $selectedAssetIds, true)) {
                return true;
            }

            $key = (int) $asset->product_id . ':' . (int) $asset->warehouse_id;
            $inventory = $inventoryByKey->get($key);

            if (!$inventory) {
                return true;
            }

            return $inventory->availableToSell() > 0;
        })->values();
    }

