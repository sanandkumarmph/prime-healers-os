    private function filteredPaymentQuery(Request $request, bool $includeRelations = false)
    {
        $query = Payment::query();

        if ($this->hasPaymentOrganizationColumn()) {
            $query->forOrganization($this->orgId());
        } else {
            $query->where(function ($paymentQuery) {
                $hasScopedCondition = false;

                if ($this->hasPaymentCustomerColumn()) {
                    $hasScopedCondition = true;
                    $paymentQuery->whereHas('customer', function ($customerQuery) {
                        $customerQuery->where('organization_id', $this->orgId());
                    });
                }

                if ($this->hasPaymentRentalColumn()) {
                    $hasScopedCondition = true;
                    ($this->hasPaymentCustomerColumn() ? $paymentQuery->orWhereHas('rental', function ($rentalQuery) {
                        $rentalQuery->where('organization_id', $this->orgId());
                    }) : $paymentQuery->whereHas('rental', function ($rentalQuery) {
                        $rentalQuery->where('organization_id', $this->orgId());
                    }));
                }

                if ($this->hasPaymentInvoiceColumn()) {
                    $hasScopedCondition = true;
                    (($this->hasPaymentCustomerColumn() || $this->hasPaymentRentalColumn())
                        ? $paymentQuery->orWhereHas('invoice', function ($invoiceQuery) {
                            $invoiceQuery->where('organization_id', $this->orgId());
                        })
                        : $paymentQuery->whereHas('invoice', function ($invoiceQuery) {
                            $invoiceQuery->where('organization_id', $this->orgId());
                        }));
                }

                if (!$hasScopedCondition) {
                    $paymentQuery->whereRaw('1 = 0');
                }
            });
        }

        $query->where(function ($linkedPaymentQuery) {
            $hasLinkedSource = false;

            if ($this->hasPaymentInvoiceColumn()) {
                $hasLinkedSource = true;
                $linkedPaymentQuery->whereHas('invoice');
            }

            if ($this->hasPaymentRentalColumn()) {
                $hasLinkedSource = true;

                if ($this->hasPaymentInvoiceColumn()) {
                    $linkedPaymentQuery->orWhereHas('rental');
                } else {
                    $linkedPaymentQuery->whereHas('rental');
                }
            }

            if (!$hasLinkedSource) {
                $linkedPaymentQuery->whereRaw('1 = 0');
            }
        });

        if ($includeRelations) {
            $with = [];

            if ($this->hasPaymentCustomerColumn()) {
                $with[] = 'customer';
            }

            if ($this->hasPaymentInvoiceColumn()) {
                $with[] = 'invoice';
            }

            if ($this->hasPaymentRentalColumn()) {
                $with[] = 'rental';
            }

            if ($with !== []) {
                $query->with($with);
            }
        }

        $search = trim((string) $request->get('search', ''));
        $city = trim((string) $request->get('city', ''));
        $customerId = $request->get('customer_id', '');
        [$fromDate, $toDate] = $this->normalizedDateFilters($request);

        if ($search !== '') {
            $query->where(function ($paymentQuery) use ($search) {
                $paymentQuery->where('notes', 'like', "%{$search}%");

                if ($this->hasPaymentCustomerColumn()) {
                    $paymentQuery->orWhereHas('customer', function ($customerQuery) use ($search) {
                        $customerQuery
                            ->where('name', 'like', "%{$search}%")
                            ->orWhere('phone', 'like', "%{$search}%")
                            ->orWhere('whatsapp_number', 'like', "%{$search}%")
                            ->orWhere('city', 'like', "%{$search}%");
                    });
                }

                if ($this->hasPaymentInvoiceColumn()) {
                    $paymentQuery->orWhereHas('invoice', function ($invoiceQuery) use ($search) {
                        $invoiceQuery->where('invoice_number', 'like', "%{$search}%");
                    });
                }

                if ($this->hasPaymentRentalColumn()) {
                    $paymentQuery->orWhereHas('rental', function ($rentalQuery) use ($search) {
                        $rentalQuery
                            ->where('customer_name', 'like', "%{$search}%")
                            ->orWhere('phone', 'like', "%{$search}%");
                    });
                }
            });
        }

        if ($city !== '' && $this->hasPaymentCustomerColumn()) {
            $query->whereHas('customer', function ($customerQuery) use ($city) {
                $customerQuery->where('city', 'like', "%{$city}%");
            });
        }

        if (filled($customerId)) {
            if ($this->hasPaymentCustomerColumn()) {
                $query->where('customer_id', $customerId);
            } elseif ($this->hasPaymentRentalColumn()) {
                $query->whereHas('rental', function ($rentalQuery) use ($customerId) {
