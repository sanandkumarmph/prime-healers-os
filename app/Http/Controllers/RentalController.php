    private function applyRentalSorting($query, string $sortBy)
    {
        return match ($sortBy) {
            'oldest' => $query->orderBy('created_at'),
            'priority' => $query->orderBy('end_date')->orderByDesc('created_at'),
            'end_date_asc' => $query->orderBy('end_date')->orderByDesc('created_at'),
            'end_date_desc' => $query->orderByDesc('end_date')->orderByDesc('created_at'),
            'customer_asc' => $query->orderBy('customer_name')->orderByDesc('created_at'),
            'customer_desc' => $query->orderByDesc('customer_name')->orderByDesc('created_at'),
            'amount_desc' => $query->orderByRaw('(COALESCE(rental_amount, 0) + COALESCE(deposit_amount, 0) + COALESCE(transport_amount, 0) + COALESCE(other_amount, 0)) DESC'),
            'amount_asc' => $query->orderByRaw('(COALESCE(rental_amount, 0) + COALESCE(deposit_amount, 0) + COALESCE(transport_amount, 0) + COALESCE(other_amount, 0)) ASC'),
            default => $query->latest(),
        };
    }

    private function applyDashboardSalesSorting($query, string $sortBy)
    {
        return match ($sortBy) {
            'oldest' => $query->orderBy('sale_date')->orderBy('id'),
            'amount_desc' => $query->orderByDesc('sale_amount')->orderByDesc('sale_date'),
            'amount_asc' => $query->orderBy('sale_amount')->orderByDesc('sale_date'),
            default => $query->orderByDesc('sale_date')->orderByDesc('id'),
        };
    }

    private function applySimpleDateRangeFilter($query, string $column, string $fromDate, string $toDate)
    {
        if ($fromDate !== '') {
            $query->whereDate($column, '>=', $fromDate);
        }

        if ($toDate !== '') {
            $query->whereDate($column, '<=', $toDate);
        }

        return $query;
    }

    private function filteredSalesQuery(Request $request, bool $includeRelations = false)
    {
        $query = Sale::query()
            ->where('organization_id', $this->orgId());

        if ($includeRelations) {
            $query->with(['customer', 'product']);
        }

        $search = trim((string) $request->get('search', ''));
        $city = trim((string) $request->get('city', ''));
        $customerId = $request->get('customer_id', '');
        [$fromDate, $toDate] = $this->normalizedDateFilters($request);

        if ($search !== '') {
            $query->where(function ($salesQuery) use ($search) {
                $salesQuery->where('id', $search)
                    ->orWhere('notes', 'like', "%{$search}%")
                    ->orWhereHas('product', function ($productQuery) use ($search) {
                        $productQuery->where('name', 'like', "%{$search}%");
                    })
                    ->orWhereHas('customer', function ($customerQuery) use ($search) {
                        $customerQuery
                            ->where('name', 'like', "%{$search}%")
                            ->orWhere('phone', 'like', "%{$search}%")
                            ->orWhere('whatsapp_number', 'like', "%{$search}%")
                            ->orWhere('city', 'like', "%{$search}%");
                    });
            });
        }

        if ($city !== '') {
            $query->whereHas('customer', function ($customerQuery) use ($city) {
                $customerQuery->where('city', 'like', "%{$city}%");
            });
        }

        if (filled($customerId)) {
            $query->where('customer_id', $customerId);
        }

        return $this->applySimpleDateRangeFilter($query, 'sale_date', $fromDate, $toDate);
    }

