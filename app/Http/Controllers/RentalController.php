    private function reconcileCompletedPickupProgress(Rental $rental): void
    {
        if (!$this->hasRentalItemsTable()) {
            return;
        }

        $pickupRecord = $rental->relationLoaded('pickupRecord')
            ? $rental->getRelation('pickupRecord')
            : $rental->pickupRecord()->first();

        if (!$pickupRecord || $pickupRecord->status !== 'completed') {
            return;
        }

        if ($rental->pendingPickupQuantityTotal() <= 0) {
            return;
        }

        $timestamp = optional($pickupRecord->completed_at)->toDateTimeString() ?: now()->toDateTimeString();

        $products = Product::query()
            ->where('organization_id', $this->orgId())
            ->whereIn('id', $rental->rentalItems()->pluck('product_id')->filter()->unique()->values())
            ->get()
            ->keyBy('id');

        foreach ($this->loadRentalProgressItems($rental) as $item) {
            $outstandingQuantity = max((int) $item->delivered_quantity_value - (int) $item->returned_quantity_value, 0);

            if ($outstandingQuantity <= 0) {
                continue;
            }

            /** @var Product|null $product */
            $product = $products->get((int) $item->product_id);
            $assetIds = $this->normalizeAssetIds($item->asset_ids ?? []);

            $item->update([
                'returned_quantity' => min($item->delivered_quantity_value, $item->returned_quantity_value + $outstandingQuantity),
            ]);

            if ($this->hasRentalAssetsTable() && !empty($assetIds)) {
                $assignments = $rental->activeRentalAssets()
                    ->with('asset')
                    ->whereIn('asset_id', $assetIds)
                    ->get();

                foreach ($assignments as $assignment) {
                    $asset = $assignment->asset;

                    if (!$asset) {
                        continue;
                    }

                    $assignment->update([
                        'returned_at' => $timestamp,
                        'return_condition' => $asset->condition_status,
                        'notes' => trim(($assignment->notes ? $assignment->notes . ' | ' : '') . 'Reconciled after completed pickup and awaiting verification.'),
                    ]);

                    $asset->update(['asset_status' => Asset::STATUS_AWAITING_VERIFICATION]);
                }
            } elseif ($product?->usesUntrackedStock()) {
                Product::query()
                    ->where('organization_id', $this->orgId())
                    ->where('id', $item->product_id)
                    ->increment('available_quantity', $outstandingQuantity);
            }
        }

        $rental->unsetRelation('rentalItems');

        // Imported/legacy rentals may have active tracked assignments without
        // item-level asset_ids. Completed pickup should still move them to
        // awaiting verification instead of directly back to available stock.
        if ($this->hasRentalAssetsTable() && $rental->activeRentalAssets()->exists()) {
            $activeAssignments = $rental->activeRentalAssets()
                ->with('asset')
                ->get();

            foreach ($activeAssignments as $assignment) {
                $asset = $assignment->asset;

                if (!$asset) {
                    continue;
                }

                $assignment->update([
                    'returned_at' => $timestamp,
                    'return_condition' => $asset->condition_status,
                    'notes' => trim(($assignment->notes ? $assignment->notes . ' | ' : '') . 'Reconciled after completed pickup and awaiting verification.'),
                ]);

                $asset->update(['asset_status' => Asset::STATUS_AWAITING_VERIFICATION]);
            }
        }

        if ($rental->deliveredQuantityTotal() > 0 && $rental->pendingPickupQuantityTotal() === 0 && $rental->status !== 'returned') {
            $rental->update([
                'status' => 'returned',
                'returned_at' => $timestamp,
            ]);
        }
    }

    private function reconcileCompletedDeliveryProgress(Rental $rental): void
    {
        if (!$this->hasRentalItemsTable()) {
            return;
        }

        $deliveryRecord = $rental->relationLoaded('deliveryRecord')
            ? $rental->getRelation('deliveryRecord')
            : $rental->deliveryRecord()->first();

        if (!$deliveryRecord || $deliveryRecord->status !== 'completed') {
            return;
        }

        if ($rental->deliveredQuantityTotal() > 0) {
            return;
        }

        $this->markImportedRentalDelivered($rental);
    }

    private function baseRentalQuery(bool $includeRelations = true, bool $applyScope = true)
    {
        $query = Rental::query()->forOrganization($this->orgId());

        if ($applyScope) {
            $query = $this->applyRentalScope($query);
        }

        $query->select('rentals.*');

        $query->selectSub(
            Invoice::query()
                ->selectRaw('COALESCE(SUM(invoices.balance_amount), 0)')
                ->join('invoice_items', 'invoice_items.invoice_id', '=', 'invoices.id')
                ->whereColumn('invoice_items.source_id', 'rentals.id')
                ->where('invoice_items.source_type', 'rental')
                ->where('invoices.organization_id', $this->orgId())
                ->whereNotIn('invoices.payment_status', ['paid', 'cancelled']),
            'outstanding_invoice_balance'
        );

        if (Rental::hasReminderLogsTable()) {
            $query->selectSub(
                RentalReminderLog::query()
                    ->selectRaw('MAX(sent_at)')
                    ->whereColumn('rental_id', 'rentals.id')
                    ->where('organization_id', $this->orgId()),
                'latest_reminder_sent_at'
            );
        }

        if ($includeRelations) {
            $with = [
                'product',
                'customer',
                'deliveries',
                'deliveryRecord.assignedStaff',
                'deliveryRecord.assignedUser',
                'pickupRecord.assignedStaff',
                'pickupRecord.assignedUser',
                'deliveryStaff',
                'pickupStaff',
                'dispatchWarehouse',
                'createdBy',
            ];

            if ($this->hasRentalAssetsTable()) {
                $with[] = 'activeRentalAssets.asset.warehouse';
            }

            if ($this->hasRentalRenewalsTable()) {
                $with[] = 'renewals';
            }

            if ($this->hasRentalItemsTable()) {
                $with[] = 'rentalItems.product';
            }

            $query->with($with);
        }

        return $query;
    }

    private function normalizedDateFilters(Request $request): array
    {
        $singleDate = trim((string) $request->get('date', ''));
        $fromDate = trim((string) $request->get('from_date', ''));
        $toDate = trim((string) $request->get('to_date', ''));

        if ($singleDate !== '') {
            $fromDate = $fromDate !== '' ? $fromDate : $singleDate;
            $toDate = $toDate !== '' ? $toDate : $singleDate;
        }

        return [$fromDate, $toDate];
    }

    private function applyDateRangeFilter($query, string $fromDate, string $toDate)
    {
        if ($fromDate !== '' && $toDate !== '') {
            return $query
                ->whereDate('start_date', '<=', $toDate)
                ->whereDate('end_date', '>=', $fromDate);
        }

        if ($fromDate !== '') {
            return $query->whereDate('end_date', '>=', $fromDate);
        }

        if ($toDate !== '') {
            return $query->whereDate('start_date', '<=', $toDate);
        }

        return $query;
    }

    private function applyLifecycleFilters($query, Request $request)
    {
        $today = Carbon::today();
        $search = trim((string) $request->get('search', ''));
        $status = (string) $request->get('status', '');
        $filter = (string) $request->get('filter', '');
        $deliveryStatus = (string) $request->get('delivery_status', '');
        $pickupStatus = (string) $request->get('pickup_status', '');
        $warehouseId = $request->get('dispatch_warehouse_id', '');
        $city = trim((string) $request->get('city', ''));
        $vendorId = $request->get('vendor_id', '');
        $customerId = $request->get('customer_id', '');
        [$fromDate, $toDate] = $this->normalizedDateFilters($request);

        if ($search !== '') {
            $query->where(function ($q) use ($search) {
                $q->where('customer_name', 'like', "%{$search}%")
                    ->orWhere('phone', 'like', "%{$search}%")
                    ->orWhere('id', $search)
                    ->orWhereHas('product', function ($productQuery) use ($search) {
                        $productQuery->where('name', 'like', "%{$search}%");
                    })
                    ->orWhereHas('customer', function ($customerQuery) use ($search) {
                        $customerQuery->where('city', 'like', "%{$search}%")
                            ->orWhere('email', 'like', "%{$search}%");
                    });

                if ($this->hasRentalAssetsTable()) {
                    $q->orWhereHas('activeRentalAssets.asset', function ($assetQuery) use ($search) {
                        $assetQuery->where('serial_number', 'like', "%{$search}%")
                            ->orWhere('barcode_value', 'like', "%{$search}%");
                    });
                }
            });
        }

        $this->applyDateRangeFilter($query, $fromDate, $toDate);

        if ($city !== '') {
            $query->whereHas('customer', function ($customerQuery) use ($city) {
                $customerQuery->where('city', 'like', "%{$city}%");
            });
        }

        if (filled($customerId)) {
            $query->where('customer_id', $customerId);
        }

        if ($this->hasDispatchWarehouseColumn() && filled($warehouseId)) {
            $query->where('dispatch_warehouse_id', $warehouseId);
        }

        if (filled($vendorId)) {
            $this->applyVendorFilterToRentalQuery($query, (int) $vendorId);
        }

        if (filled($deliveryStatus)) {
            $query->whereHas('deliveryRecord', function ($deliveryQuery) use ($deliveryStatus) {
                $deliveryQuery
                    ->where('status', $deliveryStatus);
            });
        }

        if (filled($pickupStatus)) {
            $query->whereHas('pickupRecord', function ($deliveryQuery) use ($pickupStatus) {
                $deliveryQuery
                    ->where('status', $pickupStatus);
            });
        }

        switch ($filter) {
            case 'ending_soon':
                return $query->endingSoon($today);

            case 'overdue':
                return $query->overdue($today);

            case 'returns_due_today':
                return $query->where('status', 'active')
                    ->whereDate('end_date', $today)
                    ->lifecycleStarted();

            case 'pending_delivery':
                return $query->whereHas('deliveryRecord', function ($deliveryQuery) {
                    $deliveryQuery
                        ->where('status', 'pending');
                });

            case 'out_for_delivery':
                return $query->whereHas('deliveryRecord', function ($deliveryQuery) {
                    $deliveryQuery
                        ->where('status', 'in_progress');
                });

            case 'pending_pickup':
                return $query->whereHas('pickupRecord', function ($deliveryQuery) {
                    $deliveryQuery
                        ->where('status', 'pending');
                });

            case 'out_for_pickup':
                return $query->whereHas('pickupRecord', function ($deliveryQuery) {
                    $deliveryQuery
                        ->where('status', 'in_progress');
                });

            case 'delivered':
                return $query->whereHas('deliveryRecord', function ($deliveryQuery) {
                    $deliveryQuery
                        ->where('status', 'completed');
                });
        }

        switch ($status) {
            case 'live':
                return $query->where('status', 'active')->lifecycleStarted();

            case 'active':
                return $query->effectivelyActive($today);

            case 'overdue':
                return $query->overdue($today);

            case 'delivery_pending':
                return $query->whereHas('deliveryRecord', function ($deliveryQuery) {
                    $deliveryQuery->whereIn('status', ['pending', 'assigned']);
                });

            case 'returned':
                return $query->where('status', 'returned');

            case 'delivered':
                return $query->whereHas('deliveryRecord', function ($deliveryQuery) {
                    $deliveryQuery
                        ->where('status', 'completed');
                });
        }

        return $query;
    }

    public function openReminder(Request $request, Rental $rental, string $type = 'renewal')
    {
        $rental = $this->scopedRental($rental);
        $rental->loadMissing(['product', 'customer', 'businessPartner', 'partnerClient']);

        $normalizedType = strtolower(trim($type));
        $normalizedNumber = WhatsAppHelper::normalizeNumber($rental->reminderContactPhone());

        abort_if(!$normalizedNumber, 404, 'Customer WhatsApp number not available.');

        $message = match ($normalizedType) {
            'delivery' => WhatsAppHelper::rentalDeliveryConfirmation($rental),
            'pickup' => WhatsAppHelper::rentalPickupReminder($rental),
            'overdue' => trim(
                WhatsAppHelper::rentalRenewalReminder($rental)
                . ' Your rental is now overdue. Please clear outstanding dues or coordinate immediate pickup.'
            ),
            default => WhatsAppHelper::rentalRenewalReminder($rental),
        };

        if (Rental::hasReminderLogsTable()) {
            RentalReminderLog::create([
                'organization_id' => $this->orgId(),
                'rental_id' => $rental->id,
                'customer_id' => $rental->customer_id,
                'reminder_type' => $normalizedType,
                'sent_via' => 'whatsapp',
                'sent_to_number' => $normalizedNumber,
                'message_preview' => $message,
                'sent_by_user_id' => auth()->id(),
                'sent_at' => now(),
            ]);
        }

        ActivityLogger::log('rental.reminder.opened', $rental, [
            'reminder_type' => $normalizedType,
            'sent_via' => 'whatsapp',
            'sent_to_number' => $normalizedNumber,
        ], 'WhatsApp rental reminder opened.');

        return redirect()->away(WhatsAppHelper::chatUrl($normalizedNumber, $message));
    }

