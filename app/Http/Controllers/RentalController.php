    private function restoreRentalSaleItemsStock(Rental $rental): void
    {
        if (!$this->hasRentalSaleItemsTable()) {
            return;
        }

        $rental->loadMissing(['saleItems.product', 'saleItems.asset']);

        foreach ($rental->saleItems as $saleItem) {
            $product = $saleItem->product;

            if (!$product || (int) $product->organization_id !== $this->orgId()) {
                continue;
            }

            if ($product->tracksSaleStock()) {
                if ($saleItem->asset_id) {
                    $asset = Asset::query()
                        ->where('organization_id', $this->orgId())
                        ->lockForUpdate()
                        ->find($saleItem->asset_id);

                    if ($asset && $asset->asset_stage === Asset::STAGE_NEW_STOCK) {
                        $asset->update(['asset_status' => 'available_for_sale']);
                    }
                }

                SaleInventory::syncFromSaleUnits($this->orgId(), $product->id);
                $product->refresh();
                $product->syncLegacyStockFields();
                continue;
            }

            $inventory = null;

            if ($saleItem->warehouse_id) {
                $inventory = SaleInventory::query()
                    ->where('organization_id', $this->orgId())
                    ->where('product_id', $product->id)
                    ->where('warehouse_id', $saleItem->warehouse_id)
                    ->lockForUpdate()
                    ->first();
            }

            if ($inventory) {
                $inventory->increment('quantity_in_stock', (int) $saleItem->quantity);
                $product->syncLegacyStockFields();
            } else {
                $product->increment('available_quantity', (int) $saleItem->quantity);
            }

            if ($saleItem->asset_id) {
                $asset = Asset::query()
                    ->where('organization_id', $this->orgId())
                    ->lockForUpdate()
                    ->find($saleItem->asset_id);

                if ($asset && $asset->asset_stage === Asset::STAGE_NEW_STOCK) {
                    $asset->update(['asset_status' => 'available_for_sale']);
                }
            }
        }

        $rental->saleItems()->delete();
        $rental->unsetRelation('saleItems');
    }

    private function trackedRentalSaleAllocationError(Product $product): ValidationException
    {
        return ValidationException::withMessages([
            'sale_items' => ['Tracked sale product requires available sale asset units. Add stock or convert rental asset to sale stock first.'],
        ]);
    }

    private function allocateTrackedRentalSaleAsset(Product $product, int $quantity, ?int $warehouseId = null, ?int $explicitAssetId = null): Asset
    {
        if ($quantity !== 1) {
            throw ValidationException::withMessages([
                'sale_items' => ['Tracked sale items inside rentals currently require one serialized sale asset per line. Split the quantity into single-unit lines or add a direct sale entry.'],
            ]);
        }

        $baseQuery = Asset::query()
            ->where('organization_id', $this->orgId())
            ->where('product_id', $product->id)
            ->where('asset_stage', Asset::STAGE_NEW_STOCK);

        if ($explicitAssetId) {
            $asset = (clone $baseQuery)
                ->lockForUpdate()
                ->findOrFail($explicitAssetId);

            if ($asset->asset_status !== 'available_for_sale') {
                throw $this->trackedRentalSaleAllocationError($product);
            }

            return $asset;
        }

        $asset = (clone $baseQuery)
            ->where('asset_status', 'available_for_sale')
            ->when($warehouseId, fn ($query) => $query->where('warehouse_id', $warehouseId))
            ->orderBy('serial_number')
            ->orderBy('id')
            ->lockForUpdate()
            ->first();

        if (!$asset) {
            throw $this->trackedRentalSaleAllocationError($product);
        }

        return $asset;
    }

