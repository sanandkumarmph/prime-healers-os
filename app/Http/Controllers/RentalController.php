    public function describeImportedRentalMatch(array $attributes): array
    {
        $customerId = (int) ($attributes['customer_id'] ?? 0);
        $productId = (int) ($attributes['product_id'] ?? 0);
        $quantity = max((int) ($attributes['quantity'] ?? 0), 1);
        $startDate = $attributes['start_date'] ?? null;
        $endDate = $attributes['end_date'] ?? null;
        $dispatchWarehouseId = filled($attributes['dispatch_warehouse_id'] ?? null)
            ? (int) $attributes['dispatch_warehouse_id']
            : null;
        $assetIds = $this->normalizeAssetIds($attributes['asset_ids'] ?? []);

        if ($customerId <= 0 || $productId <= 0 || blank($startDate) || blank($endDate)) {
            return ['action' => 'create', 'rental' => null, 'message' => null];
        }

        $candidates = Rental::query()
            ->where('organization_id', $this->orgId())
            ->where('customer_id', $customerId)
            ->where('product_id', $productId)
            ->whereDate('start_date', $startDate)
            ->whereDate('end_date', $endDate)
            ->where('quantity', $quantity)
            ->when($this->hasDispatchWarehouseColumn() && $dispatchWarehouseId, fn ($query) => $query->where('dispatch_warehouse_id', $dispatchWarehouseId))
            ->with(['rentalAssets', 'invoice.payments'])
            ->get();

        if (!empty($assetIds)) {
            $requestedAssetIds = collect($assetIds)->map(fn ($id) => (int) $id)->sort()->values()->all();
            $candidates = $candidates->filter(function (Rental $rental) use ($requestedAssetIds) {
                $existingAssetIds = $rental->rentalAssets
                    ->pluck('asset_id')
                    ->filter()
                    ->map(fn ($id) => (int) $id)
                    ->sort()
                    ->values()
                    ->all();

                return $existingAssetIds === $requestedAssetIds;
            })->values();
        }

        if ($candidates->isEmpty()) {
            return ['action' => 'create', 'rental' => null, 'message' => null];
        }

        if ($candidates->count() > 1) {
            return [
                'action' => 'review',
                'rental' => null,
                'message' => 'Multiple rentals match this import row. Add a unique serial/asset reference or review manually.',
            ];
        }

        $rental = $candidates->first();
        $invoice = $rental?->invoice ?? $this->rentalInvoice($rental);
        $paymentReview = $invoice ? $this->importedRentalPaymentReviewMessage($rental, $invoice, $attributes) : null;

        if ($paymentReview) {
            return [
                'action' => 'review',
                'rental' => $rental,
                'message' => $paymentReview,
            ];
        }

        return ['action' => 'update', 'rental' => $rental, 'message' => null];
    }

