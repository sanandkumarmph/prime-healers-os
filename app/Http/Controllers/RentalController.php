                'partner_client_id' => $customerContext['partner_client']?->id,
                'customer_name' => $customerContext['customer_name'],
                'phone' => $customerContext['phone'],
                'product_id' => $request->product_id,
                'delivery_staff_id' => $deliveryAssignment['staff_id'],
                'pickup_staff_id' => $request->pickup_staff_id,
                'quantity' => $request->quantity,
                'start_date' => $request->start_date,
                'end_date' => $request->end_date,
                'rental_amount' => $request->rental_amount ?? 0,
                'deposit_amount' => $request->deposit_amount ?? 0,
                'transport_amount' => $request->transport_amount ?? 0,
                'other_amount' => $request->other_amount ?? 0,
            ]);

            if ($this->hasDispatchWarehouseColumn()) {
                $rental->forceFill([
                    'dispatch_warehouse_id' => $request->dispatch_warehouse_id,
                ])->save();
            }

            $deliveryAssignmentUpdates = [];

            if ($this->hasDeliveryAssignmentTypeColumn()) {
                $deliveryAssignmentUpdates['assignment_type'] = $deliveryAssignment['user_id']
                    ? 'delivery_team'
                    : (($deliveryAssignment['type'] ?? null) === 'third_party'
                        ? 'third_party'
                        : (($deliveryAssignment['staff_role'] ?? null) === 'third_party' ? 'third_party' : ($deliveryAssignment['staff_id'] ? 'vendor' : 'delivery_team')));
            }

            if ($this->hasDeliveryAssignedUserColumn()) {
                $deliveryAssignmentUpdates['assigned_user_id'] = $deliveryAssignment['user_id'];
            }

            if ($this->hasDeliveryAssignedStaffColumn()) {
                $deliveryAssignmentUpdates['assigned_staff_id'] = $deliveryAssignment['staff_id'];
            }

            if ($this->hasDeliveryThirdPartyNameColumn()) {
                $deliveryAssignmentUpdates['third_party_name'] = ($deliveryAssignment['type'] ?? null) === 'third_party'
                    ? $request->input('third_party_name')
                    : null;
            }

            if ($this->hasDeliveryThirdPartyContactColumn()) {
                $deliveryAssignmentUpdates['third_party_contact'] = ($deliveryAssignment['type'] ?? null) === 'third_party'
                    ? $request->input('third_party_contact')
                    : null;
            }

            if ($this->hasDeliveryThirdPartyPhoneColumn()) {
                $deliveryAssignmentUpdates['third_party_phone'] = ($deliveryAssignment['type'] ?? null) === 'third_party'
                    ? $request->input('third_party_phone')
                    : null;
            }

            if (!empty($deliveryAssignmentUpdates)) {
                $rental->deliveries()
                    ->where('type', 'delivery')
                    ->where('status', '!=', 'completed')
                    ->update($deliveryAssignmentUpdates);
            }

            if ($this->hasDeliveryAssignedStaffColumn()) {
                $rental->deliveries()
                    ->where('type', 'pickup')
                    ->where('status', '!=', 'completed')
                    ->update(['assigned_staff_id' => $request->pickup_staff_id]);
            }

            $this->persistRentalItems($rental, $rentalItems);
            $this->syncRentalAssets($rental, $selectedAssets);
            $this->restoreRentalSaleItemsStock($rental);
            $this->syncRentalSaleItems($rental, $saleItems);
            $this->syncAutoGeneratedRentalSales($rental);

            $linkedInvoice = $this->rentalInvoice($rental->fresh());
            if ($linkedInvoice) {
                $this->syncRentalInvoiceFromRental($rental->fresh(), $linkedInvoice->fresh());
            }
        });

        ActivityLogger::log('rental.updated', $rental->fresh()->loadMissing(['customer', 'businessPartner', 'partnerClient']), [
            'status' => $rental->status,
            'rental_amount' => $rental->rental_amount,
        ], 'Rental details updated.');

        return redirect()->route('rentals.show', $rental)->with('success', 'Rental updated successfully.');
    }

    public function returnRental(Rental $rental)
    {
        $rental = $this->scopedRental($rental);
        $rental->loadMissing('deliveryRecord');

        if ($rental->status === 'returned') {
            return redirect('/rentals')->with('success', 'Rental already returned.');
        }

        if (!$rental->canBeReturned()) {
            return redirect('/rentals')->with('error', 'This rental cannot be returned until delivery is completed.');
        }

        DB::transaction(function () use ($rental) {
            $this->releaseRentalAssets($rental);

            $this->restoreRentalItemStock($rental);

            $rental->update([
                'status' => 'returned',
                'returned_at' => now(),
            ]);

            $existingPickup = Delivery::where('organization_id', $this->orgId())
                ->where('rental_id', $rental->id)
                ->where('type', 'pickup')
                ->first();

            if (!$existingPickup) {
                $latestDelivery = Delivery::where('organization_id', $this->orgId())
                    ->where('rental_id', $rental->id)
                    ->where('type', 'delivery')
                    ->latest()
                    ->first();

                $assignmentType = 'delivery_team';
                $assignedUserId = null;
                $thirdPartyName = null;
                $thirdPartyContact = null;
                $thirdPartyPhone = null;

                if ($latestDelivery && $this->hasDeliveryAssignmentTypeColumn()) {
                    if ($latestDelivery->assignment_type === 'vendor') {
                        $assignmentType = 'vendor';
                        if ($this->hasDeliveryAssignedUserColumn()) {
                            $assignedUserId = $latestDelivery->assigned_user_id;
                        }
                    } elseif ($latestDelivery->assignment_type === 'third_party') {
                        $assignmentType = 'third_party';
                        if ($this->hasDeliveryThirdPartyNameColumn()) {
                            $thirdPartyName = $latestDelivery->third_party_name;
                        }
                        if ($this->hasDeliveryThirdPartyContactColumn()) {
                            $thirdPartyContact = $latestDelivery->third_party_contact;
                        }
                        if ($this->hasDeliveryThirdPartyPhoneColumn()) {
                            $thirdPartyPhone = $latestDelivery->third_party_phone;
                        }
                    }
                }

                $pickupData = [
                    'organization_id' => $this->orgId(),
                    'rental_id' => $rental->id,
                    'type' => 'pickup',
                    'scheduled_at' => now(),
                    'status' => 'pending',
                    'notes' => 'Auto-created when rental was returned.',
                ];

                if ($this->hasDeliveryAssignmentTypeColumn()) {
                    $pickupData['assignment_type'] = $assignmentType;
                }

                if ($this->hasDeliveryAssignedUserColumn()) {
                    $pickupData['assigned_user_id'] = $assignedUserId;
                }

                if ($this->hasDeliveryAssignedStaffColumn()) {
                    $pickupData['assigned_staff_id'] = $rental->pickup_staff_id;
                }

                if ($this->hasDeliveryThirdPartyNameColumn()) {
                    $pickupData['third_party_name'] = $thirdPartyName;
                }

                if ($this->hasDeliveryThirdPartyContactColumn()) {
                    $pickupData['third_party_contact'] = $thirdPartyContact;
                }

                if ($this->hasDeliveryThirdPartyPhoneColumn()) {
                    $pickupData['third_party_phone'] = $thirdPartyPhone;
                }

                Delivery::create($pickupData);
            }
        });

        ActivityLogger::log('rental.returned', $rental->refresh(), [
            'returned_at' => optional($rental->returned_at)->toDateTimeString(),
        ], 'Rental marked as returned.');

        return redirect('/rentals')->with('success', 'Rental returned successfully and pickup created automatically.');
    }

    public function cancel(Rental $rental)
    {
        $rental = $this->scopedRental($rental);

        if (in_array($rental->status, ['returned', 'cancelled'], true)) {
            return redirect()->route('rentals.show', $rental)->with('error', 'This rental is already closed.');
        }

        DB::transaction(function () use ($rental) {
            $this->releaseRentalAssets($rental);

            $this->restoreRentalItemStock($rental);

            Delivery::where('organization_id', $this->orgId())
                ->where('rental_id', $rental->id)
                ->whereIn('status', ['pending', 'in_progress'])
                ->update([
                    'status' => 'cancelled',
                    'completed_at' => null,
                ]);

            $rental->update([
                'status' => 'cancelled',
                'return_notes' => trim(($rental->return_notes ? $rental->return_notes . ' | ' : '') . 'Rental cancelled.'),
            ]);
        });

        ActivityLogger::log('rental.cancelled', $rental->refresh(), [
            'status' => $rental->status,
        ], 'Rental cancelled.');

        return redirect()->route('rentals.show', $rental)->with('success', 'Rental cancelled successfully.');
    }

    public function clearDeliveryAssignment(Rental $rental)
    {
        $rental = $this->scopedRental($rental);

        $hasDeliveryTask = Delivery::query()
            ->where('organization_id', $this->orgId())
            ->where('rental_id', $rental->id)
            ->where('type', 'delivery')
            ->exists();

        if ($hasDeliveryTask) {
            return redirect()
                ->route('rentals.show', $rental)
                ->with('error', 'A delivery task exists for this rental. Cancel or delete the delivery task instead.');
        }

        if (!$rental->delivery_staff_id) {
            return redirect()
                ->route('rentals.show', $rental)
                ->with('info', 'No legacy delivery assignment was found on this rental.');
        }

        $previousStaffId = $rental->delivery_staff_id;
        $rental->update(['delivery_staff_id' => null]);

        ActivityLogger::log('rental.delivery_assignment.cleared', $rental->refresh(), [
            'previous_delivery_staff_id' => $previousStaffId,
        ], 'Legacy delivery assignment cleared.');

        return redirect()->route('rentals.show', $rental)->with('success', 'Delivery assignment cleared successfully.');
    }

    private function rentalDeletionBlockers(Rental $rental): array
    {
        $blockers = [];

        if (Schema::hasTable('invoice_items') && Schema::hasTable('invoices')) {
            $hasInvoices = DB::table('invoice_items')
                ->join('invoices', 'invoices.id', '=', 'invoice_items.invoice_id')
                ->where('invoices.organization_id', $this->orgId())
                ->where('invoice_items.source_type', 'rental')
                ->where('invoice_items.source_id', $rental->id)
                ->exists();

            if ($hasInvoices) {
                $blockers[] = 'linked invoices';
            }
        }

        if (Schema::hasTable('payments') && Schema::hasColumn('payments', 'rental_id')) {
            $hasPayments = Payment::query()
                ->when(Schema::hasColumn('payments', 'organization_id'), fn ($query) => $query->where('organization_id', $this->orgId()))
                ->where('rental_id', $rental->id)
                ->exists();

            if ($hasPayments) {
                $blockers[] = 'payments';
            }
        }

        if (Schema::hasTable('deliveries') && Schema::hasColumn('deliveries', 'rental_id')) {
            $hasDeliveries = Delivery::query()
                ->where('organization_id', $this->orgId())
                ->where('rental_id', $rental->id)
                ->where('status', '!=', 'cancelled')
                ->exists();

            if ($hasDeliveries) {
                $blockers[] = 'active delivery or pickup tasks';
            }
        }

        if (Schema::hasTable('sales') && Schema::hasColumn('sales', 'rental_id')) {
            $hasLinkedSales = Sale::query()
                ->where('organization_id', $this->orgId())
                ->where('rental_id', $rental->id)
                ->when($this->hasSalesAutoGeneratedColumn(), function ($query) {
                    $query->where(function ($salesQuery) {
                        $salesQuery->where('auto_generated_from_rental', false)
                            ->orWhereNull('auto_generated_from_rental');
                    });
                })
                ->exists();

            if ($hasLinkedSales) {
                $blockers[] = 'linked sales';
            }
        }

        return $blockers;
    }

    public function destroy(Rental $rental)
    {
        $rental = $this->scopedRental($rental);
        $this->authorize('delete', $rental);
        $blockers = $this->rentalDeletionBlockers($rental);

        if (!empty($blockers)) {
            return redirect()
                ->back()
                ->with('error', 'Cannot delete this rental because it has ' . implode(', ', $blockers) . '. Use Cancel Rental instead to preserve audit history.');
        }

        DB::transaction(function () use ($rental) {
            $this->deleteAutoGeneratedRentalSales($rental);
            $this->restoreRentalSaleItemsStock($rental);

            $this->releaseRentalAssets($rental);

            if (!in_array($rental->status, ['cancelled', 'returned'], true)) {
                $this->restoreRentalItemStock($rental);
            } elseif ($this->hasRentalItemsTable()) {
                $rental->rentalItems()->delete();
            }

            if ($this->hasRentalAssetsTable()) {
                RentalAsset::query()
                    ->where('organization_id', $this->orgId())
                    ->where('rental_id', $rental->id)
                    ->delete();
            }

            if (Schema::hasTable('deliveries') && Schema::hasColumn('deliveries', 'rental_id')) {
                Delivery::query()
                    ->where('organization_id', $this->orgId())
                    ->where('rental_id', $rental->id)
                    ->where('status', 'cancelled')
                    ->delete();
            }

            if (Rental::hasRenewalsTable()) {
                RentalRenewal::query()
                    ->where('organization_id', $this->orgId())
                    ->where('rental_id', $rental->id)
                    ->delete();
            }

            if (Rental::hasReminderLogsTable()) {
                RentalReminderLog::query()
                    ->where('organization_id', $this->orgId())
                    ->where('rental_id', $rental->id)
                    ->delete();
            }

            if (Schema::hasTable('activity_logs') && Schema::hasColumn('activity_logs', 'rental_id')) {
                DB::table('activity_logs')
                    ->where('organization_id', $this->orgId())
                    ->where('rental_id', $rental->id)
                    ->delete();
            }

            $rental->delete();
        });

        return redirect()->route('rentals.index')->with('success', 'Rental deleted successfully.');
    }
