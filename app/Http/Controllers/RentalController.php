    private function filteredDeliveryQuery(Request $request, bool $includeRelations = false)
    {
        $query = Delivery::query()
            ->where('organization_id', $this->orgId());

        $user = auth()->user();

        if ($user && $user->hasScope('assigned', 'deliveries') && $this->hasDeliveryAssignedUserColumn()) {
            $query->where('assigned_user_id', $user->id);
        }

        if ($includeRelations) {
            $query->with(['rental.customer', 'rental.product', 'assignedStaff']);
        }

        $search = trim((string) $request->get('search', ''));
        $city = trim((string) $request->get('city', ''));
        $vendorId = $request->get('vendor_id', '');
        $warehouseId = $request->get('dispatch_warehouse_id', '');
        $customerId = $request->get('customer_id', '');
        [$fromDate, $toDate] = $this->normalizedDateFilters($request);

        if ($search !== '') {
            $query->where(function ($deliveryQuery) use ($search) {
                $deliveryQuery
                    ->where('notes', 'like', "%{$search}%")
                    ->orWhereHas('rental', function ($rentalQuery) use ($search) {
                        $rentalQuery
                            ->where('id', $search)
                            ->orWhere('customer_name', 'like', "%{$search}%")
                            ->orWhere('phone', 'like', "%{$search}%")
                            ->orWhereHas('product', function ($productQuery) use ($search) {
                                $productQuery->where('name', 'like', "%{$search}%");
                            })
                            ->orWhereHas('customer', function ($customerQuery) use ($search) {
                                $customerQuery->where('city', 'like', "%{$search}%");
                            });
                    });
            });
        }

        if ($city !== '') {
            $query->whereHas('rental.customer', function ($customerQuery) use ($city) {
                $customerQuery->where('city', 'like', "%{$city}%");
            });
        }

        if (filled($customerId)) {
            $query->whereHas('rental', function ($rentalQuery) use ($customerId) {
                $rentalQuery->where('customer_id', $customerId);
            });
        }

        if (filled($vendorId)) {
            $query->where(function ($vendorQuery) use ($vendorId) {
