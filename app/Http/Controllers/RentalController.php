    public function availableAssets(Request $request)
    {
        $this->ensureRentalAccess();

        $validated = $request->validate([
            'product_id' => [
                'required',
                Rule::exists('products', 'id')->where(fn ($query) => $query->where('organization_id', $this->orgId())),
            ],
            'dispatch_warehouse_id' => [
                'nullable',
                Rule::exists('warehouses', 'id')->where(fn ($query) => $query->where('organization_id', $this->orgId())),
            ],
            'rental_id' => [
                'nullable',
                Rule::exists('rentals', 'id')->where(fn ($query) => $query->where('organization_id', $this->orgId())),
            ],
        ]);

        $assetsQuery = Asset::with('warehouse')
            ->where('organization_id', $this->orgId())
            ->where('product_id', $validated['product_id'])
            ->where('asset_stage', Asset::STAGE_RENTAL_STOCK)
            ->when(
                !empty($validated['dispatch_warehouse_id']),
                fn ($query) => $query->where('warehouse_id', $validated['dispatch_warehouse_id'])
            );

        if ($this->hasRentalAssetsTable()) {
            $currentRentalId = $validated['rental_id'] ?? null;
            $assetsQuery
                ->where(function ($query) use ($currentRentalId) {
                    $query->rentalReady();

                    if ($currentRentalId) {
                        $query->orWhereHas('activeRentalAssignments', function ($assignmentQuery) use ($currentRentalId) {
                            $assignmentQuery->where('rental_id', $currentRentalId);
                        });
                    }
                })
                ->where(function ($query) use ($currentRentalId) {
                    $query->whereDoesntHave('activeRentalAssignments');

                    if ($currentRentalId) {
                        $query->orWhereHas('activeRentalAssignments', function ($assignmentQuery) use ($currentRentalId) {
                            $assignmentQuery->where('rental_id', $currentRentalId);
                        });
                    }
                });
        } else {
            $assetsQuery->rentalReady();
        }

        $assets = $assetsQuery
            ->orderBy('serial_number')
            ->get([
                'id',
                'product_id',
                'warehouse_id',
                'asset_name',
                'serial_number',
                'barcode_value',
                'asset_status',
                'condition_status',
            ]);

        return response()->json([
            'data' => $assets->map(fn ($asset) => [
                'id' => $asset->id,
                'label' => $asset->asset_name ?: $asset->serial_number,
                'serial_number' => $asset->serial_number,
                'barcode_value' => $asset->barcode_value,
                'asset_status' => $asset->asset_status,
                'condition_status' => $asset->condition_status,
                'warehouse' => optional($asset->warehouse)->name,
            ])->values(),
        ]);
    }

