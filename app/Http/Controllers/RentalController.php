    private function validateCombinedRentalItemStock(array $items, ?Rental $editingRental = null, ?int $dispatchWarehouseId = null): void
    {
        $grouped = collect($items)
            ->groupBy('product_id')
            ->map(fn ($rows) => (int) $rows->sum('quantity'));

        $editingByProduct = collect();

        if ($editingRental && $this->hasRentalItemsTable()) {
            $editingRental->loadMissing('rentalItems');
            $editingByProduct = $editingRental->rentalItems
                ->groupBy('product_id')
                ->map(fn ($rows) => (int) $rows->sum('quantity'));
        } elseif ($editingRental) {
            $editingByProduct = collect([
                $editingRental->product_id => (int) $editingRental->quantity,
            ]);
        }

        foreach ($grouped as $productId => $requestedQuantity) {
            $product = Product::query()
                ->where('organization_id', $this->orgId())
                ->findOrFail((int) $productId);

            if (!$product->isRentalEligibleForSelection()) {
                throw ValidationException::withMessages([
                    'rental_items' => [$product->name . ' is not available for rental under the current product and stock configuration.'],
                ]);
            }

            $availability = $this->rentalAvailabilityForProduct($product, $dispatchWarehouseId);
            $available = $availability['quantity'] + (int) ($editingByProduct[$productId] ?? 0);

            if (($availability['status'] ?? null) === 'sale_only') {
                throw ValidationException::withMessages([
                    'rental_items' => [$product->name . ' is sale only and cannot be rented.'],
                ]);
            }

            if ($requestedQuantity > $available) {
                $message = $available <= 0
                    ? 'No rental asset is available for ' . $product->name . '. Add rental asset or convert sale unit to rental first.'
                    : 'Only ' . $available . ' rental asset(s) are available for ' . $product->name . '.';

                throw ValidationException::withMessages([
                    'rental_items' => [$message],
                ]);
            }
        }
    }

    private function allowsTrackedRentalSerialPendingLegacyMode(?Rental $editingRental, int $productId): bool
    {
        if (!$editingRental || !$this->hasRentalItemsTable()) {
            return false;
        }

        $editingRental->loadMissing('rentalItems');

        $hasLegacyUnassignedLine = $editingRental->rentalItems->contains(function ($item) use ($productId) {
            if ((int) $item->product_id !== $productId) {
                return false;
            }

            return empty($this->normalizeAssetIds($item->asset_ids ?? []));
        });

        if (!$hasLegacyUnassignedLine) {
            return false;
        }

        if (!$this->hasRentalAssetsTable()) {
            return true;
        }

        return !$editingRental->activeRentalAssets()
            ->whereHas('asset', fn ($query) => $query->where('product_id', $productId))
            ->exists();
    }

    private function validateTrackedRentalAssetAssignments(array $items, ?Rental $editingRental = null): void
    {
        if (empty($items)) {
            return;
        }

        $products = Product::query()
            ->where('organization_id', $this->orgId())
            ->whereIn('id', collect($items)->pluck('product_id')->filter()->unique()->values())
            ->get()
            ->keyBy('id');

        foreach ($items as $item) {
            $productId = (int) ($item['product_id'] ?? 0);
            $quantity = max((int) ($item['quantity'] ?? 0), 0);

            if ($productId <= 0 || $quantity <= 0) {
                continue;
            }

            /** @var Product|null $product */
            $product = $products->get($productId);

            if (!$product || !$product->tracksRentalStock()) {
                continue;
            }

            $assetIds = $this->normalizeAssetIds($item['asset_ids'] ?? []);

            if (count($assetIds) === $quantity) {
                continue;
            }

            if (empty($assetIds) && $this->allowsTrackedRentalSerialPendingLegacyMode($editingRental, $productId)) {
                continue;
            }

            $field = $item['form_asset_field'] ?? 'asset_ids';
            $lineLabel = $item['line_label'] ?? 'rental line';

            throw ValidationException::withMessages([
                $field => ['Tracked rental products require one assigned asset per unit for the ' . $lineLabel . '. Only existing legacy rentals may remain in serial_pending legacy mode until assets are assigned.'],
            ]);
        }
    }

    private function persistRentalItems(Rental $rental, array $items): void
    {
        if (!$this->hasRentalItemsTable()) {
            return;
        }

        $rental->loadMissing('rentalItems');
        $existingByProduct = $rental->rentalItems
            ->groupBy('product_id')
            ->map(fn ($rows) => $rows->values());

        $rental->rentalItems()->delete();

        foreach ($items as $item) {
            $matchedExisting = null;

            if ($existingByProduct->has($item['product_id'])) {
                $existingRows = $existingByProduct->get($item['product_id']);
                $matchedExisting = $existingRows->first();
                $existingByProduct->put($item['product_id'], $existingRows->slice(1)->values());
            }

            $payload = [
                'organization_id' => $this->orgId(),
                'product_id' => $item['product_id'],
                'quantity' => $item['quantity'],
                'ordered_quantity' => $item['quantity'],
                'delivered_quantity' => min((int) ($matchedExisting->delivered_quantity ?? 0), (int) $item['quantity']),
                'returned_quantity' => min((int) ($matchedExisting->returned_quantity ?? 0), (int) $item['quantity']),
                'unit_rental_amount' => $item['unit_rental_amount'],
                'gst_rate' => $item['gst_rate'] ?? 0,
                'gst_mode' => $item['gst_mode'] ?? 'exclusive',
                'tax_type' => $item['tax_type'] ?? Product::GST_TAX_TYPE_CGST_SGST,
                'taxable_amount' => $item['taxable_amount'] ?? 0,
                'cgst_amount' => $item['cgst_amount'] ?? 0,
                'sgst_amount' => $item['sgst_amount'] ?? 0,
                'igst_amount' => $item['igst_amount'] ?? 0,
                'line_total' => $item['line_total'],
                'notes' => $item['notes'],
            ];

            if ($this->hasRentalItemAssetIdsColumn()) {
                $payload['asset_ids'] = $item['asset_ids'] ?? [];
            }

            $rental->rentalItems()->create($payload);
        }

        // Reset the in-memory relation so later helpers see the fresh rows
        // instead of the empty pre-create relation snapshot.
        $rental->unsetRelation('rentalItems');
    }

    private function productsForRentalForm()
    {
        $organizationId = $this->orgId();

        $products = Product::query()
            ->where('organization_id', $organizationId)
            ->orderBy('name')
            ->get();

        if ($products->isEmpty()) {
            return $products;
        }

        $productIds = $products->pluck('id');

        $rentalAssetAvailable = Asset::query()
            ->selectRaw('product_id, COUNT(*) as available_count')
            ->where('organization_id', $organizationId)
            ->rentalReady()
            ->whereIn('product_id', $productIds)
            ->groupBy('product_id')
            ->pluck('available_count', 'product_id');

        $rentalAssetSupportCount = Asset::query()
            ->selectRaw('product_id, COUNT(*) as rental_asset_count')
            ->where('organization_id', $organizationId)
            ->where('asset_stage', Asset::STAGE_RENTAL_STOCK)
            ->whereIn('product_id', $productIds)
            ->groupBy('product_id')
            ->pluck('rental_asset_count', 'product_id');

        $rentalAssetAvailableByWarehouse = Asset::query()
            ->selectRaw('product_id, warehouse_id, COUNT(*) as available_count')
            ->where('organization_id', $organizationId)
            ->rentalReady()
            ->whereIn('product_id', $productIds)
            ->groupBy('product_id', 'warehouse_id')
            ->get()
            ->groupBy('product_id')
            ->map(function ($rows) {
                return $rows->mapWithKeys(function ($row) {
                    return [(string) $row->warehouse_id => (int) $row->available_count];
                })->all();
            });

        return $products->map(function (Product $product) use ($rentalAssetAvailable, $rentalAssetAvailableByWarehouse, $rentalAssetSupportCount) {
            $availability = $this->rentalAvailabilityForProduct(
                $product,
                null,
                (int) ($rentalAssetAvailable[$product->id] ?? 0)
            );

            $product->setAttribute('display_available_quantity', $availability['quantity']);
            $product->setAttribute('rental_available_quantity', $availability['quantity']);
            $product->setAttribute('rental_availability_status', $availability['status']);
            $product->setAttribute('rental_dropdown_label', $availability['label']);
            $product->setAttribute('rental_warehouse_quantities', $rentalAssetAvailableByWarehouse[$product->id] ?? []);
            $product->setAttribute('rental_asset_support_count', (int) ($rentalAssetSupportCount[$product->id] ?? 0));

            return $product;
        });
    }

    private function rentalProductsForSelection($products)
    {
        return $products
            ->filter(function (Product $product) {
                if (!$product->isRentalEligibleForSelection()) {
                    return false;
                }

                if (
                    $product->stock_mode === Product::STOCK_MODE_TRACKED_BOTH
                    && $product->product_type !== Product::TYPE_RENTABLE
                ) {
                    return (int) ($product->rental_asset_support_count ?? 0) > 0;
                }

                return true;
            })
            ->values();
    }

    private function rentalAvailabilityForProduct(Product $product, ?int $warehouseId = null, ?int $preloadedTrackedQuantity = null): array
    {
        if (!$product->isRentalEligibleForSelection()) {
            return [
                'quantity' => 0,
                'status' => 'sale_only',
                'label' => 'Sale only',
            ];
        }

        if ($product->tracksRentalStock()) {
            $quantity = $preloadedTrackedQuantity;

            if ($quantity === null || $warehouseId !== null) {
                $quantity = (int) Asset::query()
                    ->where('organization_id', $this->orgId())
                    ->where('product_id', $product->id)
                    ->rentalReady()
                    ->when($warehouseId, fn ($query) => $query->where('warehouse_id', $warehouseId))
                    ->count();
            }

            return [
                'quantity' => $quantity,
                'status' => $quantity > 0 ? 'rental_available' : 'no_rental_assets',
                'label' => $quantity > 0 ? 'Rental Available ' . $quantity : 'No rental assets available',
            ];
        }

        if ($product->product_type === Product::TYPE_RENTABLE) {
            $quantity = max((int) $product->available_quantity, 0);

            return [
                'quantity' => $quantity,
                'status' => $quantity > 0 ? 'rental_available' : 'no_rental_assets',
                'label' => $quantity > 0 ? 'Rental Available ' . $quantity : 'No rental units available',
            ];
        }

        return [
            'quantity' => 0,
            'status' => 'no_rental_assets',
            'label' => 'No rental assets available',
        ];
    }

    private function rentalAvailableQuantityForProduct(Product $product, ?int $warehouseId = null): int
    {
        return (int) ($this->rentalAvailabilityForProduct($product, $warehouseId)['quantity'] ?? 0);
    }

    private function resolveCombinedRentalAssets(array $items, ?int $dispatchWarehouseId = null, ?Rental $rental = null)
    {
        if (!$this->hasRentalAssetsTable()) {
            return collect();
        }

        $currentRentalId = $rental?->id;
        $existingAssetIds = $rental
            ? $rental->activeRentalAssets()->pluck('asset_id')->all()
            : [];

        $validatedAssets = collect();
        $seenAssetIds = [];

        foreach ($items as $item) {
            $assetIds = $this->normalizeAssetIds($item['asset_ids'] ?? []);

            if (empty($assetIds)) {
                continue;
            }

            $quantity = (int) ($item['quantity'] ?? 0);
            $field = $item['form_asset_field'] ?? 'asset_ids';
            $lineLabel = $item['line_label'] ?? 'rental line';

            if ($quantity > 0 && count($assetIds) !== $quantity) {
                throw ValidationException::withMessages([
                    $field => ['Select exactly ' . $quantity . ' asset(s) for the ' . $lineLabel . '.'],
                ]);
            }

            $duplicateIds = array_values(array_intersect($seenAssetIds, $assetIds));

            if (!empty($duplicateIds)) {
                throw ValidationException::withMessages([
                    $field => ['An asset was selected more than once across rental lines.'],
                ]);
            }

            $assets = Asset::query()
                ->where('organization_id', $this->orgId())
                ->where('product_id', $item['product_id'])
                ->where('asset_stage', Asset::STAGE_RENTAL_STOCK)
                ->when($dispatchWarehouseId, fn ($query) => $query->where('warehouse_id', $dispatchWarehouseId))
                ->whereIn('id', $assetIds)
                ->get();

            if ($assets->count() !== count($assetIds)) {
                throw ValidationException::withMessages([
                    $field => ['One or more selected assets do not match the product or warehouse for the ' . $lineLabel . '.'],
                ]);
            }

            $conflictingAssetIds = RentalAsset::query()
                ->whereIn('asset_id', $assetIds)
                ->whereNull('returned_at')
                ->when($currentRentalId, fn ($query) => $query->where('rental_id', '!=', $currentRentalId))
                ->pluck('asset_id')
                ->all();

            if (!empty($conflictingAssetIds)) {
                throw ValidationException::withMessages([
                    $field => ['One or more selected assets are already assigned to another active rental.'],
                ]);
            }

            $unavailableAssets = $assets
                ->filter(function ($asset) use ($existingAssetIds) {
                    return !in_array($asset->id, $existingAssetIds, true) && $asset->asset_status !== 'available';
                })
                ->pluck('serial_number')
                ->filter()
                ->values()
                ->all();

            if (!empty($unavailableAssets)) {
                throw ValidationException::withMessages([
                    $field => ['These assets are not available: ' . implode(', ', $unavailableAssets)],
                ]);
            }

            $validatedAssets = $validatedAssets->merge($assets);
            $seenAssetIds = array_values(array_unique(array_merge($seenAssetIds, $assetIds)));
        }

        return $validatedAssets
            ->unique('id')
            ->sortBy('serial_number')
            ->values();
    }

    private function restoreRentalItemStock(Rental $rental): void
    {
        if ($this->hasRentalItemsTable()) {
            $rental->loadMissing('rentalItems');

            if ($rental->rentalItems->isNotEmpty()) {
                $products = Product::query()
                    ->where('organization_id', $this->orgId())
                    ->whereIn('id', $rental->rentalItems->pluck('product_id')->filter()->unique()->values())
                    ->get()
                    ->keyBy('id');

                foreach ($rental->rentalItems as $item) {
                    $quantityToRestore = max((int) $item->quantity - (int) ($item->returned_quantity ?? 0), 0);

                    if ($quantityToRestore <= 0) {
                        continue;
                    }

                    /** @var Product|null $product */
                    $product = $products->get((int) $item->product_id);

                    if (!$product?->usesUntrackedStock()) {
                        continue;
                    }

                    Product::query()
                        ->where('organization_id', $this->orgId())
                        ->where('id', $item->product_id)
                        ->increment('available_quantity', $quantityToRestore);
                }

                $rental->rentalItems()->delete();

                return;
            }
        }

        $product = Product::query()
            ->where('organization_id', $this->orgId())
            ->find($rental->product_id);

        if ($product?->usesUntrackedStock()) {
            Product::query()
                ->where('organization_id', $this->orgId())
                ->where('id', $rental->product_id)
                ->increment('available_quantity', (int) $rental->quantity);
        }
    }

    private function consumeRentalItemStock(array $items): void
    {
        $products = Product::query()
            ->where('organization_id', $this->orgId())
            ->whereIn('id', collect($items)->pluck('product_id')->filter()->unique()->values())
            ->get()
            ->keyBy('id');

        foreach ($items as $item) {
            /** @var Product|null $product */
            $product = $products->get((int) $item['product_id']);

            if (!$product?->usesUntrackedStock()) {
                continue;
            }

            Product::query()
                ->where('organization_id', $this->orgId())
                ->where('id', $item['product_id'])
                ->decrement('available_quantity', (int) $item['quantity']);
        }
    }

