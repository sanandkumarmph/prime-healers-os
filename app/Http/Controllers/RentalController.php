    private function attachLinkedInvoiceIds($rentals)
    {
        $rentalIds = $rentals->pluck('id')->filter()->map(fn ($id) => (int) $id)->values();

        if ($rentalIds->isEmpty()) {
            return $rentals;
        }

        $invoiceMap = Invoice::query()
            ->whereIn('id', (clone $this->rentalInvoiceLookupQuery($rentalIds->all()))->select('id'))
            ->with(['items' => function ($itemQuery) use ($rentalIds) {
                $itemQuery
                    ->where('source_type', 'rental')
                    ->whereIn('source_id', $rentalIds->all());
            }])
            ->orderByDesc('id')
            ->get()
            ->reduce(function ($carry, $invoice) {
                $directRentalId = $this->hasInvoiceRentalColumn()
                    ? (int) ($invoice->rental_id ?? 0)
                    : 0;

                if ($directRentalId > 0 && !isset($carry[$directRentalId])) {
                    $carry[$directRentalId] = [
                        'id' => (int) $invoice->id,
                        'payment_status' => (string) ($invoice->payment_status ?? ''),
                        'balance_amount' => (float) ($invoice->balance_amount ?? 0),
                        'total_amount' => (float) ($invoice->total_amount ?? 0),
                    ];
                }

                foreach ($invoice->items as $item) {
                    $rentalId = (int) ($item->source_id ?? 0);

                    if ($rentalId > 0 && !isset($carry[$rentalId])) {
                        $carry[$rentalId] = [
                            'id' => (int) $invoice->id,
                            'payment_status' => (string) ($invoice->payment_status ?? ''),
                            'balance_amount' => (float) ($invoice->balance_amount ?? 0),
                            'total_amount' => (float) ($invoice->total_amount ?? 0),
                        ];
                    }
                }

                return $carry;
            }, []);

        $rentals->each(function ($rental) use ($invoiceMap) {
            $invoiceMeta = $invoiceMap[(int) $rental->id] ?? null;

            $rental->setAttribute('linked_invoice_id', $invoiceMeta['id'] ?? null);
            $rental->setAttribute('linked_invoice_payment_status', $invoiceMeta['payment_status'] ?? null);
            $rental->setAttribute('linked_invoice_balance_amount', $invoiceMeta['balance_amount'] ?? null);
            $rental->setAttribute('linked_invoice_total_amount', $invoiceMeta['total_amount'] ?? null);
        });

        return $rentals;
    }

