    public function destroyRenewal(Rental $rental, RentalRenewal $renewal)
    {
        $this->ensureRentalAccess();
        $rental = $this->scopedRental($rental);

        abort_if(!$this->hasRentalRenewalsTable(), 404);
        abort_if((int) $renewal->rental_id !== (int) $rental->id || (int) $renewal->organization_id !== $this->orgId(), 404);

        if ($renewal->invoice_id) {
            return redirect()
                ->route('rentals.show', $rental)
                ->with('error', 'This renewal already has an invoice. Void the invoice manually before deleting the renewal.');
        }

        $linkedPayment = $renewal->payment_id
            ? Payment::query()->where('organization_id', $this->orgId())->find($renewal->payment_id)
            : null;
        $nextRenewal = $this->nextRenewalFor($renewal);

        if ($linkedPayment && (float) ($linkedPayment->amount ?? 0) > 0.009) {
            return redirect()
                ->route('rentals.show', $rental)
                ->with('error', 'This renewal already has a recorded payment. Remove or reverse the payment manually before deleting the renewal.');
        }

        DB::transaction(function () use ($rental, $renewal, $linkedPayment, $nextRenewal) {
            $rental->forceFill([
                'end_date' => $nextRenewal ? $rental->end_date : ($renewal->previous_end_date ?: $rental->end_date),
                'status' => 'active',
                'rental_amount' => max((float) ($rental->rental_amount ?? 0) - (float) ($renewal->rental_amount_added ?? 0), 0),
                'deposit_amount' => max((float) ($rental->deposit_amount ?? 0) - (float) ($renewal->deposit_amount_added ?? 0), 0),
                'transport_amount' => max((float) ($rental->transport_amount ?? 0) - (float) ($renewal->transport_amount_added ?? 0), 0),
                'other_amount' => max((float) ($rental->other_amount ?? 0) - (float) ($renewal->other_amount_added ?? 0), 0),
            ])->save();

            if ($nextRenewal) {
                $nextRenewalEndDate = Carbon::parse($nextRenewal->renewed_end_date)->startOfDay();
                $nextPreviousEndDate = $renewal->previous_end_date
                    ? Carbon::parse($renewal->previous_end_date)->startOfDay()
                    : null;

                if (!$nextPreviousEndDate || !$nextPreviousEndDate->lt($nextRenewalEndDate)) {
                    throw ValidationException::withMessages([
                        'renewal' => ['This renewal cannot be deleted safely because the next renewal chain would become invalid.'],
                    ]);
                }

                $nextRenewal->forceFill([
                    'previous_end_date' => $nextPreviousEndDate,
                    'renewal_days' => max((int) $nextPreviousEndDate->diffInDays($nextRenewalEndDate), 1),
                ])->save();
            }

            if ($linkedPayment) {
                $linkedPayment->delete();
            }

            $renewal->delete();

            if ($nextRenewal?->invoice_id) {
                $this->syncRenewalInvoicePaymentState($rental, $nextRenewal->refresh());
            }
        });

        ActivityLogger::log('rental.renewal_deleted', $rental->refresh(), [
            'previous_end_date' => optional($renewal->previous_end_date)->toDateString(),
            'renewed_end_date' => optional($renewal->renewed_end_date)->toDateString(),
            'renewal_days' => $renewal->renewal_days,
        ], 'Latest rental renewal deleted safely.');

        return redirect()
            ->route('rentals.show', $rental)
            ->with('success', 'Latest renewal deleted successfully.');
    }

