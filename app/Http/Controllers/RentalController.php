                $query->whereHas('invoice', function ($invoiceQuery) use ($customerId) {
                    $invoiceQuery->where('customer_id', $customerId);
                });
            }
        }

        return $this->applySimpleDateRangeFilter($query, 'payment_date', $fromDate, $toDate);
    }

