    private function renewRentalRecord(Rental $rental, array $data, string $renewalType = 'custom')
    {
        $rental = $this->scopedRental($rental);
        $rental->loadMissing(['customer', 'product']);

        if (!$rental->canRenew()) {
            return $this->renewalRedirectFor($rental)->with('error', 'Returned rentals cannot be renewed.');
        }

        $previousEndDate = $this->normalizeCarbonDate($rental->end_date);
        $newEndDate = Carbon::parse($data['new_end_date'])->startOfDay();
        $renewalDays = $previousEndDate ? max((int) $previousEndDate->diffInDays($newEndDate), 1) : 1;

        $rentalAmountAdded = (float) ($data['rental_amount_added'] ?? 0);
        $depositAmountAdded = (float) ($data['deposit_amount_added'] ?? 0);
        $transportAmountAdded = (float) ($data['transport_amount_added'] ?? 0);
        $otherAmountAdded = (float) ($data['other_amount_added'] ?? 0);
        $paymentAmount = (float) ($data['payment_amount'] ?? 0);
        $paymentMethod = Payment::normalizeMethod($data['payment_method'] ?? null);
        $paymentDate = !empty($data['payment_date']) ? Carbon::parse($data['payment_date']) : now();
        $notes = filled($data['notes'] ?? null) ? trim((string) $data['notes']) : null;
        $sendWhatsApp = (bool) ($data['send_whatsapp'] ?? false);

        if ($this->hasRentalRenewalsTable()) {
            $latestRenewal = $this->renewalHistoryBaseQuery()
                ->where('rental_id', $rental->id)
                ->latest('id')
                ->first();

            if ($latestRenewal) {
                $sameWindow = optional($latestRenewal->previous_end_date)?->isSameDay($previousEndDate)
                    && optional($latestRenewal->renewed_end_date)?->isSameDay($newEndDate);

                $sameCommercials =
                    round((float) ($latestRenewal->rental_amount_added ?? 0), 2) === round($rentalAmountAdded, 2)
                    && round((float) ($latestRenewal->deposit_amount_added ?? 0), 2) === round($depositAmountAdded, 2)
                    && round((float) ($latestRenewal->transport_amount_added ?? 0), 2) === round($transportAmountAdded, 2)
                    && round((float) ($latestRenewal->other_amount_added ?? 0), 2) === round($otherAmountAdded, 2);

                if ($sameWindow && $sameCommercials) {
                    return $this->renewalRedirectFor($rental)
                        ->with('error', 'An identical renewal is already logged. Use Edit Renewal if you only need to correct the latest renewal.');
                }

                $latestRenewedEndDate = $this->normalizeCarbonDate($latestRenewal->renewed_end_date);
                if ($latestRenewal->canBeEdited() && $latestRenewedEndDate && $newEndDate->lessThanOrEqualTo($latestRenewedEndDate)) {
                    return $this->renewalRedirectFor($rental)
                        ->with('error', 'A renewal is already logged up to '.$latestRenewedEndDate->format('d M Y').'. Edit the latest renewal instead of creating another overlapping renewal.');
                }
            }
        }

        $whatsAppUrl = null;
        $payment = null;
        $renewal = null;

        DB::transaction(function () use (
            $rental,
            $newEndDate,
            $renewalDays,
            $renewalType,
            $rentalAmountAdded,
            $depositAmountAdded,
            $transportAmountAdded,
            $otherAmountAdded,
            $paymentAmount,
            $paymentMethod,
            $paymentDate,
            $notes,
            $sendWhatsApp,
            $previousEndDate,
            &$payment,
            &$renewal,
            &$whatsAppUrl
        ) {
            $rental->forceFill([
                'end_date' => $newEndDate,
                'status' => 'active',
                'rental_amount' => (float) ($rental->rental_amount ?? 0) + $rentalAmountAdded,
                'deposit_amount' => (float) ($rental->deposit_amount ?? 0) + $depositAmountAdded,
                'transport_amount' => (float) ($rental->transport_amount ?? 0) + $transportAmountAdded,
                'other_amount' => (float) ($rental->other_amount ?? 0) + $otherAmountAdded,
            ])->save();

            if ($paymentAmount > 0) {
                $payment = Payment::create([
                    'organization_id' => $this->orgId(),
                    'customer_id' => $rental->customer_id,
                    'rental_id' => $rental->id,
                    'invoice_id' => null,
                    'payment_date' => $paymentDate,
                    'amount' => $paymentAmount,
                    'payment_method' => $paymentMethod,
                    'notes' => $notes ?: 'Captured during rental renewal.',
                ]);
            }

            if ($this->hasRentalRenewalsTable()) {
                $renewal = RentalRenewal::create([
                    'organization_id' => $this->orgId(),
                    'rental_id' => $rental->id,
                    'previous_end_date' => $previousEndDate,
                    'renewed_end_date' => $newEndDate,
                    'renewal_days' => $renewalDays,
                    'renewal_type' => $renewalType,
                    'rental_amount_added' => $rentalAmountAdded,
                    'deposit_amount_added' => $depositAmountAdded,
                    'transport_amount_added' => $transportAmountAdded,
                    'other_amount_added' => $otherAmountAdded,
                    'payment_id' => $payment?->id,
                    'payment_amount' => $paymentAmount,
                    'payment_method' => $paymentMethod,
                    'notes' => $notes,
                    'renewed_by_user_id' => auth()->id(),
                ]);
            }

            if ($sendWhatsApp) {
                $normalizedNumber = WhatsAppHelper::resolveCustomerNumber($rental->customer);

                if ($normalizedNumber) {
                    $message = WhatsAppHelper::rentalRenewedConfirmation(
                        $rental,
                        $previousEndDate,
                        $newEndDate,
                        $rentalAmountAdded + $depositAmountAdded + $transportAmountAdded + $otherAmountAdded
                    );

                    $whatsAppUrl = WhatsAppHelper::chatUrl($normalizedNumber, $message);

                    if (Rental::hasReminderLogsTable()) {
                        RentalReminderLog::create([
                            'organization_id' => $this->orgId(),
                            'rental_id' => $rental->id,
                            'customer_id' => $rental->customer_id,
                            'reminder_type' => 'renewal_confirmation',
                            'sent_via' => 'whatsapp',
                            'sent_to_number' => $normalizedNumber,
                            'message_preview' => $message,
                            'sent_by_user_id' => auth()->id(),
                            'sent_at' => now(),
                        ]);
                    }

                    if ($renewal) {
                        $renewal->forceFill([
                            'reminder_sent_at' => now(),
                            'reminder_channel' => 'whatsapp',
                        ])->save();
                    }
                }
            }
        });

        ActivityLogger::log('rental.renewed', $rental->refresh(), [
            'renewal_id' => $renewal?->id,
            'payment_id' => $payment?->id,
            'previous_end_date' => $previousEndDate?->toDateString(),
            'new_end_date' => $newEndDate->toDateString(),
            'renewal_days' => $renewalDays,
            'renewal_type' => $renewalType,
            'rental_amount_added' => $rentalAmountAdded,
            'payment_amount' => $paymentAmount,
            'whatsapp_prepared' => filled($whatsAppUrl),
        ], 'Rental renewed on the same order.');

        $successMessage = $renewalType === 'quick'
            ? 'Rental renewed quickly without creating a duplicate record.'
            : 'Rental renewed successfully.';

        return $this->renewalRedirectFor($rental)
            ->with('success', $successMessage)
            ->with('renewal_whatsapp_url', $whatsAppUrl);
    }

