    private function syncAutoGeneratedRentalSales(Rental $rental): void
    {
        if (!Schema::hasTable('sales') || !$this->hasSalesAutoGeneratedColumn()) {
            return;
        }

        $rental->load(['saleItems.product', 'saleItems.asset']);

        $this->deleteAutoGeneratedRentalSales($rental);

        foreach ($rental->saleItems as $saleItem) {
            $product = $saleItem->product;

            if (!$product || (int) $product->organization_id !== $this->orgId()) {
                continue;
            }

            $salePayload = [
                'customer_id' => $rental->customer_id,
                'product_id' => $product->id,
                'asset_id' => $saleItem->asset_id ?: null,
                'rental_id' => $rental->id,
                'auto_generated_from_rental' => true,
                'quantity' => (int) $saleItem->quantity,
                'unit_price' => (float) ($saleItem->unit_price ?? 0),
                'discount_amount' => 0,
                'shipping_charges' => 0,
                'tax_percentage' => (float) ($saleItem->gst_rate ?? 0),
                'tax_calculation_mode' => ($saleItem->gst_mode ?? 'exclusive') === 'inclusive' ? 'inclusive' : 'exclusive',
                'sale_date' => optional($rental->created_at)->toDateString() ?? now()->toDateString(),
                'sale_amount' => (float) ($saleItem->line_total ?? 0),
                'payment_status' => 'unpaid',
                'notes' => trim(collect([
                    'Auto-generated from rental #' . $rental->id,
                    $saleItem->notes,
                ])->filter()->implode(' | ')),
                'organization_id' => $this->orgId(),
            ];

            if ($this->hasSalesWarehouseColumn()) {
                $salePayload['warehouse_id'] = $saleItem->warehouse_id;
            }

            if (Schema::hasColumn('sales', 'stock_applied')) {
                $salePayload['stock_applied'] = false;
            }

            if ($this->hasSalesCreatedByColumn() && $rental->created_by_user_id) {
                $salePayload['created_by'] = $rental->created_by_user_id;
            }

            if ($this->hasSalesCreatedByUserColumn() && $rental->created_by_user_id) {
                $salePayload['created_by_user_id'] = $rental->created_by_user_id;
            }

            Sale::create($salePayload);
        }
    }

    private function syncRentalSaleItems(Rental $rental, array $saleItems): void
    {
        if (!$this->hasRentalSaleItemsTable()) {
            return;
        }

        foreach ($saleItems as $saleItem) {
            $product = Product::query()
                ->where('organization_id', $this->orgId())
                ->findOrFail($saleItem['product_id']);

            if (!(bool) ($product->is_sellable ?? false)) {
                throw ValidationException::withMessages([
                    'sale_items' => ['Only sellable products can be added as new products.'],
                ]);
            }

            $asset = null;
            $resolvedWarehouseId = $saleItem['warehouse_id'];

            if (!empty($saleItem['asset_id'])) {
                $asset = Asset::query()
                    ->where('organization_id', $this->orgId())
                    ->lockForUpdate()
                    ->findOrFail($saleItem['asset_id']);

                if ((int) $asset->product_id !== (int) $product->id) {
                    throw ValidationException::withMessages([
                        'sale_items' => ['Selected serialized asset does not belong to ' . $product->name . '.'],
                    ]);
                }

                if ($asset->asset_stage !== Asset::STAGE_NEW_STOCK) {
                    throw ValidationException::withMessages([
                        'sale_items' => ['Only new stock assets can be linked to a new product sale.'],
                    ]);
                }

                if ($asset->asset_status !== 'available_for_sale') {
                    throw ValidationException::withMessages([
                        'sale_items' => ['Selected serialized asset is no longer available for sale.'],
                    ]);
                }

                if ((int) $saleItem['quantity'] !== 1) {
                    throw ValidationException::withMessages([
                        'sale_items' => ['Quantity must stay 1 when a serialized asset is linked.'],
                    ]);
                }

                $resolvedWarehouseId = (int) ($asset->warehouse_id ?: $resolvedWarehouseId);
            }

            if ($product->tracksSaleStock()) {
                $asset = $this->allocateTrackedRentalSaleAsset(
                    $product,
                    (int) $saleItem['quantity'],
                    $resolvedWarehouseId ? (int) $resolvedWarehouseId : null,
                    !empty($saleItem['asset_id']) ? (int) $saleItem['asset_id'] : null
                );

                $asset->update(['asset_status' => 'sold']);

                SaleInventory::syncFromSaleUnits($this->orgId(), $product->id);
                $product->refresh();
                $product->syncLegacyStockFields();

                $unitPrice = $saleItem['unit_price'] > 0
                    ? $saleItem['unit_price']
                    : (float) ($product->sale_price ?? 0);

                $rental->saleItems()->create([
                    'organization_id' => $this->orgId(),
                    'product_id' => $product->id,
                    'asset_id' => $asset->id,
                    'warehouse_id' => $asset->warehouse_id,
                    'quantity' => 1,
                    'unit_price' => $unitPrice,
                    'gst_rate' => $saleItem['gst_rate'] ?? 0,
                    'gst_mode' => $saleItem['gst_mode'] ?? 'exclusive',
                    'tax_type' => $saleItem['tax_type'] ?? Product::GST_TAX_TYPE_CGST_SGST,
                    'taxable_amount' => $saleItem['taxable_amount'] ?? $unitPrice,
                    'cgst_amount' => $saleItem['cgst_amount'] ?? 0,
                    'sgst_amount' => $saleItem['sgst_amount'] ?? 0,
                    'igst_amount' => $saleItem['igst_amount'] ?? 0,
                    'line_total' => $saleItem['line_total'] ?? round($unitPrice, 2),
                    'notes' => $saleItem['notes'],
                ]);

                continue;
            }

            $inventory = null;

            if ($resolvedWarehouseId) {
                $inventory = SaleInventory::query()
                    ->where('organization_id', $this->orgId())
                    ->where('product_id', $product->id)
                    ->where('warehouse_id', $resolvedWarehouseId)
                    ->lockForUpdate()
                    ->first();
            } elseif ($product->saleInventories()->exists()) {
                $inventory = SaleInventory::query()
                    ->where('organization_id', $this->orgId())
                    ->where('product_id', $product->id)
                    ->get()
                    ->first(fn ($row) => $row->availableToSell() >= $saleItem['quantity']);
            }

            if ($inventory) {
                if ($inventory->availableToSell() < $saleItem['quantity']) {
                    throw ValidationException::withMessages([
                        'sale_items' => ['New product quantity exceeds available sale stock for ' . $product->name . '.'],
                    ]);
                }

                $inventory->decrement('quantity_in_stock', (int) $saleItem['quantity']);
                $product->syncLegacyStockFields();
            } else {
                if ((int) $product->available_quantity < (int) $saleItem['quantity']) {
                    throw ValidationException::withMessages([
                        'sale_items' => ['New product quantity exceeds available stock for ' . $product->name . '.'],
                    ]);
                }

                $product->decrement('available_quantity', (int) $saleItem['quantity']);
            }

            if ($asset) {
                $asset->update(['asset_status' => 'sold']);
            }

            $unitPrice = $saleItem['unit_price'] > 0
                ? $saleItem['unit_price']
                : (float) ($product->sale_price ?? 0);

            $rental->saleItems()->create([
                'organization_id' => $this->orgId(),
                'product_id' => $product->id,
                'asset_id' => $asset?->id,
                'warehouse_id' => $inventory?->warehouse_id ?? $resolvedWarehouseId,
                'quantity' => (int) $saleItem['quantity'],
                'unit_price' => $unitPrice,
                'gst_rate' => $saleItem['gst_rate'] ?? 0,
                'gst_mode' => $saleItem['gst_mode'] ?? 'exclusive',
                'tax_type' => $saleItem['tax_type'] ?? Product::GST_TAX_TYPE_CGST_SGST,
                'taxable_amount' => $saleItem['taxable_amount'] ?? round(((int) $saleItem['quantity']) * $unitPrice, 2),
                'cgst_amount' => $saleItem['cgst_amount'] ?? 0,
                'sgst_amount' => $saleItem['sgst_amount'] ?? 0,
                'igst_amount' => $saleItem['igst_amount'] ?? 0,
                'line_total' => $saleItem['line_total'] ?? round(((int) $saleItem['quantity']) * $unitPrice, 2),
                'notes' => $saleItem['notes'],
            ]);
        }

        $rental->unsetRelation('saleItems');
    }

    private function resolveSelectedAssets(Request $request, ?Rental $rental = null)
    {
        if (!$this->hasRentalAssetsTable()) {
            return collect();
        }

        $assetIds = $this->normalizeAssetIds($request->input('asset_ids', []));

        if (empty($assetIds)) {
            return collect();
        }

        $quantity = (int) $request->input('quantity', 0);

        if ($quantity > 0 && count($assetIds) !== $quantity) {
            throw ValidationException::withMessages([
                'asset_ids' => 'Select exactly ' . $quantity . ' asset(s) to match the rental quantity.',
            ]);
        }

        $assets = Asset::query()
            ->where('organization_id', $this->orgId())
            ->where('product_id', $request->input('product_id'))
            ->when($request->filled('dispatch_warehouse_id'), function ($query) use ($request) {
                $query->where('warehouse_id', $request->input('dispatch_warehouse_id'));
            })
            ->whereIn('id', $assetIds)
            ->get();

        if ($assets->count() !== count($assetIds)) {
            throw ValidationException::withMessages([
                'asset_ids' => 'One or more selected assets do not match the selected product or dispatch warehouse.',
            ]);
        }

        $currentRentalId = $rental?->id;
        $conflictingAssetIds = RentalAsset::query()
            ->whereIn('asset_id', $assetIds)
            ->whereNull('returned_at')
            ->when($currentRentalId, fn ($query) => $query->where('rental_id', '!=', $currentRentalId))
            ->pluck('asset_id')
            ->all();

        if (!empty($conflictingAssetIds)) {
            throw ValidationException::withMessages([
                'asset_ids' => 'One or more selected assets are already assigned to another active rental.',
            ]);
        }

        $existingAssetIds = $rental
            ? $rental->activeRentalAssets()->pluck('asset_id')->all()
            : [];

        $unavailableAssets = $assets
            ->filter(function ($asset) use ($existingAssetIds) {
                return !in_array($asset->id, $existingAssetIds, true) && $asset->asset_status !== 'available';
            })
            ->pluck('serial_number')
            ->all();

        if (!empty($unavailableAssets)) {
            throw ValidationException::withMessages([
                'asset_ids' => 'These assets are not available: ' . implode(', ', $unavailableAssets),
            ]);
        }

        return $assets->sortBy('serial_number')->values();
    }

    private function desiredAssignedAssetStatus(Rental $rental): string
    {
        $latestDelivery = $rental->deliveries()
            ->where('type', 'delivery')
            ->latest()
            ->first();

        return $latestDelivery && $latestDelivery->status === 'completed'
            ? Asset::STATUS_RENTED
            : Asset::STATUS_RESERVED;
    }

    private function deliveredTrackedRentalAssetIds(Rental $rental): array
    {
        if (!$this->hasRentalAssetsTable()) {
            return [];
        }

        if (!$this->hasRentalItemsTable()) {
            if ($rental->deliveryStatus() !== 'completed') {
                return [];
            }

            return $rental->activeRentalAssets()
                ->pluck('asset_id')
                ->map(fn ($assetId) => (int) $assetId)
                ->filter(fn ($assetId) => $assetId > 0)
                ->values()
                ->all();
        }

        $rental->loadMissing('rentalItems');
        $deliveredAssetIds = [];

        foreach ($rental->rentalItems as $item) {
            $assetIds = collect($item->asset_ids ?? [])
                ->filter(fn ($assetId) => filled($assetId))
                ->map(fn ($assetId) => (int) $assetId)
                ->values();

            if ($assetIds->isEmpty()) {
                continue;
            }

            $deliveredCount = min((int) ($item->delivered_quantity_value ?? 0), $assetIds->count());

            if ($deliveredCount <= 0) {
                continue;
            }

            $deliveredAssetIds = array_merge($deliveredAssetIds, $assetIds->slice(0, $deliveredCount)->all());
        }

        return array_values(array_unique(array_map('intval', $deliveredAssetIds)));
    }

    private function releaseStatusForTrackedRentalAsset(Rental $rental, Asset $asset, array $deliveredAssetIds): string
    {
        if (!$asset->isRentalStock()) {
            return $asset->asset_status;
        }

        if (
            in_array($asset->id, $deliveredAssetIds, true)
            || in_array($asset->asset_status, [Asset::STATUS_RENTED, Asset::STATUS_AWAITING_VERIFICATION], true)
        ) {
            return Asset::STATUS_AWAITING_VERIFICATION;
        }

        return Asset::STATUS_AVAILABLE;
    }

    private function trackedRentalNeedsAssetAssignment(Rental $rental): bool
    {
        if (!$this->hasRentalItemsTable()) {
            return false;
        }

        $rental->loadMissing('rentalItems');

        if ($rental->rentalItems->isEmpty()) {
            return false;
        }

        $products = Product::query()
            ->where('organization_id', $this->orgId())
            ->whereIn('id', $rental->rentalItems->pluck('product_id')->filter()->unique()->values())
            ->get()
            ->keyBy('id');

        foreach ($rental->rentalItems as $item) {
            /** @var Product|null $product */
            $product = $products->get((int) $item->product_id);

            if (!$product?->tracksRentalStock()) {
                continue;
            }

            $assetIds = $this->normalizeAssetIds($item->asset_ids ?? []);

            if (count($assetIds) !== max((int) $item->quantity, 0)) {
                return true;
            }
        }

        return false;
    }

    private function syncRentalAssets(Rental $rental, $selectedAssets): void
    {
        if (!$this->hasRentalAssetsTable()) {
            return;
        }

        $desiredStatus = $this->desiredAssignedAssetStatus($rental);
        $selectedAssetIds = $selectedAssets->pluck('id')->all();
        $currentAssetIds = $rental->activeRentalAssets()->pluck('asset_id')->all();
        $deliveredAssetIds = $this->deliveredTrackedRentalAssetIds($rental);

        $assetIdsToRelease = array_values(array_diff($currentAssetIds, $selectedAssetIds));
        $assetIdsToAssign = array_values(array_diff($selectedAssetIds, $currentAssetIds));
        $assetIdsToKeep = array_values(array_intersect($currentAssetIds, $selectedAssetIds));

        if (!empty($assetIdsToRelease)) {
            $releasedAssignments = $rental->activeRentalAssets()
                ->with('asset')
                ->whereIn('asset_id', $assetIdsToRelease)
                ->get();

            foreach ($releasedAssignments as $assignment) {
                $asset = $assignment->asset;

                if (!$asset) {
                    continue;
                }

                $nextStatus = $this->releaseStatusForTrackedRentalAsset($rental, $asset, $deliveredAssetIds);

                $assignment->update([
                    'returned_at' => now(),
                    'return_condition' => $asset->condition_status,
                    'notes' => trim(($assignment->notes ? $assignment->notes . ' | ' : '') . (
                        $nextStatus === Asset::STATUS_AWAITING_VERIFICATION
                            ? 'Released during rental update after delivery and awaiting verification.'
                            : 'Released during rental update before dispatch.'
                    )),
                ]);

                $asset->update(['asset_status' => $nextStatus]);
            }
        }

        foreach ($assetIdsToAssign as $assetId) {
            RentalAsset::create([
                'organization_id' => $this->orgId(),
                'rental_id' => $rental->id,
                'asset_id' => $assetId,
                'assigned_at' => now(),
                'notes' => 'Assigned from rental workflow.',
            ]);
        }

        $assetIdsToMark = array_values(array_unique(array_merge($assetIdsToAssign, $assetIdsToKeep)));

        if (!empty($assetIdsToMark)) {
            Asset::query()
                ->where('organization_id', $this->orgId())
                ->whereIn('id', $assetIdsToMark)
                ->update(['asset_status' => $desiredStatus]);
        }
    }

    private function releaseRentalAssets(Rental $rental): void
    {
        if (!$this->hasRentalAssetsTable()) {
            return;
        }

        $deliveredAssetIds = $this->deliveredTrackedRentalAssetIds($rental);

        $activeAssignments = $rental->activeRentalAssets()
            ->with('asset')
            ->get();

        foreach ($activeAssignments as $assignment) {
            $asset = $assignment->asset;

            if (!$asset) {
                continue;
            }

            $nextStatus = $this->releaseStatusForTrackedRentalAsset($rental, $asset, $deliveredAssetIds);

            $assignment->update([
                'returned_at' => now(),
                'return_condition' => $asset->condition_status,
                'notes' => trim(($assignment->notes ? $assignment->notes . ' | ' : '') . (
                    $nextStatus === Asset::STATUS_AWAITING_VERIFICATION
                        ? 'Released on rental close after delivery and awaiting verification.'
                        : 'Released on rental close before dispatch.'
                )),
            ]);

            $asset->update(['asset_status' => $nextStatus]);
        }
    }

    private function ensureRentalItemsExist(Rental $rental): void
    {
        if (!$this->hasRentalItemsTable()) {
            return;
        }

        if ($rental->relationLoaded('rentalItems') ? $rental->rentalItems->isNotEmpty() : $rental->rentalItems()->exists()) {
            return;
        }

        $quantity = max((int) ($rental->quantity ?? 0), 1);
        $lineTotal = (float) ($rental->rental_amount ?? 0);

        $rental->rentalItems()->create([
            'organization_id' => $this->orgId(),
            'product_id' => $rental->product_id,
            'quantity' => $quantity,
            'ordered_quantity' => $quantity,
            'delivered_quantity' => 0,
            'returned_quantity' => 0,
            'unit_rental_amount' => $quantity > 0 ? round($lineTotal / $quantity, 2) : $lineTotal,
            'gst_rate' => 0,
            'gst_mode' => 'exclusive',
            'tax_type' => Product::GST_TAX_TYPE_CGST_SGST,
            'taxable_amount' => $lineTotal,
            'cgst_amount' => 0,
            'sgst_amount' => 0,
            'igst_amount' => 0,
            'line_total' => $lineTotal,
            'notes' => 'Backfilled from legacy rental line.',
        ]);

        $rental->unsetRelation('rentalItems');
    }

