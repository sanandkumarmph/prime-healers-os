    private function selectedBusinessPartnerIdFromRequest(?Rental $rental = null): ?int
    {
        $value = old('business_partner_id');

        if (filled($value)) {
            return (int) $value;
        }

        $fallback = request()->integer('business_partner_id');

        if ($fallback > 0) {
