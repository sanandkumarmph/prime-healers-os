    private function overallPendingDeliveryQuantity(Rental $rental): int
    {
        if (!$this->hasRentalItemsTable()) {
            return $rental->deliveryStatus() === 'completed' ? 0 : max((int) ($rental->quantity ?? 0), 0);
        }

        return (int) $this->loadRentalProgressItems($rental)->sum('pending_delivery_quantity');
    }

    private function overallPendingPickupQuantity(Rental $rental): int
    {
        if (!$this->hasRentalItemsTable()) {
            return $rental->status === 'returned' ? 0 : ($rental->deliveryStatus() === 'completed' ? max((int) ($rental->quantity ?? 0), 0) : 0);
        }

        return (int) $this->loadRentalProgressItems($rental)->sum('pending_pickup_quantity');
    }

    private function deliveredQuantityExists(Rental $rental): bool
    {
        if (!$this->hasRentalItemsTable()) {
            return $rental->deliveryStatus() === 'completed';
        }

        return $this->loadRentalProgressItems($rental)->sum('delivered_quantity_value') > 0;
    }

    private function resolveRentalProgressItem(Rental $rental, int $itemId): RentalItem
    {
        $items = $this->loadRentalProgressItems($rental);

        /** @var RentalItem|null $item */
        $item = $items->firstWhere('id', $itemId);

        if (!$item) {
            throw ValidationException::withMessages([
                'rental_item_id' => 'The selected rental item does not belong to this rental.',
            ]);
        }

        return $item;
    }

