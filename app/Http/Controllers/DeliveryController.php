            ->pluck('id')
            ->map(fn ($id) => (int) $id)
            ->values();
        $overdueTasks = $hydrateDeliveries($overdueTaskIds);

        $pendingCollectionIds = collect($logisticsSummary['pendingPickupTasks'] ?? collect())
