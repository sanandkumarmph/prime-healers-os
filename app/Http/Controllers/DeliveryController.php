    private function availableSaleAssets(?Sale $selectedSale = null)
    {
        $selectedAssetIds = collect();

        if ($selectedSale?->asset_id) {
            $selectedAssetIds = collect([(int) $selectedSale->asset_id]);
        }

        return Asset::query()
            ->with(['product', 'warehouse'])
            ->where('organization_id', $this->orgId())
            ->where('asset_stage', Asset::STAGE_NEW_STOCK)
            ->where(function ($query) use ($selectedAssetIds) {
                $query->where('asset_status', 'available_for_sale');

                if ($selectedAssetIds->isNotEmpty()) {
                    $query->orWhereIn('id', $selectedAssetIds->all());
                }
            })
            ->orderBy('serial_number')
            ->get();
    }

    private function validateSaleAssetLink(?Sale $sale, mixed $assetId): ?Asset
    {
        $resolvedAssetId = (int) $assetId;

        if (!$sale || $resolvedAssetId <= 0) {
            return null;
        }

        if ($sale->asset_id && (int) $sale->asset_id !== $resolvedAssetId) {
            throw ValidationException::withMessages([
                'sale_asset_id' => 'This sale already has a linked asset. Change it from the Sales screen if needed.',
            ]);
        }

        if ((int) $sale->quantity !== 1) {
            throw ValidationException::withMessages([
                'sale_asset_id' => 'Serialized asset linking from delivery is supported only when sale quantity is 1.',
            ]);
        }

        $asset = Asset::query()
            ->where('organization_id', $this->orgId())
            ->findOrFail($resolvedAssetId);

        if ((int) $asset->product_id !== (int) $sale->product_id) {
            throw ValidationException::withMessages([
                'sale_asset_id' => 'Selected asset does not belong to this sale product.',
            ]);
        }

        if ($asset->asset_stage !== Asset::STAGE_NEW_STOCK) {
            throw ValidationException::withMessages([
                'sale_asset_id' => 'Only new stock assets can be linked here.',
            ]);
        }

        $isCurrentSaleAsset = (int) ($sale->asset_id ?? 0) === (int) $asset->id;

        if ($asset->asset_status !== 'available_for_sale' && !$isCurrentSaleAsset) {
            throw ValidationException::withMessages([
                'sale_asset_id' => 'Selected asset is not available for sale.',
            ]);
        }

        return $asset;
    }

