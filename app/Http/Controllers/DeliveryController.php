    public function markInProgress(Request $request, Delivery $delivery)
    {
        $delivery = $this->scopedDelivery($delivery);
        $this->authorize('update', $delivery);

        if ($redirect = $this->ensureProofWorkflowRequest($request, $delivery, 'start')) {
            return $redirect;
        }

        if ($delivery->status === 'completed') {
            return redirect()->back()->with('error', ucfirst($delivery->type) . ' is already completed.');
        }

        if ($delivery->status !== 'pending') {
            return redirect()->back()->with('error', 'Only pending ' . $delivery->type . ' tasks can be started.');
        }

        $validated = $this->validateStartWorkflowRequest($request);

        $this->deliveryWorkflowService()->markInProgress(
            $delivery,
            fn (Delivery $activeDelivery) => $this->syncAssignedAssetStatuses($activeDelivery)
        );

        if ($delivery->type === 'pickup' && $this->hasPickupStatusColumn()) {
            $delivery->forceFill([
                'pickup_status' => 'in_progress',
            ])->saveQuietly();
        }

        $this->storeDeliveryWorkflowLocation($delivery, auth()->user(), DeliveryProof::MOMENT_START, $validated);

        ActivityLogger::log('delivery.started', $delivery, [
            'type' => $delivery->type,
            'status' => $delivery->status,
            'location_captured' => filled($validated['location_latitude'] ?? null) && filled($validated['location_longitude'] ?? null),
        ], ucfirst($delivery->type) . ' marked as in progress.');

        return redirect()
            ->to(route('deliveries.show', $delivery) . '#workflow-proof-section')
            ->with('success', ucfirst($delivery->type) . ' marked as in progress.');
    }

    public function markCompleted(Request $request, Delivery $delivery)
    {
        $delivery = $this->scopedDelivery($delivery);
        $this->authorize('update', $delivery);
        $confirmPartial = $request->boolean('confirm_partial');

        if ($redirect = $this->ensureProofWorkflowRequest($request, $delivery, 'complete')) {
            return $redirect;
        }

        if ($delivery->status === 'completed') {
            return redirect()->back()->with('error', ucfirst($delivery->type) . ' is already completed.');
        }

        if ($delivery->status !== 'in_progress') {
            return redirect()->back()->with('error', 'Only in-progress ' . $delivery->type . ' tasks can be completed.');
        }

        if ($delivery->rental_id) {
            $rental = Rental::query()
                ->where('organization_id', $this->orgId())
                ->find($delivery->rental_id);

            if ($rental) {
                $pendingQuantity = $delivery->type === 'delivery'
                    ? $this->overallPendingDeliveryQuantity($rental)
                    : $this->overallPendingPickupQuantity($rental);

                if ($pendingQuantity > 0 && !$confirmPartial) {
                    return redirect()->back()->with('error', 'Pending item quantities remain. Record the delivered/picked-up quantities first, or complete this task as partial.');
                }
            }
        }

        $validated = $this->validateCompletionWorkflowRequest($request, $delivery);

        $workflowRental = null;
        if ($delivery->rental_id) {
            $workflowRental = Rental::query()
                ->where('organization_id', $this->orgId())
                ->find($delivery->rental_id);
        }

        $this->deliveryWorkflowService()->markCompleted(
            $this->orgId(),
            $delivery,
            $workflowRental,
            fn (Delivery $completedDelivery) => $this->syncAssignedAssetStatuses($completedDelivery)
        );

        if ($delivery->type === 'pickup' && $this->hasPickupStatusColumn()) {
            $delivery->forceFill([
                'pickup_status' => 'picked_up',
            ])->saveQuietly();
        }

        $this->storeWorkflowCompletionProofs($delivery, auth()->user(), $validated);

        ActivityLogger::log('delivery.completed', $delivery, [
            'type' => $delivery->type,
            'status' => $delivery->status,
            'completed_at' => optional($delivery->completed_at)->toDateTimeString(),
            'proof_stage' => $delivery->type,
        ], ucfirst($delivery->type) . ' marked as completed.');

        $delivery->loadMissing(['assignedUser', 'rental.customer', 'rental.businessPartner', 'rental.partnerClient', 'sale.customer', 'sale.businessPartner', 'sale.partnerClient']);
        $this->notifications()->notifyDeliveryStatusChange(
            $delivery,
            $this->notifications()->organizationManagers($this->orgId())->merge($delivery->assignedUser ? collect([$delivery->assignedUser]) : collect()),
            $delivery->isPickup() ? 'pickup_completed' : 'delivery_completed',
            ucfirst($delivery->type) . ' completed',
            trim(($delivery->linkedCustomerName() ?: ucfirst($delivery->type) . ' task') . ' completed'),
            'medium'
        );

        return redirect()->back()->with('success', ucfirst($delivery->type) . ' marked as completed.');
    }

    public function cancel(Delivery $delivery)
    {
        $delivery = $this->scopedDelivery($delivery);
        $this->authorize('update', $delivery);

        if ($delivery->status === 'completed') {
            return redirect()->back()->with('error', ucfirst($delivery->type) . ' is already completed and cannot be cancelled.');
        }

        if ($delivery->status === 'cancelled') {
            return redirect()->back()->with('error', ucfirst($delivery->type) . ' is already cancelled.');
        }

        $validated = Validator::make(request()->all(), [
            'cancellation_reason' => ['required', Rule::in(Delivery::CANCELLATION_REASONS)],
            'cancellation_notes' => ['nullable', 'string', 'max:1000'],
        ])->validate();

        $cancelData = [
            'status' => 'cancelled',
            'completed_at' => null,
            'cancellation_reason' => $this->hasCancellationReasonColumn() ? $validated['cancellation_reason'] : null,
            'cancellation_notes' => $this->hasCancellationNotesColumn() ? ($validated['cancellation_notes'] ?? null) : null,
        ];

        if ($delivery->type === 'pickup' && $this->hasPickupStatusColumn()) {
            $cancelData['pickup_status'] = 'cancelled';
        }

        $delivery->update($cancelData);

        $this->syncAssignedAssetStatuses($delivery);

        ActivityLogger::log('delivery.cancelled', $delivery->refresh(), [
            'type' => $delivery->type,
            'status' => $delivery->status,
            'cancellation_reason' => $delivery->cancellation_reason ?? null,
        ], ucfirst($delivery->type) . ' cancelled.');

        $delivery->loadMissing(['assignedUser', 'rental.customer', 'rental.businessPartner', 'rental.partnerClient', 'sale.customer', 'sale.businessPartner', 'sale.partnerClient']);
        $this->notifications()->notifyDeliveryStatusChange(
            $delivery,
            $this->notifications()->organizationManagers($this->orgId())->merge($delivery->assignedUser ? collect([$delivery->assignedUser]) : collect()),
            $delivery->isPickup() ? 'pickup_failed' : 'delivery_failed',
            ucfirst($delivery->type) . ' failed',
            trim(($delivery->linkedCustomerName() ?: ucfirst($delivery->type) . ' task') . ' · ' . Delivery::cancellationReasonLabel($validated['cancellation_reason'])),
            'high'
        );

        if ($delivery->type === 'delivery') {
            app(FollowUpManager::class)->ensureFailedDeliveryFollowUp(
                $delivery->fresh(['rental.customer', 'rental.businessPartner', 'rental.partnerClient', 'sale.customer', 'sale.businessPartner', 'sale.partnerClient']),
                $delivery->cancellation_notes ?: ($delivery->cancellation_reason ? ('Reason: ' . Delivery::cancellationReasonLabel($delivery->cancellation_reason)) : null)
            );
        }

        return redirect()
            ->route('deliveries.show', $delivery)
            ->with('success', ucfirst($delivery->type) . ' cancelled successfully.');
    }

    public function assigned()
    {
        $this->authorize('viewAny', Delivery::class);

        $user = auth()->user();

        $load = [
            'rental.product',
            'rental.rentalItems.product',
            'rental.dispatchWarehouse',
            'rental.customer',
            'sale.product',
            'sale.customer',
            'sale.asset.warehouse',
            'assignedUser',
            'assignedStaff',
        ];

        if ($this->hasRentalAssetsTable()) {
            $load[] = 'rental.activeRentalAssets.asset.warehouse';
        }

        if ($this->hasRentalItemsTable()) {
            $load[] = 'rental.rentalItems.product';
        }

        if ($this->hasRentalSaleItemsTable()) {
            $load[] = 'rental.saleItems.product';
            $load[] = 'rental.saleItems.asset.warehouse';
        }

        $query = $this->applyDeliveryScope(Delivery::with($load))
            ->where('organization_id', $this->orgId())
            ->where('type', 'delivery');

        if ($this->hasDeliveryProofsTable()) {
            $query->withCount('proofs');
        }

        if ($user && $user->hasScope('assigned', 'deliveries')) {
            $query->where('assigned_user_id', $user->id);
        }

        $deliveries = $query->latest()->get();

        return view('deliveries.assigned', compact('deliveries'));
    }

