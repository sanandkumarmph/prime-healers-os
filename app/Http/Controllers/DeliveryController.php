    public function index(Request $request)
    {
        $this->authorize('viewAny', Delivery::class);

        $legacyBoard = strtolower((string) $request->query('board', ''));
        $legacyBoardDefaults = [
            'pending_delivery' => ['tab' => 'deliveries', 'task_type' => 'delivery', 'status' => 'pending'],
            'out_delivery' => ['tab' => 'in_progress', 'task_type' => 'delivery', 'status' => 'in_progress'],
            'completed_delivery' => ['tab' => 'completed', 'task_type' => 'delivery', 'status' => 'completed'],
            'pending_pickup' => ['tab' => 'pickups', 'task_type' => 'pickup', 'status' => 'pending'],
            'out_pickup' => ['tab' => 'in_progress', 'task_type' => 'pickup', 'status' => 'in_progress'],
            'completed_pickup' => ['tab' => 'completed', 'task_type' => 'pickup', 'status' => 'completed'],
        ];

        $legacyDefault = $legacyBoardDefaults[$legacyBoard] ?? [];

        $tab = strtolower((string) $request->query('tab', $legacyDefault['tab'] ?? 'all'));
        $search = trim((string) $request->query('search', ''));
        $selectedDate = trim((string) $request->query('date', ''));
        $taskType = strtolower((string) $request->query('task_type', $legacyDefault['task_type'] ?? ''));
        $staffFilter = trim((string) $request->query('staff', ''));
        $areaFilter = trim((string) $request->query('area', ''));
        $statusFilter = strtolower((string) $request->query('status', $legacyDefault['status'] ?? ''));

        $baseLoad = [
            'rental.product',
            'rental.customer',
            'rental.dispatchWarehouse',
            'sale.product',
            'sale.customer',
            'sale.asset.warehouse',
            'assignedUser',
            'assignedStaff',
        ];

        if ($this->hasRentalItemsTable()) {
            $baseLoad[] = 'rental.rentalItems.product';
        }

        if ($this->hasRentalAssetsTable()) {
            $baseLoad[] = 'rental.activeRentalAssets.asset.warehouse';
        }

        if ($this->hasRentalSaleItemsTable()) {
            $baseLoad[] = 'rental.saleItems.product';
            $baseLoad[] = 'rental.saleItems.asset.warehouse';
        }

        $baseQuery = $this->applyDeliveryScope(
            Delivery::query()->where('organization_id', $this->orgId())
        );

        if ($search !== '') {
            $baseQuery->where(function ($query) use ($search) {
                $query->whereHas('rental', function ($rentalQuery) use ($search) {
                    $rentalQuery->where(function ($rentalInnerQuery) use ($search) {
                        $rentalInnerQuery
                            ->where('customer_name', 'like', "%{$search}%")
                            ->orWhere('phone', 'like', "%{$search}%")
                            ->orWhereHas('customer', function ($customerQuery) use ($search) {
                                $customerQuery
                                    ->where('name', 'like', "%{$search}%")
                                    ->orWhere('phone', 'like', "%{$search}%")
                                    ->orWhere('email', 'like', "%{$search}%");

                                if (Schema::hasColumn('customers', 'whatsapp_number')) {
                                    $customerQuery->orWhere('whatsapp_number', 'like', "%{$search}%");
                                }

                                if (Schema::hasColumn('customers', 'contact_name')) {
                                    $customerQuery->orWhere('contact_name', 'like', "%{$search}%");
                                }
                            });
                    });
                })->orWhereHas('sale', function ($saleQuery) use ($search) {
                    $saleQuery->where(function ($saleInnerQuery) use ($search) {
                        $saleInnerQuery
                            ->where('id', 'like', "%{$search}%")
                            ->orWhereHas('customer', function ($customerQuery) use ($search) {
                                $customerQuery
                                    ->where('name', 'like', "%{$search}%")
                                    ->orWhere('phone', 'like', "%{$search}%")
                                    ->orWhere('email', 'like', "%{$search}%");

                                if (Schema::hasColumn('customers', 'whatsapp_number')) {
                                    $customerQuery->orWhere('whatsapp_number', 'like', "%{$search}%");
                                }

                                if (Schema::hasColumn('customers', 'contact_name')) {
                                    $customerQuery->orWhere('contact_name', 'like', "%{$search}%");
                                }
                            })
                            ->orWhereHas('product', function ($productQuery) use ($search) {
                                $productQuery->where('name', 'like', "%{$search}%");
                            });
                    });
                });
            });
        }

        if ($selectedDate !== '') {
            $baseQuery->whereDate('scheduled_at', $selectedDate);
        }

        if ($staffFilter !== '') {
            if (str_starts_with($staffFilter, 'user:') && $this->hasAssignedUserColumn()) {
                $baseQuery->where('assigned_user_id', (int) substr($staffFilter, 5));
            } elseif (str_starts_with($staffFilter, 'staff:') && $this->hasAssignedStaffColumn()) {
                $baseQuery->where('assigned_staff_id', (int) substr($staffFilter, 6));
            } elseif ($staffFilter === 'third_party' && $this->hasAssignmentTypeColumn()) {
                $baseQuery->where('assignment_type', 'third_party');
            } elseif ($staffFilter === 'unassigned') {
                $baseQuery->where(function ($query) {
                    if ($this->hasAssignedUserColumn()) {
                        $query->whereNull('assigned_user_id');
                    }

                    if ($this->hasAssignedStaffColumn()) {
                        $query->whereNull('assigned_staff_id');
                    }

                    if ($this->hasAssignmentTypeColumn()) {
                        $query->where(function ($innerQuery) {
                            $innerQuery->whereNull('assignment_type')
                                ->orWhere('assignment_type', 'delivery_team');
                        });
                    }
                });
            }
        }

        if ($areaFilter !== '') {
            if (str_starts_with($areaFilter, 'warehouse:')) {
                $warehouseId = (int) substr($areaFilter, 10);
                $baseQuery->where(function ($query) use ($warehouseId) {
                    $query->whereHas('rental', function ($rentalQuery) use ($warehouseId) {
                        $rentalQuery->where('dispatch_warehouse_id', $warehouseId);
                    })->orWhereHas('sale.asset', function ($assetQuery) use ($warehouseId) {
                        $assetQuery->where('warehouse_id', $warehouseId);
                    });
                });
            } elseif (str_starts_with($areaFilter, 'city:')) {
                $city = substr($areaFilter, 5);
                $baseQuery->where(function ($query) use ($city) {
                    $query->whereHas('rental.customer', fn ($customerQuery) => $customerQuery->where('city', $city))
                        ->orWhereHas('sale.customer', fn ($customerQuery) => $customerQuery->where('city', $city));
                });
            }
        }

        $orderedMinimalDeliveryQuery = function ($query) {
            return $query
                ->select([
                    'id',
                    'rental_id',
                    'sale_id',
                    'type',
                    'status',
                    'scheduled_at',
                    'completed_at',
                    'updated_at',
                    'assigned_user_id',
                    'assigned_staff_id',
                    'third_party_name',
                    'assignment_type',
                    'created_at',
                ])
                ->orderByRaw("CASE WHEN status = 'pending' THEN 0 WHEN status = 'in_progress' THEN 1 ELSE 2 END")
                ->orderByRaw("CASE WHEN scheduled_at IS NULL THEN 1 ELSE 0 END")
                ->orderBy('scheduled_at')
                ->orderByDesc('created_at');
        };

        $hydrateDeliveries = function (Collection $deliveryIds) use ($baseLoad): Collection {
            if ($deliveryIds->isEmpty()) {
                return collect();
            }

            $deliveries = Delivery::with($baseLoad)
                ->where('organization_id', $this->orgId())
                ->whereIn('id', $deliveryIds->all())
                ->get()
                ->keyBy('id');

            return $deliveryIds
                ->map(fn ($deliveryId) => $deliveries->get((int) $deliveryId))
                ->filter()
                ->values();
        };

        $summaryDeliveries = $this->dedupeDeliveryCollection(
            $orderedMinimalDeliveryQuery(clone $baseQuery)->get()
        );

        $deliveriesQuery = clone $baseQuery;

        if (in_array($taskType, ['delivery', 'pickup'], true)) {
            $deliveriesQuery->where('type', $taskType);
        }

        if (in_array($statusFilter, ['pending', 'in_progress', 'completed', 'cancelled'], true)) {
            $deliveriesQuery->where('status', $statusFilter);
        }

        $today = now()->toDateString();

        switch ($tab) {
            case 'deliveries':
                $deliveriesQuery->where('type', 'delivery');
                break;
            case 'pickups':
                $deliveriesQuery->where('type', 'pickup');
                break;
            case 'in_progress':
                $deliveriesQuery->where('status', 'in_progress');
                break;
            case 'completed':
                $deliveriesQuery->where('status', 'completed');
                break;
            case 'today':
                $deliveriesQuery->whereDate('scheduled_at', $today);
                break;
            case 'overdue':
                $deliveriesQuery
                    ->whereIn('status', ['pending', 'in_progress'])
                    ->whereDate('scheduled_at', '<', $today);
                break;
            default:
                $tab = 'all';
                break;
        }

        $dedupedTaskIds = $this->dedupeDeliveryCollection(
            $orderedMinimalDeliveryQuery(clone $deliveriesQuery)->get()
        )
            ->pluck('id')
            ->map(fn ($id) => (int) $id)
            ->values();

        $perPage = 20;
        $currentPage = Paginator::resolveCurrentPage('page');
        $pageDeliveryIds = $dedupedTaskIds->forPage($currentPage, $perPage)->values();
        $taskCollection = $hydrateDeliveries($pageDeliveryIds);
        $taskResultsCount = $dedupedTaskIds->count();

        $tasks = new LengthAwarePaginator(
            $taskCollection,
            $taskResultsCount,
            $perPage,
            $currentPage,
            [
                'path' => $request->url(),
                'query' => $request->query(),
                'pageName' => 'page',
            ]
        );

        $totalTasksCount = $summaryDeliveries->count();
        $deliveryTasksCount = $summaryDeliveries->where('type', 'delivery')->count();
        $pickupTasksCount = $summaryDeliveries->where('type', 'pickup')->count();
        $overdueTasksCount = $summaryDeliveries->filter(function (Delivery $delivery) use ($today) {
            return in_array($delivery->status, ['pending', 'in_progress'], true)
                && optional($delivery->scheduled_at)?->toDateString()
                && optional($delivery->scheduled_at)?->toDateString() < $today;
        })->count();
        $completedTodayCount = $summaryDeliveries->filter(function (Delivery $delivery) use ($today) {
            return $delivery->status === 'completed'
                && optional($delivery->completed_at)?->toDateString() === $today;
        })->count();

        $todayTaskCount = $summaryDeliveries->filter(fn (Delivery $delivery) => optional($delivery->scheduled_at)?->toDateString() === $today)->count();
        $todayDeliveryCount = $summaryDeliveries->filter(fn (Delivery $delivery) => $delivery->type === 'delivery' && optional($delivery->scheduled_at)?->toDateString() === $today)->count();
