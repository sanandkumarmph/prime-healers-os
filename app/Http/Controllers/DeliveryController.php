            if (Staff::hasAssignmentRoleColumn()) {
                $query->whereIn('assignment_role', Staff::deliveryPickupAssignmentRoles());
            } else {
                $query->whereIn('role', Staff::deliveryPickupAssignmentRoles());
            }
        });
    }

    private function assignableUsers()
    {
        $allowedRoles = ['delivery', 'pickup'];
        $allowedRoleIds = collect();

        if (Schema::hasColumn('users', 'role_id')) {
            $allowedRoleIds = Role::query()
                ->whereIn('slug', $allowedRoles)
                ->pluck('id');
