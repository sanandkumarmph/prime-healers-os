            'completed_delivery' => ['tab' => 'completed', 'task_type' => 'delivery', 'workflow' => 'completed_delivery'],
            'pending_pickup' => ['tab' => 'pickups', 'task_type' => 'pickup', 'workflow' => 'pending_pickup'],
            'scheduled_pickup' => ['tab' => 'pickups', 'task_type' => 'pickup', 'workflow' => 'scheduled_pickup'],
            'out_pickup' => ['tab' => 'in_progress', 'task_type' => 'pickup', 'workflow' => 'out_pickup'],
            'overdue_pickup' => ['tab' => 'overdue', 'task_type' => 'pickup', 'workflow' => 'overdue_pickup'],
            'completed_pickup' => ['tab' => 'completed', 'task_type' => 'pickup', 'workflow' => 'completed_pickup'],
            'delivery_workload' => ['tab' => 'deliveries', 'task_type' => 'delivery', 'workflow' => 'delivery_workload'],
            'pickup_workload' => ['tab' => 'pickups', 'task_type' => 'pickup', 'workflow' => 'pickup_workload'],
            'live_tasks' => ['tab' => 'all', 'workflow' => 'live'],
            'completed_today' => ['tab' => 'completed', 'status' => 'completed', 'workflow' => 'completed_today'],
        ];

        $legacyDefault = $legacyBoardDefaults[$legacyBoard] ?? [];

        $tab = strtolower((string) $request->query('tab', $legacyDefault['tab'] ?? 'all'));
        $search = trim((string) $request->query('search', ''));
        $selectedDate = trim((string) $request->query('date', ''));
        $taskType = strtolower((string) $request->query('task_type', $legacyDefault['task_type'] ?? ''));
        $staffFilter = trim((string) $request->query('staff', ''));
        $areaFilter = trim((string) $request->query('area', ''));
        $statusFilter = strtolower((string) $request->query('status', $legacyDefault['status'] ?? ''));
        $workflowFilter = strtolower((string) $request->query('workflow', $legacyDefault['workflow'] ?? ''));
        $ownershipFilter = strtolower((string) $request->query('ownership', 'all'));

        if (!in_array($ownershipFilter, ['all', 'my'], true)) {
            $ownershipFilter = 'all';
        }

        $baseLoad = [
            'rental.product',
            'rental.customer',
            'rental.dispatchWarehouse',
            'sale.product',
            'sale.customer',
            'sale.asset.warehouse',
            'assignedUser',
            'assignedStaff',
        ];

        if ($this->hasRentalItemsTable()) {
            $baseLoad[] = 'rental.rentalItems.product';
        }

        if ($this->hasRentalAssetsTable()) {
            $baseLoad[] = 'rental.activeRentalAssets.asset.warehouse';
        }

        if ($this->hasRentalSaleItemsTable()) {
            $baseLoad[] = 'rental.saleItems.product';
            $baseLoad[] = 'rental.saleItems.asset.warehouse';
        }

        $summaryBaseQuery = Delivery::query()->where('organization_id', $this->orgId());
        $baseQuery = clone $summaryBaseQuery;

        if ($ownershipFilter === 'my') {
            $baseQuery = $this->applyDeliveryScope($baseQuery);
        }

        $applySearchFilter = function ($query) use ($search) {
            return $query->where(function ($taskQuery) use ($search) {
                $taskQuery->whereHas('rental', function ($rentalQuery) use ($search) {
                    $rentalQuery->where(function ($rentalInnerQuery) use ($search) {
                        $rentalInnerQuery
                            ->where('customer_name', 'like', "%{$search}%")
                            ->orWhere('phone', 'like', "%{$search}%")
                            ->orWhereHas('customer', function ($customerQuery) use ($search) {
                                $customerQuery
                                    ->where('name', 'like', "%{$search}%")
                                    ->orWhere('phone', 'like', "%{$search}%")
                                    ->orWhere('email', 'like', "%{$search}%");

                                if (Schema::hasColumn('customers', 'whatsapp_number')) {
                                    $customerQuery->orWhere('whatsapp_number', 'like', "%{$search}%");
                                }

                                if (Schema::hasColumn('customers', 'contact_name')) {
                                    $customerQuery->orWhere('contact_name', 'like', "%{$search}%");
                                }
                            });
                    });
                })->orWhereHas('sale', function ($saleQuery) use ($search) {
                    $saleQuery->where(function ($saleInnerQuery) use ($search) {
                        $saleInnerQuery
                            ->where('id', 'like', "%{$search}%")
                            ->orWhereHas('customer', function ($customerQuery) use ($search) {
                                $customerQuery
                                    ->where('name', 'like', "%{$search}%")
                                    ->orWhere('phone', 'like', "%{$search}%")
                                    ->orWhere('email', 'like', "%{$search}%");

                                if (Schema::hasColumn('customers', 'whatsapp_number')) {
                                    $customerQuery->orWhere('whatsapp_number', 'like', "%{$search}%");
                                }

                                if (Schema::hasColumn('customers', 'contact_name')) {
                                    $customerQuery->orWhere('contact_name', 'like', "%{$search}%");
                                }
                            })
                            ->orWhereHas('product', function ($productQuery) use ($search) {
                                $productQuery->where('name', 'like', "%{$search}%");
                            });
                    });
                });
            });
        };

        $applyUnassignedFilter = function ($query) {
            return $query->where(function ($innerQuery) {
                if ($this->hasAssignedUserColumn()) {
                    $innerQuery->whereNull('assigned_user_id');
                }

                if ($this->hasAssignedStaffColumn()) {
                    $innerQuery->whereNull('assigned_staff_id');
                }

                if ($this->hasAssignmentTypeColumn()) {
                    $innerQuery->where(function ($assignmentQuery) {
                        $assignmentQuery->whereNull('assignment_type')
                            ->orWhere('assignment_type', 'delivery_team');
                    });
                }
            });
        };

        $applyWarehouseAreaFilter = function ($query, int $warehouseId) {
            return $query->where(function ($innerQuery) use ($warehouseId) {
                $innerQuery->whereHas('rental', function ($rentalQuery) use ($warehouseId) {
                    $rentalQuery->where('dispatch_warehouse_id', $warehouseId);
                })->orWhereHas('sale.asset', function ($assetQuery) use ($warehouseId) {
                    $assetQuery->where('warehouse_id', $warehouseId);
                });
            });
        };

        $applyCityAreaFilter = function ($query, string $city) {
            return $query->where(function ($innerQuery) use ($city) {
                $innerQuery->whereHas('rental.customer', fn ($customerQuery) => $customerQuery->where('city', $city))
                    ->orWhereHas('sale.customer', fn ($customerQuery) => $customerQuery->where('city', $city));
            });
        };

        if ($search !== '') {
            $applySearchFilter($baseQuery);
            $applySearchFilter($summaryBaseQuery);
        }

        if ($selectedDate !== '') {
            $baseQuery->whereDate('scheduled_at', $selectedDate);
            $summaryBaseQuery->whereDate('scheduled_at', $selectedDate);
        }

        if ($staffFilter !== '') {
            if (str_starts_with($staffFilter, 'user:') && $this->hasAssignedUserColumn()) {
                $baseQuery->where('assigned_user_id', (int) substr($staffFilter, 5));
                $summaryBaseQuery->where('assigned_user_id', (int) substr($staffFilter, 5));
            } elseif (str_starts_with($staffFilter, 'staff:') && $this->hasAssignedStaffColumn()) {
                $baseQuery->where('assigned_staff_id', (int) substr($staffFilter, 6));
                $summaryBaseQuery->where('assigned_staff_id', (int) substr($staffFilter, 6));
            } elseif ($staffFilter === 'third_party' && $this->hasAssignmentTypeColumn()) {
                $baseQuery->where('assignment_type', 'third_party');
                $summaryBaseQuery->where('assignment_type', 'third_party');
            } elseif ($staffFilter === 'unassigned') {
                $applyUnassignedFilter($baseQuery);
                $applyUnassignedFilter($summaryBaseQuery);
            }
        }

        if ($areaFilter !== '') {
            if (str_starts_with($areaFilter, 'warehouse:')) {
                $warehouseId = (int) substr($areaFilter, 10);
                $applyWarehouseAreaFilter($baseQuery, $warehouseId);
                $applyWarehouseAreaFilter($summaryBaseQuery, $warehouseId);
            } elseif (str_starts_with($areaFilter, 'city:')) {
                $city = substr($areaFilter, 5);
                $applyCityAreaFilter($baseQuery, $city);
                $applyCityAreaFilter($summaryBaseQuery, $city);
            }
        }

        $orderedMinimalDeliveryQuery = function ($query) {
            return $query
                ->select([
                    'id',
                    'rental_id',
                    'sale_id',
                    'type',
                    'status',
                    'scheduled_at',
                    'completed_at',
                    'updated_at',
                    'assigned_user_id',
                    'assigned_staff_id',
                    'third_party_name',
                    'assignment_type',
                    'created_at',
                ])
                ->orderByRaw("CASE WHEN status = 'pending' THEN 0 WHEN status = 'in_progress' THEN 1 ELSE 2 END")
                ->orderByRaw("CASE WHEN scheduled_at IS NULL THEN 1 ELSE 0 END")
                ->orderBy('scheduled_at')
                ->orderByDesc('created_at');
        };

        $hydrateDeliveries = function (Collection $deliveryIds) use ($baseLoad): Collection {
            if ($deliveryIds->isEmpty()) {
                return collect();
            }

            $deliveriesQuery = Delivery::with($baseLoad)
                ->where('organization_id', $this->orgId())
                ->whereIn('id', $deliveryIds->all());

            if ($this->hasDeliveryProofsTable()) {
                $deliveriesQuery->withCount('proofs');
            }

            $deliveries = $deliveriesQuery
                ->get()
                ->keyBy('id');

            return $deliveryIds
                ->map(fn ($deliveryId) => $deliveries->get((int) $deliveryId))
                ->filter()
                ->values();
        };

        $deliveriesQuery = clone $baseQuery;
        $summaryQuery = clone $summaryBaseQuery;

        if (in_array($taskType, ['delivery', 'pickup'], true)) {
            $deliveriesQuery->where('type', $taskType);
            $summaryQuery->where('type', $taskType);
        }

        if (in_array($statusFilter, ['pending', 'in_progress', 'completed', 'cancelled'], true)) {
            $deliveriesQuery->where('status', $statusFilter);
            $summaryQuery->where('status', $statusFilter);
        } else {
            $deliveriesQuery->where('status', '!=', 'cancelled');
            $summaryQuery->where('status', '!=', 'cancelled');
        }

        $today = now()->toDateString();

        switch ($tab) {
            case 'deliveries':
                $deliveriesQuery->where('type', 'delivery');
                $summaryQuery->where('type', 'delivery');
                break;
            case 'pickups':
                $deliveriesQuery->where('type', 'pickup');
                $summaryQuery->where('type', 'pickup');
                break;
            case 'in_progress':
                $deliveriesQuery->where('status', 'in_progress');
                $summaryQuery->where('status', 'in_progress');
                break;
            case 'completed':
                $deliveriesQuery->where('status', 'completed');
                $summaryQuery->where('status', 'completed');
                break;
            case 'today':
                $deliveriesQuery->whereDate('scheduled_at', $today);
                $summaryQuery->whereDate('scheduled_at', $today);
                break;
            case 'overdue':
                $deliveriesQuery
                    ->whereIn('status', ['pending', 'in_progress'])
                    ->whereDate('scheduled_at', '<', $today);
                $summaryQuery
                    ->whereIn('status', ['pending', 'in_progress'])
                    ->whereDate('scheduled_at', '<', $today);
                break;
            default:
                $tab = 'all';
                break;
        }

        $dedupedTaskIds = $this->dedupeDeliveryCollection(
            $orderedMinimalDeliveryQuery(clone $deliveriesQuery)->get()
        )
            ->pluck('id')
            ->map(fn ($id) => (int) $id)
            ->values();

        if ($this->logisticsMetrics()->isSupportedWorkflow($workflowFilter)) {
            $dedupedTaskIds = $this->logisticsMetrics()
                ->applyWorkflowFilter($hydrateDeliveries($dedupedTaskIds), $workflowFilter, now()->startOfDay())
                ->pluck('id')
                ->map(fn ($id) => (int) $id)
                ->values();
        }

        $perPage = 20;
        $currentPage = Paginator::resolveCurrentPage('page');
        $pageDeliveryIds = $dedupedTaskIds->forPage($currentPage, $perPage)->values();
        $taskCollection = $hydrateDeliveries($pageDeliveryIds);
        $taskResultsCount = $dedupedTaskIds->count();

        $tasks = new LengthAwarePaginator(
            $taskCollection,
            $taskResultsCount,
            $perPage,
            $currentPage,
            [
                'path' => $request->url(),
                'query' => $request->query(),
                'pageName' => 'page',
            ]
        );

        $summaryTaskIds = $this->dedupeDeliveryCollection(
            $orderedMinimalDeliveryQuery(clone $summaryQuery)->get()
        )
            ->pluck('id')
            ->map(fn ($id) => (int) $id)
            ->values();

        if ($this->logisticsMetrics()->isSupportedWorkflow($workflowFilter)) {
            $summaryTaskIds = $this->logisticsMetrics()
                ->applyWorkflowFilter($hydrateDeliveries($summaryTaskIds), $workflowFilter, now()->startOfDay())
                ->pluck('id')
                ->map(fn ($id) => (int) $id)
                ->values();
        }

        $summaryDeliveries = $hydrateDeliveries($summaryTaskIds);
        $logisticsSummary = $this->logisticsMetrics()->summary($summaryDeliveries, now()->startOfDay());
        $totalTasksCount = (int) ($logisticsSummary['totalTasksCount'] ?? 0);
        $deliveryTasksCount = (int) ($logisticsSummary['deliveryTasksCount'] ?? 0);
        $pickupTasksCount = (int) ($logisticsSummary['pickupTasksCount'] ?? 0);
        $overdueTasksCount = (int) ($logisticsSummary['overdueTasksCount'] ?? 0);
        $completedTodayCount = (int) ($logisticsSummary['completedTodayCount'] ?? 0);
        $pendingDeliveryCount = (int) ($logisticsSummary['pendingDeliveryCount'] ?? 0);
        $scheduledDeliveryCount = (int) ($logisticsSummary['scheduledDeliveryCount'] ?? 0);
        $outForDeliveryCount = (int) ($logisticsSummary['outForDeliveryCount'] ?? 0);
        $overdueDeliveryCount = (int) ($logisticsSummary['overdueDeliveryCount'] ?? 0);
        $completedDeliveryCount = (int) ($logisticsSummary['completedDeliveryCount'] ?? 0);
        $deliveredTodayCount = (int) ($logisticsSummary['deliveredTodayCount'] ?? 0);
        $pendingPickupCount = (int) ($logisticsSummary['pendingPickupCount'] ?? 0);
        $scheduledPickupCount = (int) ($logisticsSummary['scheduledPickupCount'] ?? 0);
        $outForPickupCount = (int) ($logisticsSummary['outForPickupCount'] ?? 0);
        $overduePickupCount = (int) ($logisticsSummary['overduePickupCount'] ?? 0);
        $completedPickupCount = (int) ($logisticsSummary['completedPickupCount'] ?? 0);
        $todayTaskCount = (int) ($logisticsSummary['todayTaskCount'] ?? 0);
        $todayDeliveryCount = (int) ($logisticsSummary['todayDeliveryCount'] ?? 0);
        $todayPickupCount = (int) ($logisticsSummary['todayPickupCount'] ?? 0);
        $pendingCollectionsCount = (int) ($logisticsSummary['pendingCollectionsCount'] ?? 0);

        $todayOverviewTaskIds = collect($logisticsSummary['todayTasks'] ?? collect())
            ->sortBy(fn (Delivery $delivery) => $delivery->scheduled_at?->timestamp ?? PHP_INT_MAX)
            ->take(5)
