    private function applyDeliveryScope($query)
    {
        $user = auth()->user();

        if ($user && $user->hasScope('assigned', 'deliveries') && $this->hasAssignedUserColumn()) {
            $query->where('assigned_user_id', $user->id);
        }

        return $query;
    }

    private function scopedDelivery(Delivery $delivery): Delivery
    {
        abort_if($delivery->organization_id !== $this->orgId(), 403);

        $user = auth()->user();

        if ($user && $user->hasScope('assigned', 'deliveries') && $this->hasAssignedUserColumn()) {
            abort_if((int) $delivery->assigned_user_id !== (int) $user->id, 403);
        }

        return $delivery;
    }

    private function redirectAfterDeliveryMutation(Delivery $delivery, string $message)
    {
        if ($this->hasSaleColumn() && $delivery->sale_id) {
            return redirect()
                ->route('sales.show', $delivery->sale_id)
                ->with('success', $message);
        }

        if ($delivery->rental_id) {
            return redirect()
                ->route('rentals.show', $delivery->rental_id)
                ->with('success', $message);
        }

        return redirect('/deliveries')->with('success', $message);
    }

    private function existingOpenTaskForRental(Rental $rental, string $type, ?int $ignoreDeliveryId = null): ?Delivery
    {
        return Delivery::query()
            ->where('organization_id', $this->orgId())
            ->where('rental_id', $rental->id)
            ->where('type', $type)
            ->whereIn('status', ['pending', 'in_progress'])
            ->when($ignoreDeliveryId, fn ($query) => $query->where('id', '!=', $ignoreDeliveryId))
            ->latest('id')
            ->first();
    }

    private function deliveryDedupKey(Delivery $delivery): string
    {
        if ($delivery->sale_id) {
            return 'sale:' . $delivery->sale_id . ':' . $delivery->type;
        }

        return 'rental:' . ($delivery->rental_id ?? 'none') . ':' . $delivery->type;
    }

    private function dedupeDeliveryCollection($deliveries)
    {
        return $deliveries
            ->sortByDesc('id')
            ->unique(fn (Delivery $delivery) => $this->deliveryDedupKey($delivery))
            ->sort(function (Delivery $a, Delivery $b) {
                $statusRank = ['pending' => 0, 'in_progress' => 1, 'completed' => 2, 'cancelled' => 3];
                $aRank = $statusRank[$a->status] ?? 9;
                $bRank = $statusRank[$b->status] ?? 9;

                if ($aRank !== $bRank) {
                    return $aRank <=> $bRank;
                }

                if (($a->scheduled_at?->timestamp ?? PHP_INT_MAX) !== ($b->scheduled_at?->timestamp ?? PHP_INT_MAX)) {
                    return ($a->scheduled_at?->timestamp ?? PHP_INT_MAX) <=> ($b->scheduled_at?->timestamp ?? PHP_INT_MAX);
                }

                return $b->id <=> $a->id;
            })
            ->values();
    }

    private function pickupTaskNeedsAction(Delivery $delivery): bool
    {
        if ($delivery->type !== 'pickup') {
            return false;
        }

        if ($delivery->sale_id || !$delivery->rental) {
            return in_array($delivery->status, ['pending', 'in_progress'], true);
        }

        return $this->overallPendingPickupQuantity($delivery->rental) > 0;
    }

