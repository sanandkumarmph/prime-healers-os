        ActivityLogger::log('pickup.partial_recorded', $delivery, [
            'rental_item_id' => $item->id,
            'product_id' => $item->product_id,
            'quantity' => $quantity,
            'notes' => $validated['notes'] ?? null,
        ], 'Partial pickup recorded.');

        return redirect()->back()->with('success', 'Partial pickup recorded successfully.');
    }

    public function markInProgress(Delivery $delivery)
    {
        $delivery = $this->scopedDelivery($delivery);
        $this->authorize('update', $delivery);

        if ($delivery->status === 'completed') {
            return redirect()->back()->with('error', ucfirst($delivery->type) . ' is already completed.');
        }

        if ($delivery->status !== 'pending') {
            return redirect()->back()->with('error', 'Only pending ' . $delivery->type . ' tasks can be started.');
        }

        $this->deliveryWorkflowService()->markInProgress(
            $delivery,
            fn (Delivery $activeDelivery) => $this->syncAssignedAssetStatuses($activeDelivery)
        );

        ActivityLogger::log('delivery.started', $delivery, [
            'type' => $delivery->type,
            'status' => $delivery->status,
        ], ucfirst($delivery->type) . ' marked as in progress.');

        return redirect()->back()->with('success', ucfirst($delivery->type) . ' marked as in progress.');
    }

    public function markCompleted(Delivery $delivery)
    {
        $delivery = $this->scopedDelivery($delivery);
        $this->authorize('update', $delivery);
        $confirmPartial = request()->boolean('confirm_partial');

        if ($delivery->status === 'completed') {
            return redirect()->back()->with('error', ucfirst($delivery->type) . ' is already completed.');
        }

        if ($delivery->status !== 'in_progress') {
            return redirect()->back()->with('error', 'Only in-progress ' . $delivery->type . ' tasks can be completed.');
        }

        if ($delivery->rental_id) {
            $rental = Rental::query()
                ->where('organization_id', $this->orgId())
                ->find($delivery->rental_id);

            if ($rental) {
                $pendingQuantity = $delivery->type === 'delivery'
                    ? $this->overallPendingDeliveryQuantity($rental)
                    : $this->overallPendingPickupQuantity($rental);

                if ($pendingQuantity > 0 && !$confirmPartial) {
                    return redirect()->back()->with('error', 'Pending item quantities remain. Record the delivered/picked-up quantities first, or complete this task as partial.');
                }
            }
        }

        $pickupRental = null;
        if ($delivery->type === 'pickup' && $delivery->rental_id) {
            $pickupRental = Rental::query()
                ->where('organization_id', $this->orgId())
                ->find($delivery->rental_id);
        }

        $this->deliveryWorkflowService()->markCompleted(
            $this->orgId(),
            $delivery,
            $pickupRental,
            fn (Delivery $completedDelivery) => $this->syncAssignedAssetStatuses($completedDelivery)
        );

        ActivityLogger::log('delivery.completed', $delivery, [
            'type' => $delivery->type,
            'status' => $delivery->status,
            'completed_at' => optional($delivery->completed_at)->toDateTimeString(),
        ], ucfirst($delivery->type) . ' marked as completed.');

        return redirect()->back()->with('success', ucfirst($delivery->type) . ' marked as completed.');
    }

    public function cancel(Delivery $delivery)
    {
        $delivery = $this->scopedDelivery($delivery);
        $this->authorize('update', $delivery);

        if ($delivery->status === 'completed') {
            return redirect()->back()->with('error', ucfirst($delivery->type) . ' is already completed and cannot be cancelled.');
        }

        if ($delivery->status === 'cancelled') {
            return redirect()->back()->with('error', ucfirst($delivery->type) . ' is already cancelled.');
        }

        $delivery->update([
            'status' => 'cancelled',
            'completed_at' => null,
        ]);

        $this->syncAssignedAssetStatuses($delivery);

        ActivityLogger::log('delivery.cancelled', $delivery->refresh(), [
            'type' => $delivery->type,
            'status' => $delivery->status,
        ], ucfirst($delivery->type) . ' cancelled.');

        return $this->redirectAfterDeliveryMutation($delivery, ucfirst($delivery->type) . ' cancelled successfully.');
    }

    public function assigned()
    {
        $this->authorize('viewAny', Delivery::class);

        $user = auth()->user();

        $load = [
            'rental.product',
            'rental.rentalItems.product',
            'rental.dispatchWarehouse',
            'rental.customer',
            'sale.product',
            'sale.customer',
            'sale.asset.warehouse',
            'assignedUser',
            'assignedStaff',
        ];

        if ($this->hasRentalAssetsTable()) {
            $load[] = 'rental.activeRentalAssets.asset.warehouse';
        }

        if ($this->hasRentalItemsTable()) {
            $load[] = 'rental.rentalItems.product';
        }

        if ($this->hasRentalSaleItemsTable()) {
            $load[] = 'rental.saleItems.product';
            $load[] = 'rental.saleItems.asset.warehouse';
        }

        $query = $this->applyDeliveryScope(Delivery::with($load))
            ->where('organization_id', $this->orgId())
            ->where('type', 'delivery');

        if ($user && $user->hasScope('assigned', 'deliveries')) {
            $query->where('assigned_user_id', $user->id);
        }

        $deliveries = $this->dedupeDeliveryCollection($query->latest()->get());

        return view('deliveries.assigned', compact('deliveries'));
    }

