    public function store(Request $request)
    {
        $this->authorize('create', Delivery::class);

        $validationRules = [
            'rental_id' => array_filter([
                $this->hasSaleColumn() ? 'nullable' : 'required',
                $this->hasSaleColumn() ? 'required_without:sale_id' : null,
                Rule::exists('rentals', 'id')->where(fn ($query) => $query->where('organization_id', $this->orgId())),
            ]),
            'sale_id' => $this->hasSaleColumn()
                ? [
                    'nullable',
                    'required_without:rental_id',
                    Rule::exists('sales', 'id')->where(fn ($query) => $query->where('organization_id', $this->orgId())),
                ]
                : ['prohibited'],
            'type' => 'required|in:delivery,pickup',
            'scheduled_at' => 'nullable|date',
            'status' => 'required|in:pending,in_progress,completed,cancelled',
            'notes' => 'nullable|string',
        ];

        if ($this->hasAssignmentTypeColumn()) {
            $validationRules['assignment_type'] = 'required|in:delivery_team,vendor,third_party';
        }

        if ($this->hasAssignedUserColumn()) {
            $validationRules['assigned_user_id'] = ['nullable', $this->assignableUserRule()];
        }

        if ($this->hasThirdPartyNameColumn()) {
            $validationRules['third_party_name'] = 'nullable|string|max:255';
        }

        if ($this->hasThirdPartyContactColumn()) {
            $validationRules['third_party_contact'] = 'nullable|string|max:255';
        }

        if ($this->hasThirdPartyPhoneColumn()) {
            $validationRules['third_party_phone'] = PhoneNumber::validationRules();
            $validationRules['third_party_phone_country_code'] = 'nullable|string|max:8';
        }

        if ($this->hasAssignedStaffColumn()) {
            $validationRules['assigned_staff_id'] = ['nullable', $this->assignableStaffRule()];
        }

        if ($this->hasSaleColumn()) {
            $validationRules['sale_asset_id'] = [
                'nullable',
                Rule::exists('assets', 'id')->where(fn ($query) => $query->where('organization_id', $this->orgId())),
            ];
        }

        $request->validate($validationRules);

        if ($this->hasSaleColumn() && $request->filled('rental_id') && $request->filled('sale_id')) {
            return back()
                ->withErrors(['sale_id' => 'Choose either a rental or a sale order, not both.'])
                ->withInput();
        }

        $rental = $request->filled('rental_id')
            ? Rental::where('organization_id', $this->orgId())->findOrFail($request->rental_id)
            : null;
        $sale = $request->filled('sale_id')
            ? Sale::where('organization_id', $this->orgId())->findOrFail($request->sale_id)
            : null;

        if ($sale && $this->hasAutoGeneratedRentalSaleColumn() && (bool) ($sale->auto_generated_from_rental ?? false)) {
            return back()->withErrors([
                'sale_id' => 'This sale is managed from the linked rental. Assign delivery from the rental workflow instead.',
            ])->withInput();
        }

        if ($sale && $request->type !== 'delivery') {
            return back()->withErrors(['type' => 'Sales orders can only be assigned for delivery.'])->withInput();
        }

        if ($rental && $request->type === 'pickup' && !$this->deliveredQuantityExists($rental)) {
            return back()->withErrors([
                'type' => 'Pickup can only be assigned after at least one rental item has been delivered.',
            ])->withInput();
        }

        if ($rental && $request->type === 'pickup' && $this->overallPendingPickupQuantity($rental) <= 0) {
            return back()->withErrors([
                'type' => 'All delivered items are already picked up for this rental.',
            ])->withInput();
        }

        if ($rental) {
            $existingTask = $this->existingOpenTaskForRental($rental, $request->type);

            if ($existingTask) {
                return back()->withErrors([
                    'type' => ucfirst($request->type) . ' is already assigned for this rental. Open the existing task instead of creating another one.',
                ])->withInput();
            }
        }

        $linkedSaleAsset = $this->validateSaleAssetLink($sale, $request->input('sale_asset_id'));

        $data = [
            'organization_id' => $this->orgId(),
            'rental_id' => $rental?->id,
            'type' => $request->type,
            'scheduled_at' => $request->scheduled_at,
            'status' => $request->status,
            'notes' => $request->notes,
        ];

        if ($this->hasSaleColumn()) {
            $data['sale_id'] = $sale?->id;
        }

        $assignmentType = $request->input('assignment_type', 'delivery_team');

        if ($this->hasAssignmentTypeColumn()) {
            $data['assignment_type'] = $assignmentType;
        }

        if ($this->hasAssignedUserColumn()) {
            $data['assigned_user_id'] = $assignmentType === 'delivery_team' ? $request->assigned_user_id : null;
        }

        if ($this->hasThirdPartyNameColumn()) {
            $data['third_party_name'] = $assignmentType === 'third_party' ? $request->third_party_name : null;
        }

        if ($this->hasThirdPartyContactColumn()) {
            $data['third_party_contact'] = $assignmentType === 'third_party' ? $request->third_party_contact : null;
        }

        if ($this->hasThirdPartyPhoneColumn()) {
            $data['third_party_phone'] = $assignmentType === 'third_party'
                ? PhoneNumber::normalize($request->third_party_phone, $request->input('third_party_phone_country_code'))
                : null;
        }

        if ($this->hasAssignedStaffColumn()) {
            $data['assigned_staff_id'] = $assignmentType === 'vendor' ? $request->assigned_staff_id : null;
        }

        if ($request->status === 'completed') {
            $data['completed_at'] = now();
        }

        if ($sale && $linkedSaleAsset && !$sale->asset_id) {
            $saleUpdates = ['asset_id' => $linkedSaleAsset->id];

            if (Schema::hasColumn('sales', 'warehouse_id')) {
                $saleUpdates['warehouse_id'] = $linkedSaleAsset->warehouse_id;
            }

            $sale->update($saleUpdates);
        }

        $delivery = Delivery::create($data);

        if ($delivery->type === 'pickup' && $delivery->status === 'completed' && $rental) {
            $this->finalizePickupCompletionForRental($delivery, $rental, optional($delivery->completed_at)->toDateTimeString());
        }

        $this->syncAssignedAssetStatuses($delivery);

        ActivityLogger::log('delivery.assigned', $delivery, [
            'type' => $delivery->type,
            'status' => $delivery->status,
            'assignment_type' => $delivery->assignment_type ?? null,
            'assigned_user_id' => $delivery->assigned_user_id ?? null,
            'assigned_staff_id' => $delivery->assigned_staff_id ?? null,
            'scheduled_at' => optional($delivery->scheduled_at)->toDateTimeString(),
        ], 'Delivery or pickup assignment created.');

        return $this->redirectAfterDeliveryMutation($delivery, 'Delivery/Pickup created successfully.');
    }

