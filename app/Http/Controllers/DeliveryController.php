    public function recordPartialDelivery(Request $request, Delivery $delivery)
    {
        $delivery = $this->scopedDelivery($delivery);
        $this->authorize('update', $delivery);

        if ($delivery->type !== 'delivery' || !$delivery->rental_id) {
            return redirect()->back()->with('error', 'Partial delivery is available only for rental delivery tasks.');
        }

        if (in_array($delivery->status, ['completed', 'cancelled'], true)) {
            return redirect()->back()->with('error', 'This delivery task is already closed.');
        }

        $validated = $request->validate([
            'rental_item_id' => 'required|integer',
            'quantity' => 'required|integer|min:1',
            'notes' => 'nullable|string|max:500',
        ]);

        $rental = Rental::query()
            ->where('organization_id', $this->orgId())
            ->findOrFail($delivery->rental_id);

        $item = $this->resolveRentalProgressItem($rental, (int) $validated['rental_item_id']);
        $quantity = (int) $validated['quantity'];

        if ($quantity > $item->pending_delivery_quantity) {
            throw ValidationException::withMessages([
                'quantity' => 'Delivery quantity cannot exceed the pending delivery quantity.',
            ]);
        }

        $assetIds = $this->nextPendingAssetIdsForDelivery($item, $quantity);

        $this->deliveryWorkflowService()->recordPartialDelivery(
            $this->orgId(),
            $delivery,
            $rental,
            $item,
            $quantity,
            $assetIds,
            $validated['notes'] ?? null,
            fn (Delivery $freshDelivery) => $this->syncAssignedAssetStatuses($freshDelivery),
            function (Delivery $loggedDelivery, array $context): void {
                ActivityLogger::log('delivery.partial_recorded', $loggedDelivery, $context, 'Partial delivery recorded.');
            }
        );

        return redirect()->back()->with('success', 'Partial delivery recorded successfully.');
    }

