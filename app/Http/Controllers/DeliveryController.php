                $this->finalizePickupCompletionForRental($delivery, $rental, optional($delivery->completed_at)->toDateTimeString());
            }
        }

        $load = [
            'rental.product',
            'rental.deliveryRecord',
            'rental.dispatchWarehouse',
            'rental.pickupRecord',
            'sale.product',
            'sale.customer',
            'sale.asset.warehouse',
            'assignedUser',
            'assignedStaff',
        ];

        if ($this->hasRentalAssetsTable()) {
            $load[] = 'rental.activeRentalAssets.asset';
        }

        if ($this->hasRentalSaleItemsTable()) {
            $load[] = 'rental.saleItems.product';
            $load[] = 'rental.saleItems.asset.warehouse';
        }

        if ($this->hasRentalItemsTable()) {
            $load[] = 'rental.rentalItems.product';
        }

        if ($this->hasRentalItemsTable()) {
            $load[] = 'rental.rentalItems.product';
        }

        $delivery->load($load);

        if (!$this->hasRentalAssetsTable() && $delivery->relationLoaded('rental') && $delivery->rental) {
            $delivery->rental->setRelation('activeRentalAssets', collect());
        }

        if (!$this->hasRentalSaleItemsTable() && $delivery->relationLoaded('rental') && $delivery->rental) {
            $delivery->rental->setRelation('saleItems', collect());
        }

        if (!$this->hasRentalItemsTable() && $delivery->relationLoaded('rental') && $delivery->rental) {
            $delivery->rental->setRelation('rentalItems', collect());
        }

        $activityLogs = ActivityLogger::recentFor($delivery);
        $deliveryProofs = $this->hasDeliveryProofsTable()
            ? $delivery->proofs()->with('creator')->latest('captured_at')->latest('id')->get()
            : collect();
        $proofConfig = $this->deliveryProofConfig();
        $cancellationReasonOptions = $this->cancellationReasonOptions();

        return view('deliveries.show', compact('delivery', 'activityLogs', 'deliveryProofs', 'proofConfig', 'cancellationReasonOptions'));
    }

